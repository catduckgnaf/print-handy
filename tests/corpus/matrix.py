"""Expand `[[matrix]]` entries (tests/corpus/matrix.toml) into named, fully specified corpus cases (#824).

One entry spans the axes colors x fit (and a layout, plus an optional `[matrix.printer]` override) and
yields one case per combination, named by `name` with {layout}, {colors} and {fit} filled in. Each case's
expectations are derived, not typed:

  parts, colors, slots   from the color count (one part per color, in the palette order the flow offers)
  plate_mode             "merge" for roomy and tight, "split" for none (the bed cannot hold the model)
  known_failure          the reason of the first [[matrix.known_failure]] rule whose keys all match the
                         case's axes (layout, colors, fit), so an open defect (#820) is linked once and a
                         whole row of cases follows it

The case.toml text this returns is what the generator writes (tests/corpus/make_models.py); the sizes in
its [model] table are resolved from the merge planner when the model is generated (tests/corpus/fit.py).

This module does not import pytest.
"""
from __future__ import annotations

import itertools
import tomllib
from pathlib import Path
from types import SimpleNamespace as S

MATRIX_FILE = Path(__file__).resolve().parent / "matrix.toml"
LAYOUTS = ("assembly", "loose")
FITS = ("roomy", "tight", "none")
MAX_COLORS = 4  # one filament slot each on the corpus printer
LICENSE = "CC0 1.0: generated by tests/corpus/make_models.py, no third party geometry"

# The buttons the color question offers, in slot order, and the color each one means.
BUTTONS = ("White", "Black", "Pink", "Dark green")
# An assembly's bodies: a base and overlays that shrink, as fractions of the fitted footprint.
ASSEMBLY_BODIES = (("Base", 4, (1.0, 1.0)), ("Trim", 1, (0.9, 0.9)),
                   ("Letters", 1, (0.7, 0.7)), ("Dots", 1, (0.5, 0.5)))
LOOSE_HEIGHT = 5
HEADER = "# Generated by tests/corpus/make_models.py from tests/corpus/matrix.toml. Edit the matrix, not this file.\n"


def load(path=MATRIX_FILE):
    """The `[[matrix]]` entries of a matrix file ([] when the file is absent)."""
    path = Path(path)
    if not path.is_file():
        return []
    return tomllib.loads(path.read_text(encoding="utf-8")).get("matrix", [])


def _value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{_value(k)} = {_value(v)}" for k, v in value.items()) + " }"
    raise TypeError(f"cannot write {value!r} as TOML")


def _part_names(layout, colors):
    if layout == "assembly":
        return [name for name, _, _ in ASSEMBLY_BODIES[:colors]]
    return [f"Part {index}" for index in range(1, colors + 1)]


def _model_parts(layout, colors):
    if layout == "assembly":
        return [{"name": name, "extruder": index, "height": height, "footprint": list(footprint)}
                for index, (name, height, footprint) in enumerate(ASSEMBLY_BODIES[:colors], 1)]
    return [{"name": name, "extruder": index, "height": LOOSE_HEIGHT, "footprint": [1.0, 1.0]}
            for index, name in enumerate(_part_names(layout, colors), 1)]


def _known_failure(rules, axes):
    for rule in rules:
        keys = {k: v for k, v in rule.items() if k != "reason"}
        if keys and all(axes.get(k) == v for k, v in keys.items()):
            return str(rule["reason"])
    return None


def _check(entry):
    layout = entry.get("layout")
    if layout not in LAYOUTS:
        raise ValueError(f"matrix layout must be one of {LAYOUTS}, got {layout!r}")
    colors, fits = entry.get("colors", []), entry.get("fit", [])
    if not colors or not fits or "name" not in entry:
        raise ValueError("a matrix entry needs name, colors and fit")
    for count in colors:
        if not 2 <= count <= MAX_COLORS:
            raise ValueError(f"matrix colors must be 2 to {MAX_COLORS} (one filament slot each), got {count}")
    for fit in fits:
        if fit not in FITS:
            raise ValueError(f"matrix fit must be one of {FITS}, got {fit!r}")


def expand(entry):
    """One matrix entry as [S(name, text)]: the case name and the case.toml text it generates."""
    _check(entry)
    layout, rules = entry["layout"], entry.get("known_failure", [])
    cases = []
    for colors, fit in itertools.product(entry["colors"], entry["fit"]):
        name = entry["name"].format(layout=layout, colors=colors, fit=fit)
        names = _part_names(layout, colors)
        reason = _known_failure(rules, {"layout": layout, "colors": colors, "fit": fit})
        lines = [HEADER.rstrip("\n"), f'license = "{LICENSE}"',
                 f'description = "{colors} color {layout} model sized {fit} against the merge planner"']
        if reason:
            lines.append(f"known_failure = {_value(reason)}")
        lines += ["", "[[click]]", 'question = "Choose colors for these parts"', 'button = "Choose colors"', ""]
        for part, button in zip(names, BUTTONS):
            question = f"for {part}," if layout == "assembly" else f'("{part}")'
            lines += ["[[click]]", f"question = {_value(question)}", f'button = "{button}"', ""]
        lines += ["[[click]]", 'question = "How many copies"', 'button = "One copy"', "",
                  "[[click]]", 'question = "·"', 'button = "Slice and print"', "", "[expect]",
                  'status = "STARTED"', f"parts = {_value(names)}", "source_plates = 1",
                  "colors = " + _value({part: button.casefold() for part, button in zip(names, BUTTONS)}),
                  f'plate_mode = "{"split" if fit == "none" else "merge"}"', "gcodes = 1", f"slots = {colors}", ""]
        if entry.get("printer"):
            lines += ["[printer]"] + [f"{k} = {_value(v)}" for k, v in entry["printer"].items()] + [""]
        model = {"layout": layout, "fit": fit}
        if "aspect" in entry:
            model["aspect"] = entry["aspect"]
        lines.append("[model]")
        lines += [f"{k} = {_value(v)}" for k, v in model.items()]
        for part in _model_parts(layout, colors):
            lines += ["", "[[model.part]]"] + [f"{k} = {_value(v)}" for k, v in part.items()]
        cases.append(S(name=name, text="\n".join(lines) + "\n"))
    return cases


def expand_all(entries=None):
    """Every case the matrix file yields, in file order. Duplicate names are an error."""
    cases = [case for entry in (load() if entries is None else entries) for case in expand(entry)]
    names = [case.name for case in cases]
    duplicated = sorted({n for n in names if names.count(n) > 1})
    if duplicated:
        raise ValueError(f"matrix expands to duplicate case names: {duplicated}")
    return cases
