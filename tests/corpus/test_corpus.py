REAL = os.environ.get("PRINT_HANDY_REAL_SLICER") == "1"
PUBLIC_LICENSE = re.compile(
    r"(?:cc0(?:[- ]1\.0(?:\s+universal)?)?"
    r"|cc[- ]by(?:[- ]sa)?(?:[- ]\d+(?:\.\d+)?(?:\s+international)?)?"
    r"|creative commons attribution(?:[- ]sharealike)?"
    r"(?:[- ]\d+(?:\.\d+)?(?:\s+international)?)?"
    r"|own work|mit(?:[- ]license)?"
    r"|apache(?:[- ]license)?(?:[- ,]+(?:version[- ]?)?(?:1\.0|1\.1|2(?:\.0)?))?"
    r"|public domain(?:[- ]dedication)?)", re.I)
# A real user file from a reported incident, published with the repository owner's explicit
# approval recorded on the named issue. Exact form only, so it cannot stand in for a license.
OWNER_APPROVED_INCIDENT = re.compile(r"owner-approved incident file, see #\d+")
PUBLIC_PROVENANCE = re.compile(r"generated by [A-Za-z0-9_./-]+, no third party geometry", re.I)
CASES = [harness.load_case(folder) for folder in harness.case_dirs()]
IDS = [case.name for case in CASES]


def _refused_at_intake(case):
    """A model refused before any question (#194): no clicks, FAILED, nothing started."""
    return not case.clicks and case.expect.get("status") == "FAILED" and case.expect.get("started") is False


def _assert_refused_before_questions(case, run):
    assert not run.slice_starts, run.slice_starts
    assert not [event for event in run.events if event[0] == "prompt"], run.events
    want = case.expect.get("error_contains")
    if want:
        assert want in (run.receipt.get("error") or ""), run.receipt


def _flow_params():
    """Parametrization for the flow tests. A case may declare
    known_failure = "<reason>" in case.toml while a tracked production defect
    is open; its flow tests then xfail (strict, so the marker must be removed
    once the defect is fixed) instead of failing the suite."""
    params = []
    for case in CASES:
        reason = case.data.get("known_failure")
        if reason:
            params.append(pytest.param(case, id=case.name,
                                       marks=pytest.mark.xfail(strict=True, reason=str(reason))))
        else:
            params.append(pytest.param(case, id=case.name))
    return params


def _allows_public_license(value):
    label = str(value).strip()
    if PUBLIC_LICENSE.fullmatch(label) or OWNER_APPROVED_INCIDENT.fullmatch(label):
        return True
    base, separator, annotation = label.partition(":")
    if not separator or not PUBLIC_PROVENANCE.fullmatch(annotation.strip()):
        return False
    return bool(PUBLIC_LICENSE.fullmatch(base.strip()))


def test_the_corpus_covers_formats_and_slicing_scenarios():
    """Pin generated public coverage for formats, colors, plates, scale, and edge meshes."""
    public_cases = [case for case in CASES if not harness.is_private_case(case.dir)]
    public_ids = {case.name for case in public_cases}
    assert len(public_cases) >= 19
    assert sum(case.model.suffix.lower() == ".3mf" for case in public_cases) >= 12
    assert sum(case.model.suffix.lower() == ".stl" for case in public_cases) >= 10
    assert {case.model.suffix.lower() for case in public_cases} <= {".3mf", ".stl"}
    for case in public_cases:
        assert case.model.stat().st_size <= 5 * 1024 * 1024, f"{case.model} exceeds 5 MB"
        assert _allows_public_license(case.data.get("license", "")), case.name
    assert {"single-part", "stl-single-part", "must-shrink", "stl-must-shrink"} <= public_ids
    assert {"stl-needs-supports", "stl-thin-footprint", "stl-ascii", "stl-text-solid-header", "stl-tiny"} <= public_ids
    assert {"parts-one-plate", "plates-multicolor", "needs-supports", "split-plan"} <= public_ids
    assert {"many-parts", "four-colors-one-plate", "five-colors-over-slots", "multiplate-select"} <= public_ids
    assert {"rotation-fit", "unicode-part-extra-plate"} <= public_ids
    assert {"stl-open-thin-wall", "stl-degenerate-zero-volume", "stl-inverted-normals"} <= public_ids
    assert {"duplicate-part-names", "missing-plate-metadata", "copies-multiple-plates"} <= public_ids
    assert {"stl-tall", "stl-very-thin-wall"} <= public_ids
    assert harness.load_case(harness.CASES / "many-parts").expect["parts"] == [f"Part {i}" for i in range(1, 9)]
    assert harness.load_case(harness.CASES / "four-colors-one-plate").expect["slots"] == 4
    assert harness.load_case(harness.CASES / "five-colors-over-slots").expect["slots"] == 4
    assert harness.load_case(harness.CASES / "multiplate-select").expect["plate_mode"] == "split"
    assert harness.load_case(harness.CASES / "must-shrink").expect["scale_range"] == [0.78, 0.84]
    assert harness.load_case(harness.CASES / "rotation-fit").expect["scale"] == 1.0
    assert harness.load_case(harness.CASES / "stl-tiny").expect["source_size_mm"] == [1.5, 1.5, 1.5]


