"""Shared vocabulary, mock generation, and provenance checks for edit corpus journeys.

This module deliberately does not pretend that a resolved plan is a sliced
result. A caller must supply actual G-code from its probe to verify an edit.
In offline mode, `generate_mock_gcode` produces valid G-code toolpaths matching
the requested dimensions, supports, and process settings.
"""
import copy
import json
import re
from pathlib import Path

from print_handy.core import edit_plan, model_job as mj


def resolve_plan(text, job, source=None):
    """Resolve and enrich one unambiguous chat request without mutating job."""
    resolved = edit_plan.resolve_request(text)
    if not resolved or resolved[0] != "plan":
        raise ValueError(f"not an unambiguous edit: {text!r}: {resolved!r}")
    return edit_plan.enrich_plan(resolved[1], job, source)


def verify_probe(plan, before_job, gcode_text):
    """Compare independently produced slicer output to the requested plan."""
    return edit_plan.verify_slice(
        plan,
        gcode_text=gcode_text,
        before_dims=edit_plan.job_dims(before_job)
    )


def generate_mock_gcode(dims=(40.0, 20.0, 10.0), supports=False, support_type="tree",
                        brim_width=0.0, layer_height=0.2, infill_percent=15.0,
                        copies=1, object_name="Cube"):
    """Generate mock G-code with object blocks, configuration block, and toolpaths."""
    lines = [
        "; HEADER_BLOCK_START",
        "; generated by OrcaSlicer 2.4.2",
        "; HEADER_BLOCK_END",
        "; estimated printing time (normal mode) = 30m 0s",
        f"; layer_height = {layer_height}",
        f"; sparse_infill_density = {infill_percent}%",
        f"; brim_width = {brim_width}",
        f"; enable_support = {'1' if supports else '0'}",
        f"; support_type = {support_type}(auto)",
        "G90",
        "M83",
        "G1 X0 Y0 Z0.2 F3000",
    ]
    sx, sy, sz = dims
    for i in range(1, copies + 1):
        name = f"{object_name}_{i}" if copies > 1 else object_name
        lines.append(f"; printing object {name} id:{i} copy {i}")
        lines.append(f"EXCLUDE_OBJECT_START NAME={name}")
        lines.append(f"G1 X0 Y0 Z{sz:.3f} E1.0 F1200")
        lines.append(f"G1 X{sx:.3f} Y0 Z{sz:.3f} E2.0")
        lines.append(f"G1 X{sx:.3f} Y{sy:.3f} Z{sz:.3f} E3.0")
        lines.append(f"G1 X0 Y{sy:.3f} Z{sz:.3f} E4.0")
        lines.append(f"G1 X0 Y0 Z{sz:.3f} E5.0")
        if supports:
            lines.append(";TYPE:Support")
            lines.append("; FEATURE: Support")
            lines.append("G1 X2 Y2 Z0.2 E5.5")
            lines.append("G1 X5 Y5 Z0.2 E6.0")
        lines.append(f"EXCLUDE_OBJECT_END NAME={name}")

    lines.append("M104 S0")
    lines.append("M140 S0")
    lines.append("G28 X Y")
    lines.append("M84")
    return "\n".join(lines) + "\n"


def build_test_job(dest_dir, source_file, title="Test Model",
                   dims=(40.0, 20.0, 10.0), parts=1, color_mode="single_color"):
    """Create a pristine JOB.json in dest_dir for edit pipeline testing."""
    dest_dir = Path(dest_dir)
    dest_dir.mkdir(parents=True, exist_ok=True)
    sx, sy, sz = dims
    job = {
        "title": title,
        "downloaded_file": str(source_file),
        "audit": {
            "plates": 1,
            "size_x": float(sx),
            "size_y": float(sy),
            "size_z": float(sz),
            "parts": int(parts)
        },
        "scale": 1.0,
        "copies": 1,
        "orientation": {},
        "edit_settings": {},
        "edits": [],
        "color_decisions": {"mode": color_mode}
    }
    job_path = dest_dir / "JOB.json"
    job_path.write_text(json.dumps(job, indent=2))
    return job_path, job
