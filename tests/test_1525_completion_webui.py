"""Production wiring for the #1525 completion surfaces.

The tranche G-I library (plate statistics, external intake, U1
feasibility) shipped with no production caller; these tests pin the
callers this PR adds, through the real HTTP server and the real page
modules:

- GET /slice-result/<job>: the result card (thumbnail image, layers,
  estimated time, grams per logical filament and per mapped slot, spool
  suggestions with their confidence) built from the job's own files;
- GET /slice-result/<job>/thumbnail/<n>: the actual embedded PNG;
- GET /u1-feasibility/<job>: the read-only report, unverified wording
  intact;
- the [external_intake] setting (validation + settings catalog) and
  the /external-intake page: config-gated scanning, draft cards, and
  the Mark-as-printed confirmation with exactly-once protection,
  including the refusal when the print id is already in the multislot
  accounting ledger and the never-retry rule for an unconfirmed charge.
"""
