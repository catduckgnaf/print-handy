TOKEN = "completion-1525-token"
SESSION = "completion-1525-session"
FORM = {"Content-Type": "application/x-www-form-urlencoded"}

GCODE_TEXT = ("; generated by OrcaSlicer 2.5.0\n"
              "; total layers: 42\n"
              "; estimated printing time (normal mode) = 1h 2m 3s\n"
              "; total filament used [g] = 12.5\n"
              "; filament used [g] = 10.0, 2.5\n"
              "G1 X1 Y1 E0.1\n")


def _png_bytes():
    buffer = io.BytesIO()
    Image.new("RGB", (48, 48), (200, 30, 30)).save(buffer, format="PNG")
    return buffer.getvalue()


def load_settings(tmp, extra="", environ=None):
    local = Path(tmp) / "local.yaml"
    local.write_text(f"paths:\n  state_home: {tmp}/state\n  archive: {tmp}/archive\n"
                     "webui:\n  enabled: true\n  port: 8765\n" + extra)
    return settings.load(local=local, environ=environ or {})


def start(data, environ=None):
    httpd = server.make_server(data, environ=environ or {}, port=0,
                               snapshot_func=lambda: {})
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    return httpd, httpd.server_address[1]


def call(port, method, path, body=None, headers=None):
    conn = http.client.HTTPConnection("127.0.0.1", port, timeout=20)
    try:
        conn.request(method, path, body=body, headers=headers or {})
        response = conn.getresponse()
        return response.status, dict(response.getheaders()), response.read()
    finally:
        conn.close()


def authed(httpd):
    httpd.sessions[SESSION] = time.time() + 3600
    return {"Cookie": f"{server.SESSION_COOKIE}={SESSION}"}


def make_job(archive, job_id="job1", *, with_source=True):
    job = Path(archive) / job_id
    job.mkdir(parents=True)
    plate = job / "plate_1.gcode.3mf"
    with zipfile.ZipFile(plate, "w") as package:
        package.writestr("3D/3dmodel.model", "<model/>")
        package.writestr("Metadata/plate_1.gcode", GCODE_TEXT)
        package.writestr("Metadata/plate_1.png", _png_bytes())
    payload = {
        "job_id": job_id, "gcode": "plate_1.gcode.3mf", "printer_id": "ad5x",
        "color_manifest": {"filaments": [
            {"source_extruder": 1, "material": "PLA", "color": "#FF0000"},
            {"source_extruder": 2, "material": "PETG", "color": "#00FF00"}]},
        "tool_to_physical_slot": {"1": 2, "2": 1}}
    if with_source:
        from tests.core.test_plate_usage import write_source
        write_source(job / "source.3mf",
                     [(f"part{i}", i + 1, None) for i in range(5)],
                     [[0, 1, 2, 3, 4]])
        payload["source_file"] = "source.3mf"
    (job / "JOB.json").write_text(json.dumps(payload))
    return job


@pytest.fixture
def served(tmp_path, monkeypatch):
    data = load_settings(tmp_path)
    archive = Path(tmp_path) / "archive"
    make_job(archive)
    monkeypatch.setattr(
        spoolman_client, "list_spools",
        lambda: [{"id": 7, "filament": {"material": "PLA", "color_hex": "FF0000"}},
                 {"id": 9, "filament": {"material": "PETG", "color_hex": "00FF00"}}])
    httpd, port = start(data, environ={"WEBUI_ACCESS_TOKEN": TOKEN})
    yield httpd, port, archive
    httpd.shutdown()
    httpd.server_close()


