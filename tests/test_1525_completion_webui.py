def test_external_intake_setting_validates(tmp_path):
    data = load_settings(tmp_path, extra=(
        "external_intake:\n  enabled: true\n  directory: /tmp/watched\n"
        "  max_bytes: 1048576\n"))
    section = data["external_intake"]
    assert section == {"enabled": True, "directory": "/tmp/watched",
                       "max_bytes": 1048576}
    with pytest.raises(settings.SettingsError):
        load_settings(tmp_path, extra="external_intake:\n  max_bytes: 0\n")
    with pytest.raises(settings.SettingsError):
        load_settings(tmp_path, extra="external_intake:\n  enabled: maybe\n")
    default = load_settings(tmp_path)
    assert default["external_intake"]["enabled"] is False


def test_external_intake_fields_are_in_the_settings_catalog():
    from print_handy.webui import catalog
    fields = {(row.section, row.key): row for row in catalog.CATALOG
              if row.section == "external_intake"}
    assert set(fields) == {("external_intake", "enabled"),
                           ("external_intake", "directory"),
                           ("external_intake", "max_bytes")}
    for row in fields.values():
        assert row.validator == "settings external intake check"
        assert row.group == "slicing"
        assert catalog.GROUP_OF[f"external_intake.{row.key}"] == "slicing"
