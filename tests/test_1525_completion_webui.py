# ---------------------------------------------------------------- intake

def intake_settings(tmp_path):
    watched = Path(tmp_path) / "watched"
    watched.mkdir()
    (watched / "benchy.gcode").write_text(GCODE_TEXT)
    data = load_settings(
        tmp_path,
        extra=("external_intake:\n  enabled: true\n"
               f"  directory: {watched}\n"))
    return data, watched


def test_intake_page_scans_only_when_enabled(tmp_path):
    data, _watched = intake_settings(tmp_path)
    cards = external_intake_page.scan_cards(data)
    assert cards == []                       # first sighting: not stable yet
    cards = external_intake_page.scan_cards(data)
    assert len(cards) == 1
    assert cards[0]["status"] == "planned"
    assert cards[0]["source_kind"] == "gcode-only"
    # And with the setting off, a fresh install scans nothing at all.
    off_dir = Path(tmp_path) / "off"
    off_dir.mkdir()
    off = load_settings(off_dir, extra="external_intake:\n  enabled: false\n")
    assert external_intake_page.scan_cards(off) == []


def test_intake_confirm_is_exactly_once(tmp_path):
    data, _watched = intake_settings(tmp_path)
    external_intake_page.scan_cards(data)
    (card,) = external_intake_page.scan_cards(data)
    result = external_intake_page.confirm_card(
        data, sha256=card["sha256"], path=card["path"],
        printer_id="ad5x", print_id="ext-1")
    assert result["identity"] == f"external:{card['sha256']}:ad5x:ext-1"
    assert "no spool was charged" in result["accounting"]["spool_charge"]
    with pytest.raises(ei.IntakeRefused, match="already"):
        external_intake_page.confirm_card(
            data, sha256=card["sha256"], path=card["path"],
            printer_id="ad5x", print_id="ext-1")
    with pytest.raises(ei.IntakeRefused, match="no draft card"):
        external_intake_page.confirm_card(
            data, sha256="0" * 64, path=card["path"],
            printer_id="ad5x", print_id="ext-2")


def test_intake_confirm_charges_through_the_spoolman_use_call(tmp_path, monkeypatch):
    data, _watched = intake_settings(tmp_path)
    external_intake_page.scan_cards(data)
    (card,) = external_intake_page.scan_cards(data)
    calls = []
    monkeypatch.setattr(spoolman_client, "request",
                        lambda *a, **k: calls.append((a, k)) or {})
    result = external_intake_page.confirm_card(
        data, sha256=card["sha256"], path=card["path"], printer_id="ad5x",
        print_id="ext-9", spool_id=7, grams=12.5)
    assert result["accounting"]["spool_charge"] == "spool 7: 12.5 g"
    assert calls[0][0] == ("PUT", "/api/v1/spool/7/use", {"use_weight": 12.5})


def test_intake_unconfirmed_charge_is_never_retried(tmp_path, monkeypatch):
    data, _watched = intake_settings(tmp_path)
    external_intake_page.scan_cards(data)
    (card,) = external_intake_page.scan_cards(data)

    def boom(*a, **k):
        raise RuntimeError("connection lost")

    monkeypatch.setattr(spoolman_client, "request", boom)
    with pytest.raises(ei.IntakeRefused, match="unconfirmed"):
        external_intake_page.confirm_card(
            data, sha256=card["sha256"], path=card["path"], printer_id="ad5x",
            print_id="ext-5", spool_id=7, grams=3.0)
    calls = []
    monkeypatch.setattr(spoolman_client, "request",
                        lambda *a, **k: calls.append((a, k)) or {})
    with pytest.raises(ei.IntakeRefused, match="unconfirmed"):
        external_intake_page.confirm_card(
            data, sha256=card["sha256"], path=card["path"], printer_id="ad5x",
            print_id="ext-5", spool_id=7, grams=3.0)
    assert calls == []                       # the retry never reaches Spoolman


def test_intake_refuses_a_print_id_already_in_the_multislot_ledger(tmp_path, monkeypatch):
    data, _watched = intake_settings(tmp_path)
    external_intake_page.scan_cards(data)
    (card,) = external_intake_page.scan_cards(data)
    monkeypatch.setattr(external_intake_page, "_multislot_ledger_keys",
                        lambda: {"job-77", "job-77#0"})
    with pytest.raises(ei.IntakeRefused, match="already recorded"):
        external_intake_page.confirm_card(
            data, sha256=card["sha256"], path=card["path"],
            printer_id="ad5x", print_id="job-77")


def test_intake_http_flow_records_once(tmp_path):
    data, _watched = intake_settings(tmp_path)
    httpd, port = start(data, environ={"WEBUI_ACCESS_TOKEN": TOKEN})
    try:
        headers = authed(httpd)
        call(port, "GET", "/external-intake", headers=headers)
        code, _h, body = call(port, "GET", "/external-intake", headers=headers)
        text = body.decode()
        assert code == 200 and "benchy.gcode" in text
        token = re.search(r'name="_csrf" value="([^"]+)"', text).group(1)
        form = urlencode({"_csrf": token,
                          "sha256": re.search(r'name="sha256" value="([^"]+)"', text).group(1),
                          "path": re.search(r'name="path" value="([^"]+)"', text).group(1),
                          "printer_id": "ad5x", "print_id": "ext-http-1",
                          "spool_id": "", "grams": ""})
        code, _h, body = call(port, "POST", "/external-intake/confirm",
                              body=form, headers={**headers, **FORM})
        assert code == 200
        assert "Recorded as printed" in body.decode()
        code, _h, body = call(port, "POST", "/external-intake/confirm",
                              body=form, headers={**headers, **FORM})
        assert code == 200
        assert "already" in body.decode()    # the second confirm is refused
    finally:
        httpd.shutdown()
        httpd.server_close()


