"""#1466: MOONRAKER_API_KEY is sent by every Moonraker caller, through one helper.

A fake Moonraker over a real local socket rejects any request that does not
carry ``X-Api-Key: <the configured key>`` with a 401. Stop, pause,
launch-state and purge-mode reads must all succeed against it while the key
is configured, and a 401/403 must surface as an auth failure naming
``MOONRAKER_API_KEY`` — in the doctor, in chat's stop path, and at the purge
launch gate — never as the silent "could not confirm" pass.
"""
import json
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

import pytest

from print_handy import moonraker
from print_handy.core import launch_state, printer_state, purge
from print_handy.runtime import print_control, print_stop

KEY = "test-key-1466"
TOWERLESS = "; generated by OrcaSlicer\nT0\n; enable_prime_tower = 0\nT1\n"


class _FakeMoonraker(BaseHTTPRequestHandler):
    seen = []  # (method, path, key header) for every request

    def log_message(self, *args):  # keep the test log clean
        pass

    def _answer(self):
        type(self).seen.append((self.command, self.path, self.headers.get("X-Api-Key")))
        if self.headers.get("X-Api-Key") != KEY:
            body = b'{"error": "unauthorized"}'
            self.send_response(401)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            return
        if self.path.startswith("/printer/objects/query?save_variables"):
            payload = {"result": {"status": {"save_variables": {"variables": {"use_trash_on_print": 0}}}}}
        elif self.path.startswith("/printer/objects/query"):
            payload = {"result": {"status": {
                "print_stats": {"state": "printing", "filename": "benchy.gcode",
                                "info": {"current_layer": 3, "total_layer": 10},
                                "print_duration": 42.0},
                "virtual_sdcard": {"progress": 0.5, "is_active": True}}}}
        elif self.path.startswith("/server/info"):
            payload = {"result": {"klippy_state": "ready"}}
        else:
            payload = {"result": {}}
        body = json.dumps(payload).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    do_GET = _answer
    do_POST = _answer


@pytest.fixture()
def fake_moonraker():
    _FakeMoonraker.seen = []
    server = ThreadingHTTPServer(("127.0.0.1", 0), _FakeMoonraker)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    yield f"http://127.0.0.1:{server.server_address[1]}"
    server.shutdown()
    server.server_close()


@pytest.fixture()
def with_key(monkeypatch):
    monkeypatch.setenv("MOONRAKER_API_KEY", KEY)


@pytest.fixture()
def without_key(monkeypatch):
    monkeypatch.delenv("MOONRAKER_API_KEY", raising=False)
    # profile_env_value also reads .env files; the test profile has none, but
    # pin the resolver so a developer machine's real key cannot leak in.
    monkeypatch.setattr(moonraker, "_profile_key", lambda: "")


def _paths():
    return [path for _method, path, _key in _FakeMoonraker.seen]


# ---------------------------------------------------------------- stop / pause

def test_stop_sends_the_key_and_reports_stopped(fake_moonraker, with_key, monkeypatch):
    monkeypatch.setattr(print_stop, "BASE", fake_moonraker)
    sent, text = print_stop.cancel("benchy.gcode", wait_s=5, poll_s=0.05)
    # The fake stays "printing" (its one canned status), so the truthful
    # outcome is "cancel sent, still reports printing" — what matters is
    # that every request carried the key and none was refused.
    assert sent is True
    assert "Cancel sent" in text
    assert _paths() and all(key == KEY for _m, _p, key in _FakeMoonraker.seen)
    assert any(p.startswith("/printer/print/cancel") for p in _paths())


def test_pause_sends_the_key(fake_moonraker, with_key, monkeypatch):
    monkeypatch.setattr(print_control, "BASE", fake_moonraker)
    from print_handy import printer_control
    printer_control.for_printer(None).send_pause()
    assert any(p.startswith("/printer/print/pause") for p in _paths())
    assert all(key == KEY for _m, _p, key in _FakeMoonraker.seen)


def test_stop_without_a_key_surfaces_an_auth_failure_in_chat(fake_moonraker, without_key, monkeypatch):
    monkeypatch.setattr(print_stop, "BASE", fake_moonraker)
    sent, text = print_stop.cancel("benchy.gcode", wait_s=5, poll_s=0.05)
    assert sent is False
    assert "MOONRAKER_API_KEY" in text
    assert "Nothing sent" in text


# ---------------------------------------------------------------- launch state

def test_launch_state_clock_read_sends_the_key(fake_moonraker, with_key):
    skew = launch_state.printer_clock_skew(fake_moonraker, timeout=5)
    assert skew is not None and abs(skew) < 120
    assert _FakeMoonraker.seen and all(key == KEY for _m, _p, key in _FakeMoonraker.seen)


def test_launch_state_clock_read_without_a_key_is_unknown_not_zero(fake_moonraker, without_key):
    assert launch_state.printer_clock_skew(fake_moonraker, timeout=5) is None


# ---------------------------------------------------------------- purge mode / gate

def test_purge_mode_read_sends_the_key(fake_moonraker, with_key):
    assert printer_state.read_purge_mode({"moonraker_url": fake_moonraker}) == 0
    assert all(key == KEY for _m, _p, key in _FakeMoonraker.seen)


def test_purge_mode_auth_failure_is_not_folded_into_none(fake_moonraker, without_key):
    with pytest.raises(moonraker.MoonrakerAuthError) as raised:
        printer_state.read_purge_mode({"moonraker_url": fake_moonraker})
    assert "MOONRAKER_API_KEY" in str(raised.value)


def test_purge_gate_refuses_on_an_auth_failure(fake_moonraker, without_key):
    """Test-first for #1466: an auth failure at the purge gate is a refusal
    naming MOONRAKER_API_KEY, never the silent 'could not confirm' pass."""
    said = []
    with pytest.raises(SystemExit) as refused:
        purge.require_launch_safe(TOWERLESS, {"moonraker_url": fake_moonraker}, said.append)
    assert "MOONRAKER_API_KEY" in str(refused.value)
    assert said == []  # no "print went ahead" note was emitted


def test_purge_gate_still_refuses_nopoop_with_the_key(fake_moonraker, with_key):
    with pytest.raises(SystemExit) as refused:
        purge.require_launch_safe(TOWERLESS, {"moonraker_url": fake_moonraker}, lambda *_: None)
    assert "use_trash_on_print=0" in str(refused.value)


# ---------------------------------------------------------------- doctor

def test_doctor_service_check_sends_the_key(fake_moonraker, with_key):
    from print_handy import doctor
    data = {"services": {"moonraker_url": fake_moonraker}}
    assert doctor.check_service(data, "moonraker_url") == fake_moonraker
    assert all(key == KEY for _m, _p, key in _FakeMoonraker.seen)


def test_doctor_service_check_names_the_key_on_auth_failure(fake_moonraker, without_key):
    from print_handy import doctor
    data = {"services": {"moonraker_url": fake_moonraker}}
    with pytest.raises(Exception) as raised:
        doctor.check_service(data, "moonraker_url")
    assert "MOONRAKER_API_KEY" in str(raised.value)


# ---------------------------------------------------------------- helper itself

def test_helper_adds_no_header_when_no_key_is_configured(fake_moonraker, without_key):
    with pytest.raises(moonraker.MoonrakerAuthError):
        moonraker.moonraker_json(fake_moonraker, "/server/info")
    assert _FakeMoonraker.seen[0][2] is None


def test_no_key_install_behaves_as_before_against_an_open_moonraker(monkeypatch):
    """An install without a key talks to an open Moonraker exactly as before:
    no header, plain JSON answers, no auth error."""
    import urllib.request

    class Resp:
        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return False

        def read(self):
            return b'{"result": {"ok": true}}'

    seen = []

    def fake_urlopen(req, timeout=None):
        seen.append(req)
        return Resp()

    monkeypatch.delenv("MOONRAKER_API_KEY", raising=False)
    monkeypatch.setattr(moonraker, "_profile_key", lambda: "")
    monkeypatch.setattr(urllib.request, "urlopen", fake_urlopen)
    assert moonraker.moonraker_json("http://printer.test:7125", "/printer/info") == {"result": {"ok": True}}
    assert seen[0].get_header("X-api-key") is None
