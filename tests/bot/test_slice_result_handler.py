"""/print-slice-result (#1525 completion): the chat slice-result card.

The handler is the chat production caller for core.slice_result: it
answers with the per-plate statistics for an archived job, attaches the
plate's actual thumbnail when the plate carries one, and changes
nothing. These tests drive it through the real handler with a stub
gateway, the way the other handler suites do.
"""
import asyncio
import io
import json
import zipfile
from pathlib import Path
from types import SimpleNamespace as S

import pytest
from PIL import Image

from print_handy.bot import runtime
from print_handy.bot.handlers import common, slice_result
from print_handy.core import model_job

OPERATOR = "200000000000000002"
HOME = "100000000000000001"

GCODE_TEXT = ("; generated by OrcaSlicer 2.5.0\n"
              "; total layers: 42\n"
              "; estimated printing time (normal mode) = 1h 2m 3s\n"
              "; total filament used [g] = 12.5\n"
              "; filament used [g] = 10.0, 2.5\n"
              "G1 X1 Y1 E0.1\n")


def run(coro):
    return asyncio.run(coro)


class Adapter:
    def __init__(self):
        self.sent = []

    async def send(self, chat_id, content, reply_to=None, metadata=None):
        self.sent.append(content)
        return S(success=True)


class Gateway:
    def __init__(self, adapter):
        self._adapter = adapter

    def _is_user_authorized_for_source(self, source):
        return True

    def _delivery_adapter_for(self, source):
        return self._adapter


def event(text="/print-slice-result"):
    source = runtime.make_source(OPERATOR, HOME, platform_name="discord")
    source.profile = common._hosting_profile()
    return S(source=source, text=text, internal=False, metadata={},
             media_urls=[], message_id="m1")


def make_job(archive, job_id="job1"):
    job = Path(archive) / job_id
    job.mkdir(parents=True)
    plate = job / "plate_1.gcode.3mf"
    buffer = io.BytesIO()
    Image.new("RGB", (48, 48), (200, 30, 30)).save(buffer, format="PNG")
    with zipfile.ZipFile(plate, "w") as package:
        package.writestr("3D/3dmodel.model", "<model/>")
        package.writestr("Metadata/plate_1.gcode", GCODE_TEXT)
        package.writestr("Metadata/plate_1.png", buffer.getvalue())
    (job / "JOB.json").write_text(json.dumps({
        "job_id": job_id, "gcode": "plate_1.gcode.3mf", "printer_id": "ad5x",
        "color_manifest": {"filaments": [
            {"source_extruder": 1, "material": "PLA", "color": "#FF0000"},
            {"source_extruder": 2, "material": "PETG", "color": "#00FF00"}]},
        "tool_to_physical_slot": {"1": 2, "2": 1}}))
    return job


@pytest.fixture
def archive(tmp_path, monkeypatch):
    root = tmp_path / "archive"
    root.mkdir()
    make_job(root)
    monkeypatch.setattr(model_job, "ARCHIVE", root)
    monkeypatch.setattr(slice_result, "_state_dir", lambda: tmp_path / "state")
    return root


def test_command_is_registered():
    from print_handy.bot import commands
    assert "print-slice-result" in {row.name for row in commands.COMMANDS}
    assert slice_result.match is not None
    assert slice_result.handle is slice_result.slice_result_dispatch


def test_card_for_the_newest_job_with_thumbnail_attached(archive, tmp_path):
    adapter = Adapter()
    result = run(slice_result.handle(event(), Gateway(adapter)))
    assert result["action"] == "skip"
    (message,) = adapter.sent
    assert "Layers: 42" in message
    assert "Estimated time: 1h 2m 3s" in message
    assert "estimated 10 g" in message and "slot 2" in message
    assert "estimated 2.5 g" in message and "slot 1" in message
    assert "Thumbnail: yes" in message
    marker = "MEDIA:"
    assert marker in message
    attached = Path(message.split(marker)[1].strip())
    assert attached.is_file()
    assert attached.read_bytes().startswith(b"\x89PNG\r\n\x1a\n")


def test_no_job_answers_plainly(archive, tmp_path, monkeypatch):
    empty = tmp_path / "empty"
    empty.mkdir()
    monkeypatch.setattr(model_job, "ARCHIVE", empty)
    adapter = Adapter()
    run(slice_result.handle(event(), Gateway(adapter)))
    (message,) = adapter.sent
    assert "No sliced job matches" in message
    assert "MEDIA:" not in message


def test_unrelated_text_is_not_handled(archive):
    adapter = Adapter()
    source_event = event("/print-status")
    assert run(slice_result.handle(source_event, Gateway(adapter))) is None
    assert adapter.sent == []
