"""Offline tests for the opt-in, user-installed Flash Studio CLI."""
import copy
from pathlib import Path

import pytest

from print_handy import printers, settings
from print_handy.core import orca_adapter as adapter
from .test_orca_adapter import _allow_post, _source, _state


def flashforge_adapter(path=""):
    config = copy.deepcopy(settings.load(local=False, environ={}))
    config.setdefault("slicer", {})["flash_studio_path"] = str(path)
    return printers.get(config["printer"]["model"], config)


def fake_flash_studio(tmp_path, *, missing_help_flag=None, exit_code=0, generated_by="Flash Studio 1.7.19"):
    """A local executable implementing only the CLI contract used by Print Handy."""
    executable = tmp_path / "fake-flash-studio"
    calls = tmp_path / "flash-studio-args.txt"
    flags = ["--load-settings", "--load-filaments", "--arrange", "--orient",
             "--ensure-on-bed", "--allow-newer-file", "--slice", "--outputdir"]
    if missing_help_flag:
        flags.remove(missing_help_flag)
    script = f'''#!/usr/bin/env python3
import pathlib
import sys

args = sys.argv[1:]
if "--help" in args:
    print("Flash Studio headless CLI\\n" + " ".join({flags!r}))
    raise SystemExit(0)
pathlib.Path({str(calls)!r}).write_text("\\n".join(args))
output_dir = pathlib.Path(args[args.index("--outputdir") + 1])
output_dir.mkdir(parents=True, exist_ok=True)
if {exit_code!r} == 0:
    (output_dir / "plate_1.gcode").write_text("; generated by {generated_by}\\nG90\\nG1 X1 Y1 Z0.2\\nEND_PRINT\\n")
raise SystemExit({exit_code!r})
'''
    executable.write_text(script)
    executable.chmod(0o755)
    return executable, calls


def test_unset_path_keeps_the_existing_orca_choice():
    printer = flashforge_adapter()
    assert adapter._flash_studio_command(printer) is None
    assert adapter.slicer_choice(printer) == "orca"


def test_configured_path_is_supported_for_stock_flashforge(tmp_path):
    # P2-76: the stock Flashforge adapter lists flash_studio among its
    # verified slicers, so executable selection must accept the
    # flashforge_stock vendor as well as the ZMod flashforge vendor.
    executable, _calls = fake_flash_studio(tmp_path)
    config = copy.deepcopy(settings.load(local=False, environ={}))
    config["printer"]["model"] = "flashforge_stock.ad5x"
    config.setdefault("slicer", {})["flash_studio_path"] = str(executable)
    printer = printers.get("flashforge_stock.ad5x", config)

    assert adapter._flash_studio_command(printer) == [str(executable.resolve())]


def test_configured_path_is_supported_only_for_flashforge(tmp_path):
    executable, _calls = fake_flash_studio(tmp_path)
    config = copy.deepcopy(settings.load(local=False, environ={}))
    config["slicer"]["flash_studio_path"] = str(executable)
    config["printer"]["model"] = "bambulab.p1s"
    printer = printers.get("bambulab.p1s", config)

    with pytest.raises(RuntimeError, match=r"only supported for Flashforge"):
        adapter._flash_studio_command(printer)


def test_configured_executable_is_invoked_with_verified_flags_and_output(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    executable, calls = fake_flash_studio(tmp_path)
    printer = flashforge_adapter(executable)

    output, provenance, _configs = adapter.slice_model(
        _source(tmp_path), tmp_path / "out", _state(), adapter=printer)

    assert output.is_file()
    assert "; generated by Flash Studio 1.7.19" in output.read_text()
    assert provenance["slicer"] == "Flash Studio"
    assert provenance["generator"] == "Flash Studio 1.7.19"
    assert provenance["fallback"] is None
    args = calls.read_text().splitlines()
    assert "--slice" in args and "--outputdir" in args
    assert str(output.parent) == args[args.index("--outputdir") + 1]


def test_configured_broken_path_fails_before_any_slicer_or_fallback(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    missing = tmp_path / "missing-flash-studio"
    printer = flashforge_adapter(missing)
    invocations = []
    monkeypatch.setattr(adapter.subprocess, "run", lambda *args, **kwargs: invocations.append(args))

    with pytest.raises(RuntimeError, match=r"flash_studio_path.*not an executable file"):
        adapter.slice_model(_source(tmp_path), tmp_path / "out", _state(), adapter=printer)

    assert invocations == []
    assert not list((tmp_path / "out").glob("*.gcode"))


def test_unadvertised_cli_option_fails_closed_before_slice_or_fallback(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    executable, calls = fake_flash_studio(tmp_path, missing_help_flag="--ensure-on-bed")
    printer = flashforge_adapter(executable)

    with pytest.raises(RuntimeError, match=r"does not advertise required headless option.*--ensure-on-bed"):
        adapter.slice_model(_source(tmp_path), tmp_path / "out", _state(), adapter=printer)

    assert not calls.exists()  # help ran; the actual slicing action did not
    assert not list((tmp_path / "out").glob("*.gcode"))


def test_flash_studio_nonzero_exit_does_not_fallback_to_orca_or_bambu(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    executable, calls = fake_flash_studio(tmp_path, exit_code=7)
    printer = flashforge_adapter(executable)
    orca_calls = []
    real_run_slicer = adapter._run_slicer

    def track_slicer(*args, **kwargs):
        if args[1] != "Flash Studio":
            orca_calls.append(args)
        return real_run_slicer(*args, **kwargs)

    monkeypatch.setattr(adapter, "_run_slicer", track_slicer)

    with pytest.raises(RuntimeError, match=r"Flash Studio slicing failed \(7\)"):
        adapter.slice_model(_source(tmp_path), tmp_path / "out", _state(), adapter=printer)

    assert calls.exists()
    assert orca_calls == []
    assert not list((tmp_path / "out").glob("*.gcode"))


def test_flash_studio_refuses_output_claiming_a_different_generator(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    executable, _calls = fake_flash_studio(tmp_path, generated_by="OrcaSlicer 2.3")
    printer = flashforge_adapter(executable)

    with pytest.raises(RuntimeError, match="Flash Studio did not generate recognized G-code"):
        adapter.slice_model(_source(tmp_path), tmp_path / "out", _state(), adapter=printer)


def test_non_executable_configured_path_fails_clearly(tmp_path):
    file = tmp_path / "not-executable"
    file.write_text("not a slicer")
    file.chmod(0o644)

    with pytest.raises(RuntimeError, match=r"flash_studio_path.*not an executable file"):
        adapter._flash_studio_command(flashforge_adapter(file))
