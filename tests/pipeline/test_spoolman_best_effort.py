"""#387: Spoolman must never block slicing or a print.

#235 made printer_state.check() warnings-only, but paths escaped it: the
print-start active-spool sync in model_job raised on a Spoolman lookup
failure and refused the launch, the slice-time derived-plate cross-check
did its own raw urlopen, and every other Spoolman call site had its own
transport and its own failure behaviour. These tests pin the replacement
(the real-socket client behaviour lives in tests/core/test_spoolman_client.py;
here the socket itself is faked at the urlopen seam, the #235 pattern, while
the wrapper's real error handling, logging and notice run):

- slicing succeeds and produces G-code with Spoolman refused, timing out
  or answering 500, on the slot/filament data already on hand, with a
  WARNING in the log and exactly one user line:
  the #390 notice (UNAVAILABLE_NOTICE: what failed, that the print
  continues, and what to check);
- print start and completion with Spoolman down raise nothing, and the
  usage that could not be reported is recorded as pending in the job /
  completion record for later reconciliation.
"""
