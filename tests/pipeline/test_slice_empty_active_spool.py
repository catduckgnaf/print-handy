"""A slot-selected slice must not depend on the active-spool record.

2.3.4 live failure (2026-11-15): the hardware record's ``spool`` was ``{}``
(the state an unassign or a fresh install leaves), the operator picked slot 4,
and ``slice_model`` died on ``state['spool']['density']`` with a bare
``KeyError: 'density'`` that reached chat as PH_SLICING_UNKNOWN. Launch sync
already resolved density as Spoolman filament, else the record, else 1.24;
slicing now does the same.
"""
import json
from pathlib import Path
from types import SimpleNamespace as S

import pytest

from print_handy import printers, settings
from print_handy.core import orca_adapter, slice_guard, spoolman_client

STATE = Path(__file__).parent / 'fixtures' / 'printer_hardware.json'


def _slice_slot_4(tmp_path, monkeypatch, spool, spoolman_answer):
    monkeypatch.setattr(orca_adapter, 'pre_slice', lambda **k: slice_guard.Result())
    monkeypatch.setattr(orca_adapter, 'post_slice', lambda *a, **k: slice_guard.Result())
    monkeypatch.setattr(orca_adapter.sg, 'enforce_approved_baseline', lambda out, **k: slice_guard.Result())
    monkeypatch.setattr(spoolman_client, 'get_spool', lambda spool_id, **k: spoolman_answer)
    monkeypatch.setattr(spoolman_client, 'note_unavailable_once', lambda *a, **k: None)

    def run(command, **_kwargs):
        out = Path(command[command.index('--outputdir') + 1]) / 'plate_1.gcode'
        out.write_text('; generated by OrcaSlicer 2.4.2\nT0\nG90\nG1 X10 Y10 Z0.2 E1\n')
        return S(returncode=0, stdout='', stderr='')
    monkeypatch.setattr(orca_adapter.subprocess, 'run', run)
    state = json.loads(STATE.read_text())
    state['spool'] = spool
    source = tmp_path / 'part.stl'
    source.write_text('solid x\nendsolid x\n')
    folder = tmp_path / 'slice'
    adapter = printers.get('flashforge.ad5x', settings.load(local=False, environ={}))
    orca_adapter.slice_model(source, folder, state, adapter=adapter, filament_slot=4)
    filament = json.loads((folder / 'filament.json').read_text())
    return float(filament['filament_density'][0])


def test_empty_active_spool_slices_on_the_default_density_when_spoolman_is_silent(tmp_path, monkeypatch):
    assert _slice_slot_4(tmp_path, monkeypatch, {}, None) == pytest.approx(1.24)


def test_empty_active_spool_takes_the_slot_spools_density_from_spoolman(tmp_path, monkeypatch):
    answer = {'id': 12, 'filament': {'name': 'Dark Green PLA', 'material': 'PLA', 'density': 1.31}}
    assert _slice_slot_4(tmp_path, monkeypatch, {}, answer) == pytest.approx(1.31)


def test_recorded_density_is_kept_when_spoolman_is_silent(tmp_path, monkeypatch):
    recorded = {'spoolman_id': 10, 'name': 'white', 'material': 'PLA', 'density': 1.27}
    assert _slice_slot_4(tmp_path, monkeypatch, recorded, None) == pytest.approx(1.27)


# The same empty record reached post-slice verification next: "selected spool
# has no material". Verification reads the material from the one slot spool the
# artifact's own map names.
from print_handy.core import printer_state  # noqa: E402

MAPPED = '; hermes_tool_slots = {"0":{"physical_slot":4,"spoolman_id":12}}\nG90\n'


def test_verify_state_takes_the_material_from_the_artifacts_one_slot_spool():
    state = {**json.loads(STATE.read_text()), 'spool': {}}
    filled = printer_state.with_artifact_spool(state, MAPPED)
    assert filled['spool']['material'] == 'PLA'
    # The printer-wide temps_c attests nothing for the slot spool (#1524 review):
    # no spoolman_id link and a material-neutral resolution, so verification
    # resolves the slot spool's own temperatures as slicing did.
    assert 'spoolman_id' not in filled['spool']
    assert filled['temperature_resolution'] == printer_state.ARTIFACT_SPOOL_RESOLUTION
    printer_state._material_temperature_contract(filled)  # no longer refuses
    assert state['spool'] == {}  # the hardware record itself is not rewritten


def test_a_recorded_active_spool_is_never_replaced():
    state = json.loads(STATE.read_text())
    assert printer_state.with_artifact_spool(state, MAPPED) is state


def test_an_artifact_naming_no_single_spool_leaves_the_empty_record_to_refuse():
    state = {**json.loads(STATE.read_text()), 'spool': {}}
    assert printer_state.with_artifact_spool(state, 'G90\n') is state
    with pytest.raises(RuntimeError, match='no material'):
        printer_state._material_temperature_contract(state)


def _petg_slot_4():
    state = {**json.loads(STATE.read_text()), 'spool': {}, 'temperature_resolution': None}
    state['filament_slots'] = {**state['filament_slots'],
                               '4': {**state['filament_slots']['4'], 'material': 'PETG'}}
    return state


def test_verification_expects_the_slot_spools_own_temperatures_not_the_stored_record():
    """#1524 review: a PETG slot job sliced at PETG temps was refused against the PLA seed 210/60."""
    state = _petg_slot_4()
    sliced, _res = printer_state.slice_temperatures(
        {**state, 'spool': {'spoolman_id': 12, 'material': 'PETG'}}, None, lambda sid: None, stored_ok=False)
    filled = printer_state.with_artifact_spool(state, MAPPED)
    expected = printer_state.gcode_temperatures(filled, ['PETG'], lambda sid: None, text=MAPPED)
    assert expected == sliced and expected != {'nozzle': 210, 'bed': 60}
    printer_state._material_temperature_contract(filled)


def test_a_leftover_resolution_for_another_family_does_not_refuse_the_slot_spool():
    state = {**_petg_slot_4(), 'temperature_resolution': {'material_family': 'PLA', 'material': 'PLA',
                                                          'spoolman_id': 10}}
    printer_state._material_temperature_contract(printer_state.with_artifact_spool(state, MAPPED))


def test_a_stock_firmware_artifact_fills_from_the_jobs_selected_slot():
    """No hermes_tool_slots map (stock AD5X): the job's slot names the spool."""
    state = {**json.loads(STATE.read_text()), 'spool': {}}
    filled = printer_state.with_artifact_spool(state, 'G90\n', slot=4)
    assert filled['spool']['material'] == 'PLA'
    assert printer_state.with_artifact_spool(state, 'G90\n', slot=9) is state  # unknown slot: refuse later


def test_a_multi_spool_artifact_fills_from_its_first_tool():
    mapped = ('; hermes_tool_slots = {"0":{"physical_slot":4,"spoolman_id":12},'
              '"1":{"physical_slot":1,"spoolman_id":10}}\n')
    state = {**_petg_slot_4(), 'temperature_resolution': None}
    filled = printer_state.with_artifact_spool(state, mapped)
    assert filled['spool']['material'] == 'PETG'


def test_four_pla_slots_with_their_own_spoolman_temps_resolve_the_jobs_slot():
    """Stock AD5X, four PLA colors, one with its own Spoolman temps: the job's slot decides, not ambiguity."""
    temps = {10: (200, 55), 11: (205, 60), 12: (220, 65), 13: (215, 60)}

    def fetch(sid):
        return {'material': 'PLA', 'settings_extruder_temp': temps[sid][0], 'settings_bed_temp': temps[sid][1]}
    state = {**json.loads(STATE.read_text()), 'spool': {}, 'temperature_resolution': None}
    filled = printer_state.with_artifact_spool(state, 'G90\n', slot=4)
    assert printer_state.gcode_temperatures(filled, ['PLA'], fetch, text='G90\n') == {'nozzle': 220, 'bed': 65}
