"""#1155: the generic remapper on a PrusaSlicer package remaps completely or refuses.

remap_prusa_member permuted a Slic3r_PE.config list only when its length
equalled the mapping's, and only the palette lists: temperatures, cooling,
filament gcode, the role extruders (perimeter, infill, solid infill, wipe
tower) and the wiping-volumes matrix stayed in source order, so the remapped
package printed the right colors with the wrong settings, or the wrong
colors outright. The PrusaSlicer height members were unclassified. These
tests build a PrusaSlicer MMU project in the test (no third-party files) and
pin that it remaps every reference, or refuses by name.
"""
