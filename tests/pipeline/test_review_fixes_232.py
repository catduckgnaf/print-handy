"""Findings from the 2.3.2 release review (2.3.0..main), each pinned."""
from types import SimpleNamespace as S

from print_handy.bot.platform import BasePlatformAdapter
from print_handy.core import nozzle, support_clearance
from tests.pipeline.test_author_settings import bambu_project, prusa_project, sliced_process
from tests.pipeline.test_designed_overhang_1373 import LOWER, _write

# A 30 x 30 mm shelf 0.2 mm over a separate base at Z 10, and the same 0.2 mm gap at the plate.
SHELF_02 = (5, 5, 10.2, 35, 35, 12)
FLOATING_02 = (60, 60, 0.2, 80, 80, 2)


def test_the_first_layer_contact_rule_applies_only_at_the_plate(tmp_path):
    over_part = _write(tmp_path / "over.3mf", [[LOWER], [SHELF_02]])
    report = support_clearance.analyze(over_part, first_layer_mm=0.24)
    assert support_clearance.risky(report)  # two unsupported fine layers, not a squished first layer
    at_plate = _write(tmp_path / "plate.3mf", [[FLOATING_02]])
    assert not support_clearance.risky(support_clearance.analyze(at_plate, first_layer_mm=0.24))


def test_a_turned_pose_does_not_inherit_the_designers_no_supports_exemption(tmp_path):
    src = _write(tmp_path / "one.3mf", [[LOWER, (5, 5, 10.5, 35, 35, 12)]], enable_support="0")
    assert not support_clearance.risky(support_clearance.posed_report(src))
    upside_down = [1, 0, 0, 0, -1, 0, 0, 0, -1]
    turned = support_clearance.posed_report(src, matrix=upside_down)
    assert turned["authored_supports"] is None


def test_a_prusa_projects_first_layer_sets_the_contact_threshold(tmp_path):
    config = "; generated by PrusaSlicer 2.8.1\n; first_layer_height = 0.1\n; layer_height = 0.1\n"
    src = prusa_project(tmp_path / "p.3mf", config)
    assert support_clearance.profile_first_layer_mm(source=str(src)) == 0.1


def test_a_first_layer_edit_reaches_the_slicer_under_orcas_key(tmp_path):
    process, _ = sliced_process(tmp_path, bambu_project(tmp_path / "b.3mf", {"wall_loops": "3"}),
                                edits={"profile": {"initial_layer_height": 0.6}})
    assert process["initial_layer_print_height"] == "0.28"  # clamped to the 0.4 mm nozzle's range
    assert "initial_layer_height" not in process or process.get("initial_layer_height") != "0.6"


def test_anyone_allowed_may_press_stop_on_someone_elses_slice():
    adapter = BasePlatformAdapter.__new__(BasePlatformAdapter)
    adapter.denied, adapter.approvers = set(), set()
    adapter.registry = S(session_key=lambda cid: "discord:chat::111", choices=lambda cid: ["Stop"])
    assert adapter.may_answer_prompt("222", "c") is True
    adapter.registry = S(session_key=lambda cid: "discord:chat::111", choices=lambda cid: ["Black", "White"])
    assert adapter.may_answer_prompt("222", "c") is False


def test_a_project_set_up_for_another_nozzle_is_noted():
    profile = nozzle.get_tuned_nozzle_profile(0.4)
    _l, _f, _r, notes = nozzle.resolve_layer_heights(profile, {"layer_height": "0.1", "nozzle_diameter": ["0.2"]})
    assert any("set up for a 0.2 mm nozzle" in n for n in notes)
    _l, _f, _r, notes = nozzle.resolve_layer_heights(profile, {"layer_height": "0.2", "nozzle_diameter": ["0.4"]})
    assert not notes
