@pytest.mark.real_slicer
def test_real_slicer_prepares_one_layer_without_network(tmp_path):
    with mock.patch.object(job, 'ARCHIVE', tmp_path), \
         mock.patch.object(job, 'request_json', side_effect=AssertionError('network forbidden')):
        output = job.prepare_first_layer(1, 'white', 'PLA', 10)
    text = output.read_text()
    manifest = json.loads((output.parent.parent / 'JOB.json').read_text())
    assert 'generated by OrcaSlicer' in text
    assert text.count(';LAYER_CHANGE') == 1
    assert manifest['gcode_verified'] is False
    assert manifest['provenance']['gcode_sha256'] == job.file_sha256(output)
    assert manifest['filament_selection']['slot'] == 1
    assert job.gcode_motion_bounds(text)['x'][0] >= 0
    assert job.gcode_motion_bounds(text)['x'][1] <= 220


@pytest.mark.parametrize('slot,color,material,spoolman_id,active_spool', [
    (1, 'black', 'PLA', 10, 10),
    (1, 'white', 'PETG', 10, 10),
    (2, 'white', 'PLA', 10, 10),
    (1, 'white', 'PLA', 12, 10),
    (1, 'white', 'PLA', 10, 12),
])
def test_selection_mismatch_refuses_before_slicing(
        tmp_path, offline_hardware, slot, color, material, spoolman_id, active_spool):
    offline_hardware['spool']['spoolman_id'] = active_spool
    from print_handy.core import orca_adapter
    with mock.patch.object(job, 'ARCHIVE', tmp_path), \
         mock.patch.object(orca_adapter, 'slice_model') as slicer, \
         mock.patch.object(job.subprocess, 'run') as run:
        with pytest.raises(ValueError, match='selected filament differs from recorded slot/active spool'):
            job.prepare_first_layer(slot, color, material, spoolman_id)
    run.assert_not_called()
    slicer.assert_not_called()
    assert not (tmp_path / 'ad5x-first-layer-sliced').exists()


