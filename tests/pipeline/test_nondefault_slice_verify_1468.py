"""#1468: a slice for a non-default roster printer must be verified for that printer.

On main at 623aa6bb the single-plate path in jobs/slice.py ran
``_verify_routed`` only when ``adapter.key == printers.current().key`` and
then stamped ``gcode_verified: True`` unconditionally, so a slice for any
roster printer whose model differs from the default printer's model was
recorded as verified when the offline bounds, tool and family checks never
ran on it. ``finalize_multicolor`` in the same file read
``printers.current().native_or_none`` instead of the job's adapter, so a
secondary printer without the ZMod contract could be finalized through
the default printer's contract (and the other way around).

The secondary printer here is a Prusa MK4S (prusalink): its family guard
(printers/prusa/guard.py) refuses Klipper/ZMod start code such as
START_PRINT. The default printer is a Flashforge AD5X.
"""
