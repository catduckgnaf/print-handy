import json
from pathlib import Path

import pytest

from print_handy import printers, settings
from print_handy.core import model_job as model_job
from print_handy.jobs import slice as jobs_slice
from print_handy.jobs.store import _job_adapter

from .test_multicolor_contract import sparse_artifact, state as ad5x_state

SECONDARY = "workshop-prusa"

TWO_PRINTERS = """
discord:
  chat_id: "111"
printers:
  - id: garage-ad5x
    name: Garage AD5X
    model: flashforge.ad5x
    moonraker_url: http://192.168.1.60:7125
  - id: workshop-prusa
    name: Workshop Prusa
    model: prusa.mk4s
    chat_id: "222"
"""

SECONDARY_STATE = {
    "nozzle": {"diameter_mm": 0.4, "type": "brass"},
    "spool": {"material": "PLA", "spoolman_id": 1, "name": "Black", "density": 1.24},
    "temps_c": {"nozzle": 210, "bed": 60},
    "bed_mm": [250, 210],
    "max_print_height_mm": 250,
    "filament_slots": {},
}

# G-code the Prusa family guard refuses: Klipper/ZMod start code
# (START_PRINT) in a file sliced for the Prusa.
FOREIGN_GCODE = (
    "; generated by OrcaSlicer 2.4.2\n"
    "; printer_model = Prusa MK4S\n"
    "; nozzle_diameter = 0.4\n"
    "; filament_type = PLA\n"
    "M140 S60\nM104 S210\n"
    "START_PRINT BED_TEMP=60 EXTRUDER_TEMP=210\n"
    "; MACHINE_START_GCODE_END\n"
    "G90\n;LAYER_CHANGE\n"
    "G1 X10 Y10 Z0.2 E1\nG1 X20 Y20 E2\n"
    "; MACHINE_END_GCODE_START\n"
    "M104 S0\nM140 S0\n"
)

# The same shape without the foreign start code: the guard passes it.
CLEAN_GCODE = (
    "; generated by OrcaSlicer 2.4.2\n"
    "; printer_model = Prusa MK4S\n"
    "; nozzle_diameter = 0.4\n"
    "; filament_type = PLA\n"
    "M140 S60\nM104 S210\n"
    "; MACHINE_START_GCODE_END\n"
    "G90\n;LAYER_CHANGE\n"
    "G1 X10 Y10 Z0.2 E1\nG1 X20 Y20 E2\n"
    "; MACHINE_END_GCODE_START\n"
    "M104 S0\nM140 S0\n"
)


@pytest.fixture
def two_printers(tmp_path, monkeypatch):
    local = tmp_path / "local.yaml"
    local.write_text(TWO_PRINTERS)
    data = settings.load(home=settings.HOME, local=local, environ={})
    assert [entry["id"] for entry in data["printers"]] == ["garage-ad5x", SECONDARY]
    assert printers.current(data).key == "flashforge.ad5x"
    monkeypatch.setattr(settings, "current", lambda: data)
    return data


@pytest.fixture
def secondary_rig(two_printers, monkeypatch):
    """printer_state serving the secondary record, and a checked printer."""
    records = {SECONDARY: SECONDARY_STATE}

    def fake_load(printer_id=None):
        return copy.deepcopy(records.get(printer_id, SECONDARY_STATE))

    monkeypatch.setattr(model_job.printer_state, "load", fake_load)
    monkeypatch.setattr(model_job.printer_state, "check",
                        lambda st=None, **kw: (True, [], {}))
    return records


def _job(tmp_path):
    source = tmp_path / "part.stl"
    source.write_text("solid x\nendsolid x\n")
    job_path = tmp_path / "JOB.json"
    job_path.write_text(json.dumps({
        "downloaded_file": str(source),
        "audit": {"size_x": "10", "size_y": "10", "size_z": "10"},
        "title": "Part",
        "printer_id": SECONDARY,
    }))
    return job_path


def _fake_slice(monkeypatch, text, seen):
    def fake_slice_model(src, folder, st, brim=None, **kw):
        seen.update(kw)
        folder = Path(folder)
        folder.mkdir(parents=True, exist_ok=True)
        out = folder / "plate_1.gcode"
        out.write_text(text)
        return out, {}, []

    monkeypatch.setattr("print_handy.core.orca_adapter.slice_model", fake_slice_model)


def test_secondary_slice_fails_when_the_family_guard_refuses(tmp_path, monkeypatch, secondary_rig):
    seen = {}
    _fake_slice(monkeypatch, FOREIGN_GCODE, seen)
    job_path = _job(tmp_path)
    with pytest.raises(RuntimeError, match="another vendor's start code"):
        model_job.slice_job(job_path)
    # The slicer was handed the job's own (Prusa) adapter, not the default's.
    assert seen.get("adapter") is not None and seen["adapter"].key == "prusa.mk4s"
    saved = json.loads(job_path.read_text())
    # No downloadable artifact is recorded, and nothing is stamped verified.
    assert "gcode" not in saved
    assert saved.get("gcode_verified") is not True


def test_secondary_slice_verifies_and_only_then_stamps_verified(tmp_path, monkeypatch, secondary_rig):
    seen = {}
    _fake_slice(monkeypatch, CLEAN_GCODE, seen)
    job_path = _job(tmp_path)
    out = model_job.slice_job(job_path)
    assert Path(out).name == "plate_1.gcode"
    saved = json.loads(job_path.read_text())
    assert saved["printer_model"] == "prusa.mk4s"
    assert saved["gcode_verified"] is True
    # The full verification marker is written only by _verify_routed after
    # the full verify passes on these bytes: its presence proves the
    # secondary slice really was verified, not merely stamped.
    assert saved.get("gcode_full_verified_sha256")


def test_finalize_multicolor_takes_the_jobs_adapter(two_printers, tmp_path):
    job = {"printer_id": SECONDARY}
    adapter = _job_adapter(job)
    assert adapter.key == "prusa.mk4s" and adapter.native_or_none is None
    assert printers.current().native_or_none is not None  # the default AD5X has the contract
    gcode = tmp_path / "plate_1.gcode"
    gcode.write_text("T0\nG90\n")
    # By adapter and by job alike, the Prusa job finalizes through its own
    # adapter: no native contract, so nothing is inserted.
    assert jobs_slice.finalize_multicolor(gcode, None, {}, {"0": 1}, adapter=adapter) is None
    assert jobs_slice.finalize_multicolor(gcode, None, {}, {"0": 1}, job=job) is None
    assert gcode.read_text() == "T0\nG90\n"


def test_finalize_multicolor_with_the_ad5x_adapter_still_finalizes(two_printers, tmp_path, monkeypatch):
    # The other direction: with the current printer patched to the Prusa
    # (no contract), an AD5X job's adapter still finalizes in full.
    prusa = _job_adapter({"printer_id": SECONDARY})
    monkeypatch.setattr(printers, "current", lambda *a, **k: prusa)
    st = ad5x_state()
    path = tmp_path / "plate.gcode"
    path.write_text(sparse_artifact([0], ["PLA"]))
    result = jobs_slice.finalize_multicolor(path, None, st, {"0": 1},
                                            adapter=_job_adapter({"printer_id": "garage-ad5x"}))
    assert result is not None
    assert path.read_bytes().startswith(b"; MD5:")
    assert model_job.zmod_md5_valid(path)
