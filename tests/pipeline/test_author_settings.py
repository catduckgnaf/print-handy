def prusa_project(path, config=PRUSA_CONFIG):
    vertices, faces = box(20, 20, 10)
    model = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02" '
             'xmlns:slic3rpe="http://schemas.slic3r.org/3mf/2017/06">',
             '<metadata name="slic3rpe:Version3mf">1</metadata>', '<resources>',
             '<object id="1" name="Block" type="model"><mesh><vertices>']
    model += [f'<vertex x="{x + 50:.4f}" y="{y + 50:.4f}" z="{z:.4f}"/>' for x, y, z in vertices]
    model.append('</vertices><triangles>')
    model += [f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in faces]
    model += ['</triangles></mesh></object>', '</resources><build><item objectid="1"/></build></model>']
    _write_package(path, {"3D/3dmodel.model": "\n".join(model), "Metadata/Slic3r_PE.config": config})
    return path


def bambu_project(path, project, paint=None, extra=None):
    """A one-part Bambu/Orca project; paint=(attribute, code) paints every triangle; extra adds members."""
    write_3mf(path, [("Block", 1, box(20, 20, 10), (60, 60))], [("Plate 1", [0])], [("#FFFFFF", "PLA")],
              project_extra=project)
    with zipfile.ZipFile(path) as archive:
        entries = {info.filename: archive.read(info) for info in archive.infolist()}
    if paint:
        entries["3D/3dmodel.model"] = entries["3D/3dmodel.model"].replace(
            b'<triangle ', f'<triangle {paint[0]}="{paint[1]}" '.encode())
    entries.update(extra or {})
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in entries.items():
            archive.writestr(name, data)
    return path


def fake_slice(cmd, **kwargs):
    folder = Path(cmd[cmd.index("--outputdir") + 1])
    (folder / "plate_1.gcode").write_text("; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2\n"
                                          "; HEADER_BLOCK_END\nT0\nG90\n")
    return type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})()


def sliced_process(tmp_path, source, **kwargs):
    """The process profile slice_model hands Orca for this source (whole-model route), plus provenance."""
    state = copy.deepcopy(model_job.printer_state.load())
    with patch.object(orca_adapter.subprocess, "run", side_effect=fake_slice):
        _out, provenance, configs = orca_adapter.slice_model(source, tmp_path / "out", state, **kwargs)
    return json.loads(Path(configs[1]).read_text()), provenance


