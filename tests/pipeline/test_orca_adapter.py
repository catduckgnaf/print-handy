def _flex_retry_run(captured):
    """Fake slicer for the -100 path: the first Orca run is rejected with
    return_code -100 (thin features under Classic walls), the retry succeeds.
    Every invocation's process config is captured as Orca would receive it."""
    def run(command, **kwargs):
        process = Path(command[command.index('--load-settings') + 1].split(';')[1])
        captured.append(json.loads(process.read_text()))
        folder = Path(kwargs['cwd'])
        if len(captured) == 1:
            (folder / 'result.json').write_text(json.dumps(
                {'return_code': -100, 'error_string': 'Failed slicing the model.'}))
            return type('R', (), {'returncode': 1, 'stdout': '', 'stderr': ''})()
        (folder / 'plate_1.gcode').write_text(
            '; generated by OrcaSlicer 2.4.2\nG90\nG1 X1 Y1 Z0.2\nEND_PRINT\n')
        return type('R', (), {'returncode': 0, 'stdout': '', 'stderr': ''})()
    return run


def test_flex_retry_preserves_explicit_supports_and_brim_policy(tmp_path, monkeypatch):
    # P2-65: the -100 flex retry must not silently drop the operator's resolved
    # supports/brim: slice_job enables supports for orientations that need them,
    # and a retry that removed them would approve an unsupported print.
    _allow_post(monkeypatch)
    captured = []
    monkeypatch.setattr(adapter.subprocess, 'run', _flex_retry_run(captured))
    output, provenance, _configs = adapter.slice_model(
        _source(tmp_path), tmp_path / 'out', _state(), supports=True,
        brim_policy={'type': 'outer_only', 'width_mm': 5})
    assert output.is_file()
    assert len(captured) == 2  # the rejected run and the flex retry
    first, retry = captured
    assert first['enable_support'] == '1' and first['brim_type'] == 'outer_only'
    assert first['brim_width'] == '5'
    assert retry['wall_generator'] == 'arachne'  # the flex profile did apply
    assert retry['enable_support'] == '1'
    assert retry['brim_type'] == 'outer_only' and retry['brim_width'] == '5'
    assert provenance['geometry']['thin_feature_profile'].startswith('arachne flex')


