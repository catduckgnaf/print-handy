def test_designer_support_placement_keys_carry_over_the_template(tmp_path, monkeypatch):
    """#275: a MakerWorld profile's support_threshold_angle (and its neighbours) override the template's 30."""
    import zipfile
    source = tmp_path / 'designer.3mf'
    with zipfile.ZipFile(source, 'w') as archive:
        archive.writestr('3D/3dmodel.model', '<model/>')
        archive.writestr('Metadata/project_settings.config', json.dumps({
            'layer_height': '0.24', 'wall_loops': '2', 'sparse_infill_density': '5%',
            'enable_support': '1', 'support_type': 'tree(auto)', 'support_threshold_angle': '35',
            'support_style': 'tree_slim', 'support_critical_regions_only': '1',
            'support_remove_small_overhang': '0', 'support_filament': '3', 'support_top_z_distance': '0.1'}))
    template = json.loads((adapter.TEMPLATES / 'process.json').read_text())
    assert template['support_threshold_angle'] == '30'  # the value the sliced G-code reported in #275
    seen = {}

    def run(command, **_kwargs):
        process = Path(command[command.index('--load-settings') + 1].split(';')[1])
        seen.update(json.loads(process.read_text()))
        out = Path(command[command.index('--outputdir') + 1]) / 'plate_1.gcode'
        out.write_text('; generated by OrcaSlicer 2.4.2\nG90\n')
        return type('R', (), {'returncode': 0, 'stdout': '', 'stderr': ''})()

    monkeypatch.setattr(adapter.subprocess, 'run', run)
    monkeypatch.setattr(adapter, 'finalize_zmod', lambda *_args: None)
    state = job.printer_state.load()
    state = {**state, 'spool': {**state['spool'], 'color_code': 'F7E6DE'}}
    state['filament_slots'] = {'1': {'spoolman_id': state['spool']['spoolman_id'], 'material': state['spool']['material'],
                                'physical_color_verified': True}}
    _out, provenance, _ = adapter.slice_model(source, tmp_path / 'out', state, preserve_layout=True)
    assert seen['support_threshold_angle'] == '35' and seen['enable_support'] == '1'
    assert seen['support_type'] == 'tree(auto)' and seen['support_style'] == 'tree_slim'
    assert seen['support_critical_regions_only'] == '1' and seen['support_remove_small_overhang'] == '0'
    assert seen['wall_loops'] == '2' and seen['sparse_infill_density'] == '5%'
    # Material and Z-gap calibration stay the printer template's.
    assert seen['support_filament'] == template['support_filament']
    assert seen['support_top_z_distance'] == template['support_top_z_distance']
    assert provenance['author_process']['support_threshold_angle'] == '35'


