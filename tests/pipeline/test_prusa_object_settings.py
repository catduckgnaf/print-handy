def test_multicolor_export_carries_cutter_settings(tmp_path):
    src = two_color_modifier_source(tmp_path / "mod.3mf")
    manifest = source_colors.inventory(src)
    state = model_job.printer_state.load()
    choices = {}
    for part in manifest["parts"]:
        slot = part["source_extruder"]
        choices["part:" + part["key"]] = model_job.resolve_filament_selection(
            state, dict(state["filament_slots"][str(slot)], slot=slot))
    decisions = {"schema": "part_slots_v1", "mode": "per_part", "source_sha256": manifest["source_sha256"],
                 "choices": choices}
    out = tmp_path / "geometry.3mf"
    export_color_geometry(src, out, decisions)
    modifier, subtype = _part_meta(out, "dense zone")
    assert subtype == "modifier_part"
    assert modifier["sparse_infill_density"] == "80%" and modifier["seam_position"] == "random"
    assert "nozzle_temperature" not in modifier


# --- derived plates: the Prusa members are rewritten ----------------------------------------------

def _fake_orca_capture(captured):
    def run(cmd, **kwargs):
        with zipfile.ZipFile(cmd[-1]) as archive:
            captured["names"] = archive.namelist()
            for name in captured["names"]:
                if name.endswith(".config"):
                    captured[name] = archive.read(name)
        folder = Path(cmd[cmd.index("--outputdir") + 1])
        (folder / "plate_1.gcode").write_text("; generated by OrcaSlicer 2.4.2\nT0\n")
        return type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})()
    return run


def _spool_patch():
    import io
    import urllib.request
    spool = io.BytesIO(json.dumps({"archived": False, "filament": {"material": "PLA"}}).encode())
    return patch.object(urllib.request, "urlopen", return_value=spool)


def test_derived_plate_from_a_prusa_project_is_rewritten(tmp_path):
    src = prusa_object_source(tmp_path / "prusa.3mf")
    state = model_job.printer_state.load()
    manifest = source_colors.inventory(src)
    white = model_job.resolve_filament_selection(state, dict(state["filament_slots"]["1"], slot=1))
    decisions = {"schema": "part_slots_v1", "mode": "per_part", "source_sha256": manifest["source_sha256"],
                 "choices": {row["key"]: white for row in source_colors.canonical_prompts(manifest)}}
    keys = [part["key"] for part in manifest["parts"] if part["source_extruder"] == 1]
    plate = tmp_path / "plate.3mf"
    export_single_color_plate(src, plate, decisions, keys, slot_colors=state["filament_slots"])
    with zipfile.ZipFile(plate) as archive:  # the plate itself is still the author's package
        assert "Metadata/Slic3r_PE.config" in archive.namelist()
    captured = {}
    with patch.object(orca_adapter.subprocess, "run", side_effect=_fake_orca_capture(captured)), _spool_patch():
        orca_adapter.slice_model(plate, tmp_path / "out", state, preserve_layout=True, filament_slot=1)
    # The private copy Orca read: the Prusa members are gone, replaced by Orca config files.
    assert "Metadata/Slic3r_PE.config" not in captured["names"]
    assert "Metadata/Slic3r_PE_model.config" not in captured["names"]
    project = json.loads(captured["Metadata/project_settings.config"])
    template_machine = json.loads((Path(orca_adapter.TEMPLATES) / "machine.json").read_text())
    assert project["printer_model"] == template_machine["printer_model"]
    assert "PRUSA FOREIGN START" not in project["machine_start_gcode"]
    assert project["wall_loops"] == "4"  # the project-level Prusa setting, translated and kept
    root = ET.fromstring(captured["Metadata/model_settings.config"])
    meta = {}
    for obj in root.findall("object"):
        for part in obj.findall("part"):
            meta[part.get("id")] = {m.get("key"): m.get("value") for m in part.findall("metadata")}
    assert meta["2"]["wall_loops"] == "5" and meta["3"]["wall_loops"] == "5"
    assert meta["3"]["sparse_infill_density"] == "80%"
    assert meta["3"]["extruder"] == "1"  # a one-filament plate: every volume on the plate's filament


def test_whole_model_slice_of_a_prusa_project_keeps_per_object_settings(tmp_path):
    src = prusa_object_source(tmp_path / "prusa.3mf")
    captured = {}
    state = model_job.printer_state.load()
    with patch.object(orca_adapter.subprocess, "run", side_effect=_fake_orca_capture(captured)), _spool_patch():
        orca_adapter.slice_model(src, tmp_path / "out", state, filament_slot=1)
    root = ET.fromstring(captured["Metadata/model_settings.config"])
    meta = {}
    for obj in root.findall("object"):
        for part in obj.findall("part"):
            entries = {m.get("key"): m.get("value") for m in part.findall("metadata")}
            meta[entries.get("name")] = entries
    assert meta["Widget"]["wall_loops"] == "5"
    assert meta["Insert"]["wall_loops"] == "5"
    assert meta["Insert"]["sparse_infill_density"] == "80%"
