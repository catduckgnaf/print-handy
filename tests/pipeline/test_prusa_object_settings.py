def test_volume_plate_export_carries_per_volume_settings(tmp_path):
    src = bambu_modifier_source(tmp_path / "mod.3mf")
    out = tmp_path / "geometry.3mf"
    export_geometry(src, out)  # the cutter path: a rebuilt single-filament 3MF
    body, _ = _part_meta(out, "main")
    assert body["wall_loops"] == "6"
    modifier, subtype = _part_meta(out, "dense zone")
    assert subtype == "modifier_part"
