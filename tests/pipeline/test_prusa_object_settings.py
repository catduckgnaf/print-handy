def prusa_object_source(path):
    """A two-volume PrusaSlicer project: per-object walls, a denser second volume, MMU extruders."""
    return _package(path, _two_mesh_model(), {
        "Metadata/Slic3r_PE.config": PRUSA_CONFIG,
        "Metadata/Slic3r_PE_model.config": PRUSA_MODEL_CONFIG})


def bambu_modifier_source(path):
    """One object: a body volume with its own wall count plus a modifier volume carrying
    per-volume settings (kept, not-kept and Orca-invalid entries side by side)."""
    settings_xml = ('<?xml version="1.0" encoding="UTF-8"?><config><object id="1">'
                    '<metadata key="name" value="assembly"/><metadata key="extruder" value="1"/>'
                    '<part id="2" subtype="normal_part"><metadata key="name" value="main"/>'
                    '<metadata key="extruder" value="1"/><metadata key="wall_loops" value="6"/></part>'
                    '<part id="3" subtype="modifier_part"><metadata key="name" value="dense zone"/>'
                    '<metadata key="extruder" value="1"/><metadata key="sparse_infill_density" value="80%"/>'
                    '<metadata key="seam_position" value="random"/>'
                    '<metadata key="nozzle_temperature" value="250"/>'
                    '<metadata key="top_surface_pattern" value="not-a-pattern"/></part>'
                    '</object></config>')
    model = ('<?xml version="1.0" encoding="UTF-8"?>'
             f'<model unit="millimeter" xmlns="{NS}"><resources>'
             f'<object id="2" name="main" type="model">{_mesh_xml(_box(40, 40, 10))}</object>'
             f'<object id="3" name="dense zone" type="model">{_mesh_xml(_box(10, 10, 12, (5, 5, 0)))}</object>'
             '<object id="1" name="assembly" type="model"><components>'
             '<component objectid="2" transform="1 0 0 0 1 0 0 0 1 0 0 0"/>'
             '<component objectid="3" transform="1 0 0 0 1 0 0 0 1 0 0 0"/>'
             '</components></object>'
             '</resources><build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 0 0 0"/></build></model>')
    return _package(path, model, {"Metadata/model_settings.config": settings_xml,
                                  "Metadata/project_settings.config": json.dumps(
                                      {"filament_colour": ["#FFFFFF"], "filament_type": ["PLA"]})})


def _part_meta(package, name):
    """The metadata of the part called `name` in a rebuilt export (ids are reassigned)."""
    with zipfile.ZipFile(package) as archive:
        root = ET.fromstring(archive.read("Metadata/model_settings.config"))
    for obj in root.findall("object"):
        for part in obj.findall("part"):
            meta = {m.get("key"): m.get("value") for m in part.findall("metadata")}
            if meta.get("name") == name:
                return meta, part.get("subtype")
    raise AssertionError(f"no part named {name} in {package}")


