"""Per-object author settings (#867, closing the gaps batch 1 of #867 left named):

- PrusaSlicer per-object settings (Metadata/Slic3r_PE_model.config) are carried: translated to Orca
  names, attached to the inventoried parts (extruder assignment included), kept by the rebuilt
  exports, and rewritten into model_settings.config when a derived plate is adopted.
- A derived plate's own copy of Slic3r_PE.config is rewritten like the rest of the project
  settings: the plate Orca reads carries project_settings.config with the job's profile, and the
  Prusa members are gone.
- Rebuilt exports keep every volume's kept per-volume settings, modifier volumes included;
  keys outside the kept set and values Orca rejects are dropped (#867 gap: modifier volumes kept
  their geometry but lost their per-volume settings).

Offline: Orca is faked where a slice runs; the configs and the private 3MF copy are read back.
"""
