def test_prusa_model_config_parses_objects_and_volumes(tmp_path):
    parsed = author_settings.parse_prusa_model(PRUSA_MODEL_CONFIG.encode())
    obj = parsed["1"]
    assert obj["extruder"] == 1
    assert obj["settings"] == {"wall_loops": "5"}  # Prusa "perimeters", translated
    assert obj["volumes"][0]["extruder"] == 1 and obj["volumes"][0]["settings"] == {}
    insert = obj["volumes"][1]
    assert insert["extruder"] == 2
    # fill_density translated; wipe_tower_x has no Orca author-intent translation and is dropped.
    assert insert["settings"] == {"sparse_infill_density": "80%"}


def test_inventory_carries_prusa_per_object_settings_and_extruders(tmp_path):
    manifest = source_colors.inventory(prusa_object_source(tmp_path / "prusa.3mf"))
    parts = {p["name"]: p for p in manifest["parts"]}
    assert parts["Widget"]["source_extruder"] == 1
    assert parts["Widget"]["settings"] == {"wall_loops": "5"}
    assert parts["Insert"]["source_extruder"] == 2
    assert parts["Insert"]["settings"] == {"wall_loops": "5", "sparse_infill_density": "80%"}
    assert [f["source_extruder"] for f in manifest["filaments"]] == [1, 2]


