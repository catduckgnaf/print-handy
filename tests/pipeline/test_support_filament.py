"""A project's dedicated support filament is kept (#867, ForgeBridge 1.1.4 rule).

The author named a filament for the supports (support_filament / support_interface_filament in a
Bambu/Orca project, support_material_extruder in a PrusaSlicer one) that no part prints with.
Intake asks about it like any other source color (the #870 height-change pattern), the chosen
spool is loaded as a tool of the job, and the slice points Orca's support filament at it.
Derived one-filament plates keep the job's own filament (test_foreign_project_adoption).

Offline: Orca is faked; the process profile and filament profiles Orca would get are read back.
"""
import io
import json
import urllib.request
import zipfile
from pathlib import Path
from unittest.mock import patch

import pytest

from print_handy import printers
from print_handy.core import model_job, orca_adapter, source_colors
from tests.corpus.make_models import box, write_3mf
from tests.pipeline.test_multi_tool_intake import creator_config, tool_state

PALETTE = [("#FFFFFF", "PLA"), ("#067749", "PLA")]


def support_source(path, **project):
    """Two parts on filament 1; filament 2 exists only as the designated support filament."""
    base = {"enable_support": "1", "support_filament": "2", "support_interface_filament": "2",
            "filament_colour": ["#FFFFFF", "#067749"], "filament_type": ["PLA", "PLA"]}
    base.update(project)
    write_3mf(path, [("Base", 1, box(30, 30, 10), (60, 60)), ("Cap", 1, box(20, 20, 8), (110, 110))],
              [("Plate 1", [0, 1])], PALETTE, project_extra=base)
    return path


def decisions_for(manifest, state, picks):
    """picks: {prompt key: IFS/toolhead slot}. Builds a validated per-part decision."""
    choices = {}
    for row in source_colors.canonical_prompts(manifest):
        slot = picks[row["key"]]
        record = model_job.resolve_filament_selection(state, dict(state["filament_slots"][str(slot)], slot=slot))
        choices[row["key"]] = record
    return {"schema": "part_slots_v1", "mode": "per_part", "source_sha256": manifest["source_sha256"],
            "choices": choices}


def fake_slice(captured):
    def run(cmd, **kwargs):
        captured["cmd"] = cmd
        folder = Path(cmd[cmd.index("--outputdir") + 1])
        (folder / "plate_1.gcode").write_text("; generated by OrcaSlicer 2.4.2\nT0\n")
        return type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})()
    return run


def slice_offline(tmp_path, source, state, decisions=None, adapter=None, **kwargs):
    captured = {}
    spool = io.BytesIO(json.dumps({"archived": False, "filament": {"material": "PLA"}}).encode())
    with patch.object(orca_adapter.subprocess, "run", side_effect=fake_slice(captured)), \
            patch.object(urllib.request, "urlopen", return_value=spool):
        out, provenance, configs = orca_adapter.slice_model(
            source, tmp_path / "out", state, color_decisions=decisions, adapter=adapter, **kwargs)
    process = json.loads(Path(configs[1]).read_text())
    # configs is [machine, process, filament] + filament_paths, and filament_paths
    # itself starts with that same base filament file: the loaded profiles in
    # order are the base plus everything after the duplicate.
    filaments = [json.loads(Path(configs[2]).read_text())] + \
                [json.loads(Path(p).read_text()) for p in configs[4:]]
    return provenance, process, filaments


def test_inventory_records_the_designated_support_filament(tmp_path):
    manifest = source_colors.inventory(support_source(tmp_path / "s.3mf"))
    assert manifest["support_filaments"] == {"base": 2, "interface": 2}
    plain = source_colors.inventory(support_source(tmp_path / "p.3mf", support_filament="0",
                                                   support_interface_filament="0"))
    assert "support_filaments" not in plain  # 0 names the object's own filament: no designation


def test_inventory_records_a_prusa_support_extruder(tmp_path):
    from tests.pipeline.test_prusa_object_settings import prusa_object_source, PRUSA_CONFIG
    src = prusa_object_source(tmp_path / "prusa.3mf")
    with zipfile.ZipFile(src) as archive:
        entries = {info.filename: archive.read(info) for info in archive.infolist()}
    entries["Metadata/Slic3r_PE.config"] = (PRUSA_CONFIG + "; support_material_extruder = 2\n").encode()
    with zipfile.ZipFile(src, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in entries.items():
            archive.writestr(name, data)
    manifest = source_colors.inventory(src)
    assert manifest["support_filaments"] == {"base": 2, "interface": None}


def test_intake_asks_about_the_support_filament(tmp_path):
    manifest = source_colors.inventory(support_source(tmp_path / "s.3mf"))
    rows = {row["key"]: row for row in source_colors.canonical_prompts(manifest)}
    assert "filament:2" in rows and "support" in rows["filament:2"]["question"]
    assert len(source_colors.distinct_source_colours(manifest)) == 2


def test_a_decision_that_skips_the_support_question_is_refused(tmp_path):
    src = support_source(tmp_path / "s.3mf")
    manifest = source_colors.inventory(src)
    state = model_job.printer_state.load()
    picks = {row["key"]: 1 for row in source_colors.canonical_prompts(manifest)}
    full = decisions_for(manifest, state, picks)
    broken = {"schema": "part_slots_v1", "mode": "per_part", "source_sha256": manifest["source_sha256"],
              "choices": {k: v for k, v in full["choices"].items() if k != "filament:2"}}
    with pytest.raises(ValueError):
        source_colors.validate_decisions(manifest, broken, state, model_job.resolve_filament_selection)


def test_support_spool_is_loaded_and_pointed_at(tmp_path):
    src = support_source(tmp_path / "s.3mf")
    manifest = source_colors.inventory(src)
    state = model_job.printer_state.load()
    picks = {row["key"]: (3 if row["key"] == "filament:2" else 1)
             for row in source_colors.canonical_prompts(manifest)}
    provenance, process, filaments = slice_offline(tmp_path, src, state, decisions_for(manifest, state, picks))
    # Loaded order is the sorted picked slots [1, 3]: the parts' tool is 0, the support tool is 1.
    assert provenance["tool_mapping"] == {"0": 1, "1": 3}
    assert process["support_filament"] == "2" and process["support_interface_filament"] == "2"
    assert len(filaments) == 2
    assert filaments[1]["filament_colour"] == ["#000000"]  # slot 3's spool, loaded for the supports


def test_support_pointing_at_a_part_filament_needs_no_extra_tool(tmp_path):
    src = support_source(tmp_path / "s.3mf")
    manifest = source_colors.inventory(src)
    state = model_job.printer_state.load()
    picks = {row["key"]: 1 for row in source_colors.canonical_prompts(manifest)}
    provenance, process, filaments = slice_offline(tmp_path, src, state, decisions_for(manifest, state, picks))
    assert provenance["tool_mapping"] == {"0": 1}
    assert process["support_filament"] == "1" and len(filaments) == 1


def test_no_support_tool_is_loaded_when_supports_are_off(tmp_path):
    src = support_source(tmp_path / "s.3mf")
    manifest = source_colors.inventory(src)
    state = model_job.printer_state.load()
    picks = {row["key"]: (3 if row["key"] == "filament:2" else 1)
             for row in source_colors.canonical_prompts(manifest)}
    provenance, process, filaments = slice_offline(
        tmp_path, src, state, decisions_for(manifest, state, picks), supports=False)
    assert provenance["tool_mapping"] == {"0": 1}
    assert process["support_filament"] == "0" and len(filaments) == 1


def test_support_filament_on_a_creator_toolhead(tmp_path):
    src = support_source(tmp_path / "s.3mf")
    manifest = source_colors.inventory(src)
    state = tool_state()
    picks = {row["key"]: (4 if row["key"] == "filament:2" else 1)
             for row in source_colors.canonical_prompts(manifest)}
    adapter = printers.get("flashforge.creator5", creator_config("flashforge.creator5"))
    provenance, process, filaments = slice_offline(
        tmp_path, src, state, decisions_for(manifest, state, picks), adapter=adapter)
    assert provenance["tool_mapping"] == {"0": 1, "3": 4}
    assert process["support_filament"] == "4" and process["support_interface_filament"] == "4"


def test_support_designated_to_a_part_extruder_is_still_asked_and_pointed(tmp_path):
    # Regression (Codex, #876): the designation names a source extruder a part
    # also prints with. The support question is still asked in its own right,
    # and the pointer follows the support answer — not the part's spool.
    src = tmp_path / "covered.3mf"
    palette = [("#FFFFFF", "PLA"), ("#067749", "PLA"), ("#FF0000", "PLA")]
    write_3mf(src, [("Base", 1, box(30, 30, 10), (60, 60)), ("Cap", 2, box(20, 20, 8), (110, 110))],
              [("Plate 1", [0, 1])], palette,
              project_extra={"enable_support": "1", "support_filament": "1",
                             "support_interface_filament": "0"})
    state = model_job.printer_state.load()
    manifest = source_colors.inventory(src)
    rows = source_colors.canonical_prompts(manifest)
    support_rows = [r for r in rows if r["key"] == "filament:1" and "support filament" in r["question"]]
    assert len(support_rows) == 1
    picks = {}
    for row in rows:
        if row["key"] == "filament:1":
            picks[row["key"]] = 3  # the supports get their own spool, not Base's
        elif row["source_extruder"] == 1:
            picks[row["key"]] = 1
        else:
            picks[row["key"]] = 2
    decisions = decisions_for(manifest, state, picks)
    _provenance, process, filaments = slice_offline(tmp_path, src, state, decisions)
    assert process["support_filament"] == "3"
    assert len(filaments) == 3
