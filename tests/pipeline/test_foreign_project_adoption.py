"""A derived plate (route (c)) slices with the job's Flashforge values, not its source's foreign profile (#868).

export_single_color_plate copies the source package byte for byte, so a Bambu project's
project_settings.config (speeds, accelerations, start G-code, Supertack bed, printer model) and its
per-object overrides reach Orca with the plate. slice_model rewrites the private copy from the job's
own machine/process/filament profile before Orca reads it (orca_adapter.adopt_job_settings). These
tests read that copy at the moment Orca is called. tests/slicer/test_derived_plate_real.py reads the
same values back from a real Orca G-code header.
"""
import copy
import io
import json
import re
import urllib.request
import zipfile
from pathlib import Path
from unittest.mock import patch

from print_handy.core import model_job, orca_adapter, source_colors
from print_handy.core.color_geometry import export_single_color_plate
from tests.corpus.make_models import box, write_3mf

STATE = Path(__file__).parent / "fixtures" / "printer_hardware.json"
PALETTE = [("#FFFFFF", "PLA"), ("#067749", "PLA")]
BAMBU_START = "M1002 judge_flag g29_before_print_flag\nG28\nM1002 gcode_claim_action : 2\n"
FOREIGN = {
    "printer_model": "Bambu Lab X1 Carbon", "printer_settings_id": "Bambu Lab X1 Carbon 0.4 nozzle",
    "print_settings_id": "0.20mm Standard @BBL X1C", "inherits": "0.20mm Standard @BBL X1C",
    "different_settings_to_system": ["outer_wall_speed;sparse_infill_pattern", "", "", ""],
    "machine_start_gcode": BAMBU_START, "machine_end_gcode": "M1002 end\n",
    "curr_bed_type": "Supertack Plate", "supertack_plate_temp": ["35", "35"],
    "outer_wall_speed": "300", "inner_wall_speed": "450", "bridge_speed": "5",
    "default_acceleration": "10000", "outer_wall_acceleration": "5000", "default_jerk": "9",
    "machine_max_acceleration_x": ["20000", "20000"], "travel_speed": "700",
    "support_filament": "2", "support_interface_filament": "2", "enable_prime_tower": "1",
    "sparse_infill_pattern": "gyroid", "seam_position": "back", "wall_loops": "3",
}


def foreign_source(path, project=FOREIGN):
    """Two boxes on filaments 1 and 2 in a Bambu X1C project, with per-object and per-plate overrides."""
    write_3mf(path, [("Base", 1, box(30, 30, 10), (60, 60)), ("Cap", 2, box(20, 20, 8), (110, 110))],
              [("Plate 1", [0, 1])], PALETTE, project_extra=project)
    with zipfile.ZipFile(path) as archive:
        entries = {info.filename: archive.read(info) for info in archive.infolist()}
    settings = entries["Metadata/model_settings.config"].decode()
    # Object 1: a foreign speed, a kept author key and an enum value Orca does not know.
    settings = settings.replace(
        '<object id="1"><metadata key="name" value="Base"/>',
        '<object id="1"><metadata key="name" value="Base"/><metadata key="outer_wall_speed" value="400"/>'
        '<metadata key="sparse_infill_density" value="30%"/><metadata key="support_style" value="tree_organic"/>', 1)
    settings = settings.replace('<plate><metadata key="plater_id" value="1"/>',
                                '<plate><metadata key="plater_id" value="1"/>'
                                '<metadata key="curr_bed_type" value="Supertack Plate"/>', 1)
    entries["Metadata/model_settings.config"] = settings.encode()
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in entries.items():
            archive.writestr(name, data)
    return path


def derived_plate(tmp_path, source):
    state = json.loads(STATE.read_text())
    manifest = source_colors.inventory(source)
    white = model_job.resolve_filament_selection(state, dict(state["filament_slots"]["1"], slot=1))
    decisions = {"schema": "part_slots_v1", "mode": "per_part", "source_sha256": manifest["source_sha256"],
                 "choices": {row["key"]: white for row in source_colors.canonical_prompts(manifest)}}
    keys = [part["key"] for part in manifest["parts"] if part["source_extruder"] == 1]
    plate = tmp_path / "slot1.3mf"
    export_single_color_plate(source, plate, decisions, keys, slot_colors=state["filament_slots"])
    return plate


def slice_capture(tmp_path, plate):
    """slice_model on the plate (route (c)); returns (what Orca read, provenance, job configs)."""
    seen = {}

    def run(cmd, **kwargs):
        private = Path(cmd[-1])
        with zipfile.ZipFile(private) as archive:
            seen.update({name: archive.read(name) for name in archive.namelist()})
        out = Path(cmd[cmd.index("--outputdir") + 1])
        (out / "plate_1.gcode").write_text("; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2\n"
                                           "; HEADER_BLOCK_END\nT0\nG90\n")
        return type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})()

    state = copy.deepcopy(model_job.printer_state.load())
    slot = state["filament_slots"]["1"]
    spool = io.BytesIO(json.dumps({"archived": False, "filament": {"material": slot["material"]}}).encode())
    with patch.object(orca_adapter.subprocess, "run", side_effect=run), \
            patch.object(urllib.request, "urlopen", return_value=spool):
        _out, provenance, configs = orca_adapter.slice_model(plate, tmp_path / "out", state,
                                                             preserve_layout=True, filament_slot=1)
    job = {}
    for path in configs[:3]:
        job.update(json.loads(Path(path).read_text()))
    return seen, provenance, job


def test_derived_plate_reaches_orca_with_the_job_profile_not_the_foreign_one(tmp_path):
    plate = derived_plate(tmp_path, foreign_source(tmp_path / "bambu.3mf"))
    with zipfile.ZipFile(plate) as archive:  # the leak: the plate still carries the X1C profile
        assert json.loads(archive.read("Metadata/project_settings.config"))["outer_wall_speed"] == "300"
    seen, provenance, job = slice_capture(tmp_path, plate)
    project = json.loads(seen["Metadata/project_settings.config"])
    # Machine, motion and bed: the job's values.
    for key in ("printer_model", "printer_settings_id", "print_settings_id", "machine_start_gcode",
                "machine_end_gcode", "outer_wall_speed", "inner_wall_speed", "default_acceleration",
                "outer_wall_acceleration", "travel_speed", "enable_prime_tower", "support_filament",
                "support_interface_filament"):
        assert project[key] == job[key], key
    assert project["printer_model"] == "Flashforge AD5X"
    assert "START_PRINT" in project["machine_start_gcode"] and "M1002" not in project["machine_start_gcode"]
    assert project["curr_bed_type"] == orca_adapter.ORCA_DEFAULT_BED_TYPE == "Cool Plate"
    assert project["machine_max_acceleration_x"] == job["machine_max_acceleration_x"]
    # Foreign keys the job leaves to Orca's defaults are gone, as on a sliced STL.
    assert "default_jerk" not in project and "supertack_plate_temp" not in project
    # Nothing is left for Orca to re-apply as a user change of the X1C preset.
    assert project["inherits"] == ""
    assert set(project["different_settings_to_system"]) == {""}
    # Author intent stays: kept keys reach Orca with the author's values.
    assert project["sparse_infill_pattern"] == job["sparse_infill_pattern"] == "gyroid"
    assert project["seam_position"] == job["seam_position"] == "back"
    assert project["wall_loops"] == job["wall_loops"] == "3"
    # A lowered author speed is the designer's (bridge 5 mm/s); a faster one never is (outer wall 300).
    assert job["bridge_speed"] == "5" and float(job["outer_wall_speed"]) < 300
    # Per-object overrides: only kept author keys with Orca values survive; structure stays.
    settings = seen["Metadata/model_settings.config"].decode()
    obj = re.search(r'<object id="1">.*?</object>', settings, re.S).group(0)
    assert 'key="outer_wall_speed"' not in obj and 'key="support_style"' not in obj
    assert '<metadata key="sparse_infill_density" value="30%"/>' in obj
    assert '<metadata key="extruder" value="1"/>' in obj and '<metadata key="name" value="Base"/>' in obj
    plate_block = re.search(r'<plate>.*?</plate>', settings, re.S).group(0)
    assert "curr_bed_type" not in plate_block and 'key="object_id" value="1"' in plate_block
    assert {"outer_wall_speed", "curr_bed_type", "Metadata/model_settings.config"} <= set(
        provenance["project_settings_rewritten"])
    assert any("bridge_speed" in note for note in provenance["author_notes"])


def test_source_of_record_is_never_rewritten(tmp_path):
    plate = derived_plate(tmp_path, foreign_source(tmp_path / "bambu.3mf"))
    before = plate.read_bytes()
    slice_capture(tmp_path, plate)
    assert plate.read_bytes() == before


def test_adopt_keeps_per_filament_list_shape_and_layer_range_intent(tmp_path):
    path = tmp_path / "p.3mf"
    project = {"nozzle_temperature": ["250", "250"], "filament_type": ["PETG", "PETG"],
               "outer_wall_speed": "300", "jerk_values": "1", "default_jerk": "9", "curr_bed_type": "Supertack Plate",
               "name": "project_settings", "from": "project", "printer_extruder_variant": ["Direct Drive Standard"],
               "nozzle_volume_type": ["Standard"]}
    ranges = ('<?xml version="1.0" encoding="utf-8"?>\n<objects>\n <object id="1">\n'
              '  <range min_z="0" max_z="5">\n   <option opt_key="extruder">2</option>\n'
              '   <option opt_key="layer_height">0.12</option>\n   <option opt_key="outer_wall_speed">500</option>\n'
              '   <option opt_key="sparse_infill_pattern">bogus</option>\n  </range>\n </object>\n</objects>\n')
    with zipfile.ZipFile(path, "w") as archive:
        archive.writestr("3D/3dmodel.model", "<model/>")
        archive.writestr("Metadata/project_settings.config", json.dumps(project))
        archive.writestr("Metadata/layer_config_ranges.xml", ranges)
    job = {"nozzle_temperature": ["215"], "filament_type": ["PLA"], "outer_wall_speed": "140",
           "curr_bed_type": "Textured PEI Plate", "name": "job process", "from": "system"}
    changed = orca_adapter.adopt_job_settings(path, job)
    with zipfile.ZipFile(path) as archive:
        out = json.loads(archive.read("Metadata/project_settings.config"))
        ranges_out = archive.read("Metadata/layer_config_ranges.xml").decode()
    assert out["nozzle_temperature"] == ["215", "215"] and out["filament_type"] == ["PLA", "PLA"]
    assert out["outer_wall_speed"] == "140" and out["curr_bed_type"] == "Textured PEI Plate"
    assert "default_jerk" not in out and out["jerk_values"] == "1"  # only foreign machine/motion keys go
    assert out["name"] == "project_settings" and out["from"] == "project"  # preset bookkeeping untouched
    # Multi-extruder variant bookkeeping stays: its filament half is not the machine's to remove.
    assert out["printer_extruder_variant"] == ["Direct Drive Standard"] and out["nozzle_volume_type"] == ["Standard"]
    assert 'opt_key="extruder">2<' in ranges_out and 'opt_key="layer_height">0.12<' in ranges_out
    assert "outer_wall_speed" not in ranges_out and "bogus" not in ranges_out
    assert changed["default_jerk"] == ["9", None]
    # A second pass has nothing left to change.
    assert orca_adapter.adopt_job_settings(path, job) == {}


def test_dedicated_support_filament_never_points_past_the_plates_one_filament(tmp_path):
    """Edge case 10 (ForgeBridge 1.1.4). Print Handy prints supports with the template's support
    filament (0: the object's own), so a source whose supports use a dedicated filament 2 never
    leaves a derived one-filament plate asking Orca for filament 2."""
    project = {**FOREIGN, "enable_support": "1", "raft_layers": "2", "support_filament": "2",
               "support_interface_filament": "2"}
    plate = derived_plate(tmp_path, foreign_source(tmp_path / "bambu.3mf", project))
    seen, _provenance, job = slice_capture(tmp_path, plate)
    out = json.loads(seen["Metadata/project_settings.config"])
    assert out["support_filament"] == job["support_filament"] == "0"
    assert out["support_interface_filament"] == job["support_interface_filament"] == "0"
    assert len(out["filament_colour"]) == 1
    assert job["enable_support"] == "1"  # the author's supports stay on, in the plate's filament


def _adopted_project(tmp_path, project, job=None):
    path = tmp_path / "imported.3mf"
    write_3mf(path, [("Base", 1, box(30, 30, 10), (60, 60))], [("Plate 1", [0])], PALETTE,
              project_extra=project)
    changed = orca_adapter.adopt_job_settings(path, job or {"curr_bed_type": "Cool Plate"})
    with zipfile.ZipFile(path) as archive:
        adopted = json.loads(archive.read("Metadata/project_settings.config"))
    return adopted, changed


def test_plugin_keys_are_stripped_from_an_imported_project(tmp_path):
    # #1087 insurance: Orca's CLI never loads plugins today, but an
    # imported project naming a slicing-pipeline plugin has both
    # plugin keys removed at intake, so a future CLI that does load
    # them finds nothing to load.
    project = dict(FOREIGN, slicing_pipeline_plugin="acme.plugin:SlicingPipeline",
                   plugins="acme.plugin")
    adopted, changed = _adopted_project(tmp_path, project)
    assert "slicing_pipeline_plugin" not in adopted
    assert "plugins" not in adopted
    assert changed["slicing_pipeline_plugin"] == ["acme.plugin:SlicingPipeline", None]
    assert changed["plugins"] == ["acme.plugin", None]
    # Ordinary author intent the job does not set is not foreign; it survives.
    assert adopted["sparse_infill_pattern"] == FOREIGN["sparse_infill_pattern"]
    assert adopted["wall_loops"] == FOREIGN["wall_loops"]


def test_plugin_keys_are_stripped_from_plate_overrides(tmp_path):
    source = foreign_source(tmp_path / "source.3mf")
    with zipfile.ZipFile(source) as archive:
        entries = {info.filename: archive.read(info) for info in archive.infolist()}
    settings = entries["Metadata/model_settings.config"].decode()
    settings = settings.replace(
        "<plate>", '<plate><metadata key="slicing_pipeline_plugin" value="acme.plugin"/>', 1)
    entries["Metadata/model_settings.config"] = settings.encode()
    with zipfile.ZipFile(source, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in entries.items():
            archive.writestr(name, data)
    orca_adapter.adopt_job_settings(source, {"curr_bed_type": "Cool Plate"})
    with zipfile.ZipFile(source) as archive:
        adopted = archive.read("Metadata/model_settings.config").decode()
    assert "slicing_pipeline_plugin" not in adopted
