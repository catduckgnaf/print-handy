"""Author 3mf values Orca rejects as out of range are clamped, never fatal.

Regression: Sticker Buddy (MakerWorld 2354477) carried Bambu's raft_first_layer_expansion=-1
("auto"), which Orca 2.4 rejects with return -18, failing the Discord intake closed.
"""
import json
import sys
import zipfile
from pathlib import Path

import pytest

from print_handy.core import orca_adapter as adapter  # noqa: E402

LOG = ('Param values in 3mf/config error: \n'
       'raft_first_layer_expansion: -1 not in range [0.000000,340282346638528859811704183484516925440.000000]\n'
       'run found error, return -18, exit...\n')


def _make(path, settings):
    with zipfile.ZipFile(path, 'w') as z:
        z.writestr('3D/3dmodel.model', '<model/>')
        z.writestr('Metadata/project_settings.config', json.dumps(settings))


def test_only_known_rejected_auto_sentinels_are_normalized(tmp_path):
    p = tmp_path / 'a.3mf'
    log = LOG + ('tree_support_wall_count: -1 not in range [0,100]\\n'
                 'wall_loops: -1 not in range [1,100]\\n')
    _make(p, {'raft_first_layer_expansion': '-1', 'tree_support_wall_count': '-1',
              'raft_layers': '0', 'wall_loops': '-1'})
    assert adapter.sanitize_project_settings(p, log) == {
        'raft_first_layer_expansion': ['-1', '0'], 'tree_support_wall_count': ['-1', '0']}
    with zipfile.ZipFile(p) as z:
        s = json.loads(z.read('Metadata/project_settings.config'))
        assert s['raft_first_layer_expansion'] == '0'
        assert s['tree_support_wall_count'] == '0'
        assert s['wall_loops'] == '-1'
        assert z.read('3D/3dmodel.model') == b'<model/>'


def test_unknown_negative_and_unrejected_values_are_not_normalized(tmp_path):
    p = tmp_path / 'a.3mf'
    _make(p, {'raft_first_layer_expansion': '-2', 'tree_support_wall_count': '-1', 'wall_loops': '-1'})
    assert adapter.sanitize_project_settings(p) == {'tree_support_wall_count': ['-1', '0']}
    with zipfile.ZipFile(p) as z:
        settings = json.loads(z.read('Metadata/project_settings.config'))
    assert settings == {'raft_first_layer_expansion': '-2', 'tree_support_wall_count': '0', 'wall_loops': '-1'}


def test_noop_without_known_sentinel_or_config(tmp_path):
    p = tmp_path / 'a.3mf'
    _make(p, {'raft_first_layer_expansion': '-2'})
    before = p.read_bytes()
    assert adapter.sanitize_project_settings(p) == {}
    assert p.read_bytes() == before
    assert adapter.sanitize_project_settings(tmp_path / 'x.stl') == {}



def test_range_recovery_clamps_only_named_keys(tmp_path):
    p = tmp_path / 'a.3mf'
    _make(p, {'wall_loops': '-1', 'tree_support_wall_count': '-1', 'raft_first_layer_expansion': '-2'})
    log = 'wall_loops: -1 not in range [1,100]\n'
    assert adapter.clamp_rejected_settings(p, log) == {'wall_loops': ['-1', '1']}
    with zipfile.ZipFile(p) as z:
        settings = json.loads(z.read('Metadata/project_settings.config'))
    assert settings['wall_loops'] == '1'
    assert settings['tree_support_wall_count'] == '-1'
    assert settings['raft_first_layer_expansion'] == '-2'
    assert adapter.clamp_rejected_settings(p, '') == {}


def test_list_values_clamped(tmp_path):
    p = tmp_path / 'a.3mf'
    _make(p, {'raft_first_layer_expansion': ['-1', '2']})
    assert adapter.sanitize_project_settings(p, LOG)
    with zipfile.ZipFile(p) as z:
        assert json.loads(z.read('Metadata/project_settings.config'))['raft_first_layer_expansion'] == ['0', '2']


def test_known_auto_sentinels_are_normalized_before_first_orca_attempt(tmp_path, monkeypatch):
    from print_handy.core import model_job

    source = tmp_path / 'bambu-2.5.3mf'
    _make(source, {'raft_first_layer_expansion': '-1', 'tree_support_wall_count': '-1',
                   'wall_loops': '-1'})
    original = source.read_bytes()
    calls = []

    def run(command, **kwargs):
        calls.append(command)
        private = Path(command[-1])
        with zipfile.ZipFile(private) as archive:
            settings = json.loads(archive.read('Metadata/project_settings.config'))
        assert settings['raft_first_layer_expansion'] == '0'
        assert settings['tree_support_wall_count'] == '0'
        assert settings['wall_loops'] == '-1'
        out = tmp_path / 'out' / 'plate_1.gcode'
        out.write_text('; generated by OrcaSlicer 2.4.2\\nG90\\n')
        return type('R', (), {'returncode': 0, 'stdout': '', 'stderr': ''})()

    monkeypatch.setattr(adapter.subprocess, 'run', run)
    monkeypatch.setattr(adapter, 'finalize_zmod', lambda *_args: None)
    state = model_job.printer_state.load()
    state = {**state, 'spool': {**state['spool'], 'color_code': 'F7E6DE'}}
    state['filament_slots'] = {'1': {'spoolman_id': state['spool']['spoolman_id'], 'material': state['spool']['material'], 'physical_color_verified': True}}
    out, provenance, _ = adapter.slice_model(
        source, tmp_path / 'out', state, preserve_layout=True)

    assert out.is_file()
    assert len(calls) == 1
    assert source.read_bytes() == original
    assert provenance['sanitized_author_settings'] == {
        'raft_first_layer_expansion': ['-1', '0'], 'tree_support_wall_count': ['-1', '0']}


def test_failure_includes_orca_result_json_details(tmp_path, monkeypatch):
    from print_handy.core import model_job

    source = tmp_path / 'bambu-2.5.3mf'
    _make(source, {})
    outdir = tmp_path / 'failed'

    def run(_command, **_kwargs):
        (outdir / 'result.json').write_text(json.dumps({
            'return_code': -24, 'error_string': 'Unsupported 3MF version'}))
        return type('R', (), {'returncode': 232, 'stdout': '', 'stderr': ''})()

    monkeypatch.setattr(adapter.subprocess, 'run', run)
    state = model_job.printer_state.load()
    state = {**state, 'spool': {**state['spool'], 'color_code': 'F7E6DE'}}
    state['filament_slots'] = {'1': {'spoolman_id': state['spool']['spoolman_id'], 'material': state['spool']['material'], 'physical_color_verified': True}}
    try:
        adapter.slice_model(source, outdir, state, preserve_layout=True)
    except RuntimeError as exc:
        assert 'Orca return_code -24: Unsupported 3MF version' in str(exc)
    else:
        raise AssertionError('failed Orca result was accepted')


