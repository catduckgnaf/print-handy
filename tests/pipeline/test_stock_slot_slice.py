"""#658: a stock-firmware AD5X slices a job bound to one IFS slot without the ZMod contract.

The stock adapter has no native (ZMod) helpers, and its launch binds the slot from the job's
filament_selection. Finalizing a slot-bound slice must therefore insert nothing for it, while the
ZMod AD5X keeps its slot map, color data and MD5 exactly as before.
"""
import copy
from pathlib import Path
from unittest.mock import patch

from print_handy import printers
from print_handy.core import model_job as job
from print_handy.core import orca_adapter as adapter


def stock():
    # The process settings (with [orca]) viewed as the stock AD5X.
    return printers.get("flashforge_stock.ad5x")


def state():
    st = copy.deepcopy(job.printer_state.load())
    st['spool'] = {'spoolman_id': 12, 'name': 'Dark Green PLA', 'material': 'PLA', 'diameter_mm': 1.75, 'density': 1.24}
    return st


def fake_slice(cmd, **kwargs):
    folder = Path(cmd[cmd.index('--outputdir') + 1])
    (folder / 'plate_1.gcode').write_text(
        '; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2\n'
        '; filament_type = PLA+\n; HEADER_BLOCK_END\nT0\nG90\n')
    return type('Result', (), {'returncode': 0, 'stdout': '', 'stderr': ''})()


def fake_stock_slice(cmd, **kwargs):
    """Stock firmware runs the slicer's own start code, and its guard (#211) checks the recorded
    nozzle and heaters and holds Orca's toolpath to the bed, so the fake output carries all three."""
    folder = Path(cmd[cmd.index('--outputdir') + 1])
    (folder / 'plate_1.gcode').write_text(
        '; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2\n'
        '; filament_type = PLA+\n; nozzle_diameter = 0.4\n; HEADER_BLOCK_END\n'
        'M140 S60\nM104 S210\nM190 S60\nM109 S210\nG28\nG90\nM83\nT0\n'
        '; MACHINE_START_GCODE_END\n;LAYER_CHANGE\nG1 Z0.2\nG1 X10 Y10\nG1 X100 Y100 E1\n'
        '; MACHINE_END_GCODE_START\nM104 S0\nM140 S0\n')
    return type('Result', (), {'returncode': 0, 'stdout': '', 'stderr': ''})()


def test_finalize_inserts_nothing_for_a_printer_without_the_zmod_contract(tmp_path):
    gcode = tmp_path / 'plate_1.gcode'
    gcode.write_text('T0\nG90\n')
    with patch.object(printers, 'current', stock):
        assert job.finalize_multicolor(gcode, None, state(), {'0': 2}) is None
    assert gcode.read_text() == 'T0\nG90\n'


def test_a_slot_bound_slice_on_the_stock_ad5x_is_not_refused_as_multicolor(tmp_path):
    source = tmp_path / 'part.stl'
    source.write_text('solid x\nendsolid x\n')
    with patch.object(adapter.subprocess, 'run', side_effect=fake_stock_slice):
        output, provenance, _ = adapter.slice_model(source, tmp_path / 'out', state(), filament_slot=2,
                                                    adapter=stock())
    raw = output.read_bytes()
    assert not raw.startswith(b'; MD5:')  # no ZMod checksum or slot map on stock firmware
    assert b'; hermes_tool_slots =' not in raw


def test_the_zmod_ad5x_still_gets_its_slot_map_and_checksum(tmp_path):
    source = tmp_path / 'part.stl'
    source.write_text('solid x\nendsolid x\n')
    with patch.object(adapter.subprocess, 'run', side_effect=fake_slice):
        output, _, _ = adapter.slice_model(source, tmp_path / 'out', state(), filament_slot=2)
    raw = output.read_bytes()
    assert raw.startswith(b'; MD5:') and job.zmod_md5_valid(output)
    assert b'; hermes_tool_slots =' in raw
