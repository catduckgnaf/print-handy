SOURCE_4 = Path(__file__).resolve().parents[2] / 'tests' / 'corpus' / 'cases' / 'four-colors-one-plate' / 'model.3mf'


def _slice_four_colors(tmp_path, monkeypatch, nozzle_dia):
    """A mapped AD5X slice with a fake Orca (test_ifs_purge_mode's shape),
    with the fitted nozzle diameter chosen by the test."""
    from types import SimpleNamespace as S

    from print_handy import printers, settings
    from print_handy.core import printer_state, slice_guard, source_colors
    # These tests are about the tower's width; a chute-purge printer slices without one (#832), so ask for it.
    monkeypatch.setitem(settings.current()['purge'], 'prime_tower', 'on')
    monkeypatch.setattr(printer_state, '_get', lambda url, *a, **k: {
        'result': {'status': {'save_variables': {'variables': {'use_trash_on_print': 1, 'display_off': 1}}}}})
    monkeypatch.setattr(orca_adapter, 'pre_slice', lambda **k: slice_guard.Result())
    monkeypatch.setattr(orca_adapter, 'post_slice', lambda *a, **k: slice_guard.Result())
    monkeypatch.setattr(orca_adapter.sg, 'enforce_approved_baseline', lambda out, **k: slice_guard.Result())
    monkeypatch.setattr(orca_adapter, 'finalize_zmod', lambda *a, **k: None, raising=False)

    def run(command, **_kwargs):
        out = Path(command[command.index('--outputdir') + 1]) / 'plate_1.gcode'
        out.write_text('; generated by OrcaSlicer 2.4.2\nT0\nG90\nG1 X10 Y10 Z0.2 E1\nT1\nG1 X11 Y10 E1\n')
        return S(returncode=0, stdout='', stderr='')
    monkeypatch.setattr(orca_adapter.subprocess, 'run', run)
    state = json.loads(tcg.STATE.read_text())
    state['nozzle']['diameter_mm'] = nozzle_dia
    manifest = source_colors.inventory(SOURCE_4)
    choices = {}
    for row, slot in zip(source_colors.canonical_prompts(manifest), [1, 2, 1, 2]):
        record = state['filament_slots'][str(slot)]
        choices[row['key']] = {'slot': slot, 'color': record['color'], 'material': 'PLA',
                               'spoolman_id': record['spoolman_id']}
    decisions = {'source_sha256': manifest['source_sha256'], 'mode': 'per_part',
                 'schema': 'part_slots_v1', 'choices': choices}
    folder = tmp_path / 'slice'
    printer = printers.get('flashforge.ad5x', settings.load(local=False, environ={}))
    _output, _provenance, _configs = orca_adapter.slice_model(
        SOURCE_4, folder, state, adapter=printer, color_decisions=decisions)
    process = json.loads((folder / 'process.json').read_text())
    return process


def _tower_spy(monkeypatch):
    seen = []
    real = color_geometry.prime_tower_candidates

    def spy(part_bounds, **kwargs):
        seen.append(kwargs.get('tower'))
        return real(part_bounds, **kwargs)
    monkeypatch.setattr(color_geometry, 'prime_tower_candidates', spy)
    return seen


def test_overlapping_parts_of_one_build_item_export_as_one_object(tmp_path):
    # Separate Orca objects whose footprints touch fail Orca's path-conflict check.
    src = tcg.COUPON
    st = json.loads(tcg.STATE.read_text())
    mapping, report = export_color_geometry(src, tmp_path / 'out.3mf', tcg.decisions(src, st))
    with zipfile.ZipFile(tmp_path / 'out.3mf') as z:
        items = re.findall(r'<(?:\w+:)?item ', z.read('3D/3dmodel.model').decode())
    assert len(report['parts']) == 3
    assert len(items) == 1


def test_tower_candidates_clear_parts_and_are_spread():
    postit = [[[112.5, 196.5], [113.0, 144.5], [0, 84]], [[24.0, 100.4], [19.5, 105.0], [0, 1.4]],
              [[23.5, 99.9], [115.8, 201.3], [0, 1.5]], [[112.3, 188.7], [18.7, 104.2], [0, 1.4]]]
    towers = prime_tower_candidates(postit)
    assert towers[0] == color_geometry.prime_tower_xy(postit)
    assert len(towers) >= 2
    tw, m = color_geometry.TOWER_MM, color_geometry.TOWER_MARGIN_MM
    for x, y in towers:
        assert color_geometry.TOWER_EDGE_MM <= x <= 220 - tw - color_geometry.TOWER_EDGE_MM
        for (x0, x1), (y0, y1), _ in postit:
            assert not (x < x1 + m and x + tw > x0 - m and y < y1 + m and y + tw > y0 - m)
    for i, a in enumerate(towers):
        for b in towers[i + 1:]:
            assert abs(a[0] - b[0]) >= 20 or abs(a[1] - b[1]) >= 20


def test_effective_tower_width_is_the_max_of_config_and_nozzle(monkeypatch):
    # P2-2/P2-34: placement and the emitted Orca profile must agree on one
    # tower width — the larger of the configured size and the fitted
    # nozzle's tuned width.
    assert color_geometry.effective_tower_mm() == color_geometry.TOWER_MM
    assert color_geometry.effective_tower_mm(0.6) == 60
    assert color_geometry.effective_tower_mm(0.8) == 75
    monkeypatch.setattr(color_geometry, 'TOWER_MM', 52.0)
    assert color_geometry.effective_tower_mm(0.4) == 52.0  # configured size wins when larger
    monkeypatch.setattr(color_geometry, 'TOWER_MM', 30.0)
    assert color_geometry.effective_tower_mm(0.4) == 45  # a smaller configured size cannot
    # shrink the tower below what the nozzle's purge volume needs


def test_mapped_slice_geometry_and_profile_share_the_nozzle_tower_width(tmp_path, monkeypatch):
    seen = _tower_spy(monkeypatch)
    process = _slice_four_colors(tmp_path, monkeypatch, 0.6)
    assert process['prime_tower_width'] == '60'
    assert seen and all(tower == 60 for tower in seen)


def test_mapped_slice_honors_the_configured_tower_size(tmp_path, monkeypatch):
    monkeypatch.setattr(color_geometry, 'TOWER_MM', 52.0)
    seen = _tower_spy(monkeypatch)
    process = _slice_four_colors(tmp_path, monkeypatch, 0.4)
    assert process['prime_tower_width'] == '52'
    assert seen and all(tower == 52 for tower in seen)


def test_mapped_slice_never_auto_arranges_and_retries_tower_on_conflict():
    body = inspect.getsource(orca_adapter.slice_model)
    arrange = re.search(r"\['--arrange', '0', '--orient', '0'\] if \((.*?)\) else", body).group(1)
    assert 'mapped_profile' in arrange  # #77 renamed the multi-tool flag
    assert "_orca_conflict(folder)" in body and "prime_tower_candidates_mm" in body
    assert '--no-check' not in body


def test_conflict_detector_reads_result_json(tmp_path):
    assert not orca_adapter._orca_conflict(tmp_path)
    (tmp_path / 'result.json').write_text(json.dumps({'error_string': ' G-code conflicts detected after slicing.'}))
    assert orca_adapter._orca_conflict(tmp_path)
    (tmp_path / 'result.json').write_text(json.dumps({'error_string': 'Success.'}))
    assert not orca_adapter._orca_conflict(tmp_path)


def test_orca_failure_details_include_conflicting_object_names(tmp_path):
    (tmp_path / 'result.json').write_text(json.dumps({
        'return_code': -101,
        'error_string': 'G-code conflicts detected after slicing.',
    }))
    (tmp_path / '00000.log').write_text(
        'debug: gcode path conflicts found between WipeTower and 通用-圆柱体.\n'
    )

    details = orca_adapter._orca_failure_details(tmp_path)

    assert 'return_code -101' in details
    assert 'conflicting objects: WipeTower and 通用-圆柱体' in details
