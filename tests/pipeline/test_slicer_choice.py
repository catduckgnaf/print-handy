"""[printer] slicer: Bambu Studio by default for Bambu Lab, OrcaSlicer for everyone else."""
import copy
from pathlib import Path

import pytest

from print_handy import printers, settings
from print_handy.core import orca_adapter as adapter
from print_handy.printers.base import PrinterModel
from print_handy.printers.klipper.adapter import KlipperAdapter
from .test_orca_adapter import _allow_post, _source, _state

KEY = "bambulab.zz_test_printer"


def bambu_adapter(monkeypatch, slicer):
    model = PrinterModel(key=KEY, label="Test Bambu", adapter=KlipperAdapter, templates="klipper_generic",
                         vendor=printers.VENDORS["bambulab"], supported_nozzle_sizes=(0.4,), settings={})
    monkeypatch.setitem(printers.MODELS, KEY, model)
    cfg = copy.deepcopy(settings.current())
    cfg["printer"].update(model=KEY, vendor="bambulab", slicer=slicer)
    cfg["orca"]["templates"] = settings.ROOT / "print_handy" / "templates" / "orca" / "klipper_generic"
    return printers.get(KEY, cfg)


# Each fake writes the identity form its real slicer writes (#434): Bambu Studio's header block,
# OrcaSlicer's "; generated by" line. text overrides both (a caller-shaped file).
BAMBU_TEXT = ("; HEADER_BLOCK_START\n; BambuStudio 2.8.2\n"
              "; model printing time: 1m 0s; total estimated time: 2m 0s\nG90\nG1 X1 Y1 Z0.2\n")
ORCA_TEXT = "; generated by OrcaSlicer 2.8.2\nG90\nG1 X1 Y1 Z0.2\n"


def fake_run(calls, text=None):
    def run(command, **_kwargs):
        calls.append(command)
        output = Path(command[command.index('--outputdir') + 1]) / 'plate_1.gcode'
        output.write_text(text if text is not None
                          else BAMBU_TEXT if 'com.bambulab.BambuStudio' in command else ORCA_TEXT)
        return type('R', (), {'returncode': 0, 'stdout': '', 'stderr': ''})()
    return run


def test_bambu_lab_defaults_to_bambu_studio(monkeypatch):
    printer = bambu_adapter(monkeypatch, None)
    printer.config["printer"].pop("slicer", None)
    assert adapter.slicer_choice(printer) == "bambu_studio"
    assert printers.MODELS[KEY].defaults()["printer"]["slicer"] == "bambu_studio"


def test_existing_printers_slice_with_orca():
    for key in ("flashforge.ad5x", "sovol.sv06", "klipper.generic", "octoprint.marlin"):
        assert adapter.slicer_choice(printers.get(key)) == "orca"


def test_bambu_studio_primary_runs_once_and_is_not_a_fallback(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    calls = []
    monkeypatch.setattr(adapter.subprocess, 'run', fake_run(calls))
    printer = bambu_adapter(monkeypatch, "bambu_studio")
    output, provenance, configs = adapter.slice_model(_source(tmp_path), tmp_path / 'out', _state(), adapter=printer)
    assert len(calls) == 1 and 'com.bambulab.BambuStudio' in calls[0]
    assert '--unshare=network' in calls[0]  # the configured Flathub command keeps its network cut
    assert provenance['slicer'] == 'Bambu Studio' and provenance['fallback'] is None
    assert any(path.parent.name == 'bambu' for path in configs)
    assert not (tmp_path / 'out' / 'orca.log').exists()


def test_ineligible_fallback_is_not_spawned_and_cli_conflict_is_preserved(tmp_path, monkeypatch):
    from dataclasses import replace
    _allow_post(monkeypatch)
    printer = bambu_adapter(monkeypatch, "orca")
    printer.model = replace(printer.model, vendor=replace(printer.model.vendor, fallback_slicer=None))
    monkeypatch.setattr(adapter.shutil, 'which', lambda _name: '/mock/bambu-studio')
    monkeypatch.setattr(adapter.os, 'access', lambda *_args: True)
    calls = []

    def fail(command, **_kwargs):
        calls.append(command)
        return type('R', (), {'returncode': 1, 'stdout': (
            'G-code conflicts detected after slicing.\n'
            'gcode path conflicts found between BRONZE DETAILS and BLACK BODY.\n'), 'stderr': ''})()

    monkeypatch.setattr(adapter, '_spawn_slicer', fail)
    with pytest.raises(adapter.SliceFailure) as caught:
        adapter.slice_model(_source(tmp_path), tmp_path / 'out', _state(), adapter=printer)
    assert len(calls) == 1
    assert caught.value.kind == 'conflict'
    assert caught.value.returncode == 1
    assert caught.value.as_dict()['conflict_objects'] == ['BRONZE DETAILS', 'BLACK BODY']
    assert 'fallback skipped' in str(caught.value).lower()


def test_bambu_vendor_with_orca_runs_orca(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    calls = []
    monkeypatch.setattr(adapter.subprocess, 'run', fake_run(calls))
    printer = bambu_adapter(monkeypatch, "orca")
    _output, provenance, _ = adapter.slice_model(_source(tmp_path), tmp_path / 'out', _state(), adapter=printer)
    assert len(calls) == 1 and 'com.orcaslicer.OrcaSlicer' in calls[0]
    assert provenance['slicer'] == 'OrcaSlicer'
    phases = provenance['timing_s']['python_subphases_s']
    assert phases['inventory_s'] >= 0
    assert phases['geometry_s'] >= 0
    assert phases['prepare_other_s'] >= 0
    assert phases['other_s'] >= 0
    assert abs(sum(phases.values()) - provenance['timing_s']['python_s']) < 0.02


def test_slice_reuses_inventory_but_rechecks_resource_guards(tmp_path, monkeypatch):
    from print_handy.core import intake_resources, slice_guard, source_colors
    _allow_post(monkeypatch)
    source = _source(tmp_path)
    calls = {'inventory': 0, 'guard': 0}

    def inventory(path):
        calls['inventory'] += 1
        return {'parts': []}

    def guard(path):
        calls['guard'] += 1

    def pre_slice(**kwargs):
        first = source_colors.inventory(source)
        first['parts'].append('mutated')
        assert source_colors.inventory(source)['parts'] == []
        return slice_guard.Result()

    monkeypatch.setattr(source_colors, '_inventory', inventory)
    monkeypatch.setattr(intake_resources, 'check_source', guard)
    monkeypatch.setattr(adapter, 'pre_slice', pre_slice)
    monkeypatch.setattr(adapter.subprocess, 'run', fake_run([]))
    adapter.slice_model(source, tmp_path / 'out', _state(), adapter=bambu_adapter(monkeypatch, 'orca'))
    assert calls == {'inventory': 1, 'guard': 2}


def test_klipper_start_code_in_bambu_output_is_blocked_after_slicing(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    calls = []
    text = "; HEADER_BLOCK_START\n; BambuStudio 2.8.2\nPRINT_START BED=60 HOTEND=215\nG1 X1 Y1 Z0.2\n"
    monkeypatch.setattr(adapter.subprocess, 'run', fake_run(calls, text))
    printer = bambu_adapter(monkeypatch, "bambu_studio")
    with pytest.raises(RuntimeError, match="Post-slice guard blocked: .*non-Bambu commands.*PRINT_START"):
        adapter.slice_model(_source(tmp_path), tmp_path / 'out', _state(), adapter=printer)


def test_bambu_studio_failure_names_its_own_log(tmp_path, monkeypatch):
    _allow_post(monkeypatch)

    def run(command, **_kwargs):
        return type('R', (), {'returncode': 3, 'stdout': '', 'stderr': 'boom'})()
    monkeypatch.setattr(adapter.subprocess, 'run', run)
    printer = bambu_adapter(monkeypatch, "bambu_studio")
    with pytest.raises(RuntimeError, match=r"Bambu Studio is the configured slicer; Bambu Studio failed \(3\)") as exc:
        adapter.slice_model(_source(tmp_path), tmp_path / 'out', _state(), adapter=printer)
    assert 'orca.log' not in str(exc.value) and 'bambu.log' in str(exc.value)
