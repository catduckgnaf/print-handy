"""Shared slicer-shaped G-code fakes (testing-hardening pass, E3).

One factory for every test that needs G-code, so fixture realism drift
(the Lane B pattern: each test hand-rolling a slightly different fake
until the fakes no longer resemble slicer output) has one place to be
fixed. Shapes mirror what each slicer family actually writes:

* the generated-by header line each family emits;
* heater + toolpath body (M104/M109/M140/M190, extruding G1 moves,
  layer markers in the family's spelling);
* the footer config block OrcaSlicer / PrusaSlicer / Bambu Studio
  append AFTER the toolpath (``; printer_model = ...``,
  ``; nozzle_diameter = ...``) — placement matters: foreign-G-code
  detection reads head+tail windows precisely because the model comment
  lives in the footer of a real file;
* Cura writes no ``printer_model`` comment at all — the factory keeps
  that realism, and the contract tests pin what detection does with it;
* ``gcode_3mf`` packages plates as ``Metadata/plate_N.gcode`` entries,
  the layout both the detector and ``gcode_3mf`` read.

Nothing here touches the network or a real slicer.
"""
from __future__ import annotations

import zipfile
from pathlib import Path

TOOLPATH = (
    "M104 S210\n"
    "M140 S60\n"
    "M109 S210\n"
    "M190 S60\n"
    "G28\n"
    "G1 Z0.20 F600\n"
    "G1 X10.0 Y10.0 E0.50 F1200\n"
    "G1 X20.0 Y10.0 E0.50\n"
    "G1 X20.0 Y20.0 E0.50\n"
)

_FOOTER_MODELS = ("orca", "bambu", "prusa")


def gcode_text(family: str = "orca", model: str = "AD5X", *,
               nozzle: str = "0.4", body: str = TOOLPATH,
               footer: bool = True) -> str:
    """One plate of slicer-shaped G-code as text."""
    if family == "orca":
        head = ("; generated by OrcaSlicer 2.5.0 on 2026-11-07\n"
                ";thumbnail begin\n;thumbnail end\n")
        layer = ";LAYER_CHANGE\n"
    elif family == "bambu":
        head = "; generated by BambuStudio 02.09.01.70\n"
        layer = ";LAYER_CHANGE\n"
    elif family == "prusa":
        head = "; generated by PrusaSlicer 2.8.0 on 2026-11-07\n"
        layer = ";LAYER_CHANGE\n"
    elif family == "cura":
        head = (";Generated with Cura_SteamEngine 5.6.0\n"
                ";FLAVOR:Marlin\n;TIME:3600\n;Filament used: 1.2m\n"
                ";Layer height: 0.2\n;MINX:10\n;MAXX:20\n")
        layer = ";LAYER:0\n"
    else:
        raise ValueError(f"unknown slicer family {family!r}")
    text = head + layer + body
    if footer and family in _FOOTER_MODELS:
        text += (f"; printer_model = {model}\n"
                 f"; nozzle_diameter = {nozzle}\n"
                 "; filament used [g] = 3.21\n")
    elif footer and family == "cura":
        text += ";End of Gcode\n"
    return text


def write_gcode(path, family: str = "orca", model: str = "AD5X", **kw) -> Path:
    path = Path(path)
    path.write_text(gcode_text(family, model, **kw), encoding="utf-8")
    return path


def write_gcode_3mf(path, plates: dict[int, str], *,
                    model_xml: str = "<build></build>") -> Path:
    """A .gcode.3mf package: ``plates`` maps plate number -> G-code text."""
    path = Path(path)
    with zipfile.ZipFile(path, "w") as archive:
        for number in sorted(plates):
            archive.writestr(f"Metadata/plate_{number}.gcode", plates[number])
        archive.writestr("3D/3dmodel.model", model_xml)
    return path
