"""Paired-ratio gates for the #1153 remainder: the one-scan verify lookups and the settings parse cache.

Same method as test_perf_gate.py (whose helpers this reuses): each gate first proves the work
really happened and gives the old answer, then times candidate against the removed path in the
same process, interleaved, so machine speed cancels. Baselines are in baselines.json, reviewed by
hand; the absolute ceiling is reporting only.
"""
from __future__ import annotations

import os
import time

import pytest

from print_handy import settings
from print_handy.core import fuzzy, model_job
from tests.core.test_gcode_lines_equivalence import _Adapter, new_answers, old_answers
from tests.gcode_factory import TOOLPATH
from tests.perf.test_perf_gate import check_gate, paired_ratio

MACROS = ("PRINT_START", "PRINT_END")


def plate_text():
    """A 1.3 MB Orca-shaped plate: toolpath first, the configuration block at the very end."""
    body = "".join(f";LAYER_CHANGE\n;Z:{0.2 * (n + 1):.2f}\n;TYPE:Outer wall\n;WIDTH:0.42\n" + TOOLPATH * 40
                   + ("M104 S215\n" if n % 50 == 0 else "") for n in range(250))
    return ("; generated by OrcaSlicer 2.5.0\nM190 S60\nM109 S215\nPRINT_START BED=60 HOTEND=215\n" + body
            + "PRINT_END\n" + "".join(f"; key_{n} = {n}\n" for n in range(800))
            + "; filament_type = PLA\n; first_layer_height = 0.2\n; nozzle_diameter = 0.4\n")


@pytest.fixture(scope="module")
def plate():
    return plate_text()


def _new(text):
    lines = model_job._verify_lines(text, _Adapter(*MACROS))
    answers = new_answers(lines, *MACROS)
    assert lines.scans == 1
    return answers


def test_verify_scan_does_the_required_work(plate):
    answers = _new(plate)
    assert answers == old_answers(plate, *MACROS)
    assert answers["config nozzle_diameter"] is not None and answers["layers"][1] == 251
    assert len(plate) > 1_000_000


def test_verify_scan_perf_gate(plate):
    ratio, new_s, _ = paired_ratio(lambda: _new(plate), lambda: old_answers(plate, *MACROS))
    assert not check_gate("verify_line_scan", ratio, new_s)


@pytest.fixture
def home_layer():
    """The shipped home layer, the largest file every settings.load() and /config read parses."""
    path = settings.HOME if settings.HOME.is_file() else settings.LEGACY_HOME
    settings._READ_CACHE.clear()
    if time.time() - os.stat(path).st_mtime < settings._READ_CACHE_RACY_S + 0.5:
        pytest.skip("the home layer was just written; the cache would rightly refuse it")
    yield path
    settings._READ_CACHE.clear()


def test_settings_read_cache_does_the_required_work(home_layer):
    first = settings._read(home_layer)
    assert first == settings._read_uncached(home_layer) and first
    assert len(settings._READ_CACHE) == 1
    first.clear()
    assert settings._read(home_layer) == settings._read_uncached(home_layer)


def test_settings_read_cache_perf_gate(home_layer):
    settings._read(home_layer)
    ratio, cached_s, _ = paired_ratio(lambda: settings._read(home_layer),
                                      lambda: settings._read_uncached(home_layer))
    assert not check_gate("settings_read_cached", ratio, cached_s)


# ---------------------------------------------------------------- loaded-spools near-miss scoring

PLAIN_MESSAGES = ("can you print this for me tonight please", "hello there", "make it 20% bigger",
                  "what is the bed temperature right now?", "whta colors are loded",
                  "the loaded filament is tangled again and I need help")


def _old_loaded_fuzzy(plugin, text):
    """plugins/print-feedback _loaded_spools_fuzzy over the frozen pre-#1153 scorer."""
    from tests.core.test_fuzzy_score_equivalence import old_fuzzy_score
    text = ' '.join(str(text or '').split()).strip()
    best = {}
    for family, phrases in (("loaded", plugin._LOADED_FUZZY_PHRASES), ("other", plugin._LOADED_FUZZY_RIVALS)):
        for phrase in phrases:
            score = old_fuzzy_score(text, phrase)
            if score > best.get(family, 0):
                best[family] = score
    scored = [(score, family) for family, score in best.items() if score]
    if not scored:
        return False
    decision = fuzzy.decide(scored)
    return decision.kind == "direct" and decision.best == "loaded"


def _new_loaded_fuzzy(plugin):
    # Cold memo on every run: each timed message is folded as if it were new,
    # and the fixed phrases are folded once per run, not once per process.
    fuzzy._canonical_memo.cache_clear()
    fuzzy._phonetic.cache_clear()
    return [plugin._loaded_spools_fuzzy(text) for text in PLAIN_MESSAGES]


def test_loaded_spools_fuzzy_does_the_required_work():
    from tests.core.test_fuzzy_score_equivalence import _plugin
    plugin = _plugin()
    answers = _new_loaded_fuzzy(plugin)
    assert answers == [_old_loaded_fuzzy(plugin, text) for text in PLAIN_MESSAGES]
    assert answers.count(True) == 1


def test_loaded_spools_fuzzy_perf_gate():
    from tests.core.test_fuzzy_score_equivalence import _plugin
    plugin = _plugin()
    ratio, new_s, _ = paired_ratio(lambda: _new_loaded_fuzzy(plugin),
                                   lambda: [_old_loaded_fuzzy(plugin, text) for text in PLAIN_MESSAGES])
    assert not check_gate("loaded_spools_fuzzy", ratio, new_s)


