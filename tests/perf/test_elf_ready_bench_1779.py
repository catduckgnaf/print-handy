"""The copies-to-Ready benchmark's report parsing (#1779): offline, no slicer needed.

``scripts/bench/elf_ready_bench.py`` runs the real intake with Orca on the test host. What
runs here is the part that turns TIMING.jsonl rows into the per-slice report, and the
offline guard, so a change to the stage names the report reads fails in CI.
"""
import importlib.util
import socket
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[2] / 'scripts' / 'bench' / 'elf_ready_bench.py'
spec = importlib.util.spec_from_file_location('elf_ready_bench', SCRIPT)
bench = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bench)


def _rows():
    first = [
        {'stage': 'slice_start', 't': 100.0}, {'stage': 'inventory_done', 't': 106.0},
        {'stage': 'orca_begin', 't': 106.1},
        {'stage': 'orca_finalize_done', 't': 200.0, 'slicer_s': 70.0, 'python_s': 56.0},
        {'stage': 'python_overhead', 't': 200.0,
         'subphases_s': {'inventory_s': 6.0, 'geometry_s': 25.0, 'prepare_other_s': 20.0, 'finalize_s': 2.0}},
        {'stage': 'verify_begin', 't': 200.0}, {'stage': 'verify_done', 't': 204.5},
        {'stage': 'slice_done', 't': 205.0},
    ]
    variant = [dict(r, variant='supports', t=r['t'] + 1.0) for r in first]
    for r in variant:
        if r['stage'] == 'orca_finalize_done':
            r.update(slicer_s=72.5, python_s=50.0)
    return first + variant


def test_each_slice_reports_its_slicer_python_and_prepare_split():
    out = bench.slice_rows(_rows())
    assert set(out) == {'first', 'supports'}
    assert out['first']['slicer_s'] == 70.0 and out['first']['python_s'] == 56.0
    assert out['first']['prepare_s'] == 51.0  # inventory + geometry + other prepare work
    assert out['first']['wall_s'] == 105.0 and out['first']['verify_s'] == 4.5
    assert out['supports']['slicer_s'] == 72.5 and out['supports']['python_s'] == 50.0


def test_a_run_with_no_variant_rows_has_only_the_first_slice():
    assert set(bench.slice_rows([r for r in _rows() if 'variant' not in r])) == {'first'}


def test_normalized_digest_ignores_the_per_run_header_lines(tmp_path):
    a, b = tmp_path / 'a.gcode', tmp_path / 'b.gcode'
    body = 'G1 X1 Y1\n; enable_support = 1\nG1 X2\n'
    a.write_text('; generated by OrcaSlicer 2.5.2 on 2026-11-27 at 10:00:00 UTC\n' + body)
    b.write_text('; generated by OrcaSlicer 2.5.2 on 2026-11-27 at 10:05:00 UTC\n' + body)
    assert bench._sha(a) != bench._sha(b)
    assert bench._normalized_sha(a) == bench._normalized_sha(b)
    assert bench._gcode_support_flag(a) == '1'


def test_offline_guard_refuses_a_non_loopback_connection(monkeypatch):
    monkeypatch.setattr(socket.socket, 'connect', socket.socket.connect)
    monkeypatch.setattr(socket.socket, 'connect_ex', socket.socket.connect_ex)
    monkeypatch.setattr(socket, 'getaddrinfo', socket.getaddrinfo)
    bench._block_network()
    with pytest.raises(OSError, match='offline'):
        with socket.socket(socket.AF_INET) as s:
            s.connect(('203.0.113.9', 80))
    with pytest.raises(OSError, match='offline'):
        with socket.socket(socket.AF_INET) as s:
            s.connect_ex(('203.0.113.9', 80))
    with pytest.raises(OSError, match='offline'):
        socket.getaddrinfo('makerworld.com', 443)


def _recorder(color='red', slot=2):
    return bench.Recorder(lambda: 0.0, copies=2, slot=slot, color_word=color)


COLOR_Q = 'Choose the color for Elf body'


def test_color_question_picks_the_matching_slot_button():
    rec = _recorder()
    assert rec._pick(COLOR_Q, ['Blue (slot 1)', 'Red (slot 2)', 'Red (slot 3)']) == 1
    assert rec.unmatched == []


def test_an_unmatched_color_raises_with_the_question_instead_of_the_first_button():
    with pytest.raises(RuntimeError, match='no button for color') as err:
        _recorder()._pick(COLOR_Q, ['Blue (slot 1)', 'Green (slot 2)'])
    assert COLOR_Q in str(err.value)


@pytest.mark.parametrize('question', [
    'Choose the color/material for the 4 chains',
    'Choose the loaded color/material for the White filament',
    'Choose the starting color for Elf body (the print pauses at each height color change)',
])
def test_every_intake_color_wording_raises_when_unmatched(question):
    with pytest.raises(RuntimeError, match='no button for color'):
        _recorder()._pick(question, ['Blue (slot 1)', 'Green (slot 2)'])


@pytest.mark.parametrize('question,choices', [
    ('I can match some of these colors to loaded spools: Body: Red. Use those and pick the rest?',
     ['Use these and pick the rest', 'Pick every color', 'One color for everything']),
    ('Same colors as last time for this file? Body: Blue', ['Same colors as last time', 'Change colors', 'One color for everything']),
    ('Does this fit?', ['Shrink to fit', 'Cancel']),
])
def test_a_non_color_prompt_gets_the_first_button_and_is_recorded(question, choices):
    rec = _recorder()
    assert rec._pick(question, choices) == 0
    assert rec.unmatched == [{'question': question, 'choices': choices, 'picked': 0}]


def test_an_unmatched_color_through_send_clarify_ends_the_run_fast_with_the_error():
    """The intake catches what a prompt raises and answers 'skip', so the report must still say why."""
    import asyncio
    import time
    from types import SimpleNamespace as S

    from print_handy.core import link_intake

    rec = _recorder()
    source = S(chat_id='bench', thread_id=None, user_id='bench')
    ids = []
    real_send = rec.send_clarify

    async def spy(**kw):
        ids.append(kw['clarify_id'])
        return await real_send(**kw)
    rec.send_clarify = spy

    async def run():
        return await asyncio.wait_for(
            link_intake.ask(rec, source, 'bench-key', COLOR_Q, ['Blue (slot 1)', 'Green (slot 2)'], timeout=30), 20)

    t0 = time.monotonic()
    with pytest.raises(RuntimeError, match='no button for color'):
        asyncio.run(run())
    assert time.monotonic() - t0 < 20  # ends at once; the run timeout is 1500 s
    assert 'no button for color' in rec.run_error(None) and COLOR_Q in rec.run_error(None)
    assert rec.run_error('TimeoutError: x') == 'TimeoutError: x'
    from print_handy.core import prompts as core_prompts
    assert len(ids) == 1 and not core_prompts.is_open(ids[0])  # the prompt is closed, nothing left waiting
