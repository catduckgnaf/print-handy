"""The copies-to-Ready benchmark's report parsing (#1779): offline, no slicer needed.

``scripts/bench/elf_ready_bench.py`` runs the real intake with Orca on the test host. What
runs here is the part that turns TIMING.jsonl rows into the per-slice report, and the
offline guard, so a change to the stage names the report reads fails in CI.
"""
import importlib.util
import socket
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[2] / 'scripts' / 'bench' / 'elf_ready_bench.py'
spec = importlib.util.spec_from_file_location('elf_ready_bench', SCRIPT)
bench = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bench)


def _rows():
    first = [
        {'stage': 'slice_start', 't': 100.0}, {'stage': 'inventory_done', 't': 106.0},
        {'stage': 'orca_begin', 't': 106.1},
        {'stage': 'orca_finalize_done', 't': 200.0, 'slicer_s': 70.0, 'python_s': 56.0},
        {'stage': 'python_overhead', 't': 200.0,
         'subphases_s': {'inventory_s': 6.0, 'geometry_s': 25.0, 'prepare_other_s': 20.0, 'finalize_s': 2.0}},
        {'stage': 'verify_begin', 't': 200.0}, {'stage': 'verify_done', 't': 204.5},
        {'stage': 'slice_done', 't': 205.0},
    ]
    variant = [dict(r, variant='supports', t=r['t'] + 1.0) for r in first]
    for r in variant:
        if r['stage'] == 'orca_finalize_done':
            r.update(slicer_s=72.5, python_s=50.0)
    return first + variant


def test_each_slice_reports_its_slicer_python_and_prepare_split():
    out = bench.slice_rows(_rows())
    assert set(out) == {'first', 'supports'}
    assert out['first']['slicer_s'] == 70.0 and out['first']['python_s'] == 56.0
    assert out['first']['prepare_s'] == 51.0  # inventory + geometry + other prepare work
    assert out['first']['wall_s'] == 105.0 and out['first']['verify_s'] == 4.5
    assert out['supports']['slicer_s'] == 72.5 and out['supports']['python_s'] == 50.0


def test_a_run_with_no_variant_rows_has_only_the_first_slice():
    assert set(bench.slice_rows([r for r in _rows() if 'variant' not in r])) == {'first'}


def test_normalized_digest_ignores_the_per_run_header_lines(tmp_path):
    a, b = tmp_path / 'a.gcode', tmp_path / 'b.gcode'
    body = 'G1 X1 Y1\n; enable_support = 1\nG1 X2\n'
    a.write_text('; generated by OrcaSlicer 2.5.2 on 2026-11-27 at 10:00:00 UTC\n' + body)
    b.write_text('; generated by OrcaSlicer 2.5.2 on 2026-11-27 at 10:05:00 UTC\n' + body)
    assert bench._sha(a) != bench._sha(b)
    assert bench._normalized_sha(a) == bench._normalized_sha(b)
    assert bench._gcode_support_flag(a) == '1'


def test_offline_guard_refuses_a_non_loopback_connection(monkeypatch):
    monkeypatch.setattr(socket.socket, 'connect', socket.socket.connect)
    monkeypatch.setattr(socket, 'getaddrinfo', socket.getaddrinfo)
    bench._block_network()
    with pytest.raises(OSError, match='offline'):
        socket.socket(socket.AF_INET).connect(('203.0.113.9', 80))
    with pytest.raises(OSError, match='offline'):
        socket.getaddrinfo('makerworld.com', 443)
