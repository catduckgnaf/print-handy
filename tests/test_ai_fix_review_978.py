# ---------------------------------------------------------------- chat flow

def test_chat_fix_refused_by_the_ai_allowlist_sends_nothing(fix_env, monkeypatch):
    calls = []
    monkeypatch.setattr(ai_fix, "lane_allowed", lambda user_id, cfg=None, now=None:
                        (False, "not on the AI allowlist"))
    monkeypatch.setattr(ai_fix, "propose_fix", lambda *a, **k: calls.append(a))
    result = asyncio.run(plugin.edit_dispatch(_event("fix this"), fix_env.gateway))
    assert result["reason"] == "repair: not on the AI allowlist"
    assert calls == [] and fix_env.confirms == [] and fix_env.reentered == []


def test_chat_fix_restores_the_job_when_reentry_fails(fix_env, monkeypatch):
    before = json.loads(fix_env.job_path.read_text())

    async def broken_reenter(*args, **kwargs):
        raise RuntimeError("slicer exploded")
    monkeypatch.setattr(edit_chat, "_edit_reenter", broken_reenter)
    result = asyncio.run(plugin.edit_dispatch(_event("fix this"), fix_env.gateway))
    assert result["reason"] == "repair re-entry failed"
    assert json.loads(fix_env.job_path.read_text()) == before
    assert not any("Fix applied" in (m or "") for m in fix_env.adapter.sent)
    assert any("job above is unchanged" in (m or "") for m in fix_env.adapter.sent)


def test_chat_undo_reverts_the_whole_fix(fix_env):
    original = str(fix_env.folder / "model.stl")
    asyncio.run(plugin.edit_dispatch(_event("fix this"), fix_env.gateway))
    fixed_job = json.loads(fix_env.job_path.read_text())
    assert fixed_job["downloaded_file"] != original
    asyncio.run(plugin.edit_dispatch(_event("undo"), fix_env.gateway))
    restored = json.loads(fix_env.job_path.read_text())
    assert restored["downloaded_file"] == original
    assert restored["ai_fixes"][0]["undone"] is True
    assert any("Undid the AI fix" in (m or "") for m in fix_env.adapter.sent)
