"""#978 review follow-ups for "Fix this for my printer".

Pins the fixes made after review of PR #980:
- repair routing takes explicit repair requests only; ordinary edits that
  mention "fix ... it" stay on the free, verified edit vocabulary;
- the foreign G-code check reads the footer config block where real
  OrcaSlicer/PrusaSlicer/Bambu files carry ``printer_model``, streams
  packages with bounded memory, picks plate 1 numerically, and does not
  call the printer's own registry names foreign;
- the model's summary never carries mentions or links into chat;
- AI fix requests honor the [ai] allowlist and per-user rate limit;
- painted 3MFs and multi-file jobs refuse file-changing fixes instead of
  silently losing colors or files;
- a fix is recorded and undone as one step (file swap and plans together);
- mesh repair is vectorized and finishes promptly on a large mesh;
- the chat repair flow restores the job when re-entry fails and does not
  claim success it did not have; "undo" reverts a whole fix.
"""
