"""Bambu Lab A1 with the real Bambu Studio CLI: the vendor-default primary path and the Orca->Bambu fallback.

Skipped unless PRINT_HANDY_REAL_SLICER=1 and PRINT_HANDY_REAL_BAMBU=1; CI's Slicer test (bambu) job
runs this file with the Flathub Bambu Studio the home configuration uses ([bambu] command in
config/home.yaml: flatpak run --command=bambu-studio com.bambulab.BambuStudio). The A1 templates
still come from the installed OrcaSlicer's resources: that is the production arrangement
(profiles.install is identity-checked against the OrcaSlicer tree), and Bambu Studio then slices
from the resolved production profiles. Until this file existed, every Bambu Studio code path was
covered only with the slicer process mocked, and docs/BAMBU-LAB.md recorded "No real Bambu Studio
A1 slice has been run yet".

The first runs of this file found why that mattered (#434): the real slicer writes no
"; generated by BambuStudio" line (its identity is the header block's "; BambuStudio <version>"),
so slice_model rejected every real Bambu slice after slicing succeeded. The #434 fix reads
identity from the header block (core.slice_guard.generator_identity) and the Bambu Lab guard
accepts either verified slicer, so the two production-flow tests below run for real.

Locally: install both Flatpaks like the CI job does, then
PRINT_HANDY_REAL_SLICER=1 PRINT_HANDY_REAL_BAMBU=1 python3 -m pytest -s tests/slicer/test_bambu_real_a1.py
"""
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

from print_handy import printers, settings
from print_handy.printers.bambulab import profiles

from .test_orca_real import WORK, write_cube
from .test_orca_real_bambu_a1 import adapter_for, installed_resources, toolpath_bounds

REAL = os.environ.get("PRINT_HANDY_REAL_SLICER") == "1"
REAL_BAMBU = os.environ.get("PRINT_HANDY_REAL_BAMBU") == "1"
pytestmark = pytest.mark.skipif(not (REAL and REAL_BAMBU),
                                reason="set PRINT_HANDY_REAL_SLICER=1 and PRINT_HANDY_REAL_BAMBU=1 "
                                       "to slice with the real Bambu Studio CLI")
ROOT = Path(__file__).resolve().parents[2]


@pytest.fixture
def work():
    WORK.mkdir(exist_ok=True)
    import tempfile
    with tempfile.TemporaryDirectory(dir=WORK) as tmp:
        yield Path(tmp)


@pytest.fixture
def a1(work):
    """The A1 adapter with templates generated from the installed OrcaSlicer (production identities only)."""
    adapter = adapter_for("bambulab.a1", work / "hermes")
    known = profiles.install(adapter, installed_resources())
    print(f"\nA1 profiles: {known['label']} from {installed_resources()}")
    return adapter


def bambu_flow(work, stl, **overrides):
    """tests.printers.a1_flow (slice_job -> verification -> bambu_handoff -> print_now) in a subprocess.

    overrides are extra environment for the flow process; the caller picks the slicer path there.
    """
    env = {**os.environ, "PRINT_HANDY__PRINTER__MODEL": "bambulab.a1",
           "PRINT_HANDY__PATHS__STATE_HOME": str(work / "flow-hermes"), **overrides}
    out = subprocess.run([sys.executable, "-m", "tests.printers.a1_flow", str(work / "flow"), "--stl", str(stl),
                          "--resources", str(installed_resources())],
                         cwd=ROOT, capture_output=True, text=True, env=env, timeout=900)
    line = next((l for l in out.stdout.splitlines() if l.startswith("A1_FLOW ")), None)
    assert line, out.stdout[-3000:] + out.stderr[-3000:]
    result = json.loads(line[len("A1_FLOW "):])
    print(f"\nA1 Bambu flow: {json.dumps(result, indent=1)}")
    return result


def test_bambu_studio_cli_is_the_configured_command():
    """The configured [bambu] command starts the real Bambu Studio and answers its CLI help."""
    from print_handy.core import orca_adapter
    result = subprocess.run([*orca_adapter.BAMBU_COMMAND, "--help"], capture_output=True, text=True, timeout=300)
    log = result.stdout + result.stderr
    print(f"\n$ {' '.join(orca_adapter.BAMBU_COMMAND)} --help\nexit {result.returncode}\n{log[:2000]}")
    assert result.returncode == 0
    assert "BambuStudio" in log


def test_bambu_studio_cli_slices_a_cube_with_the_a1_templates(work, a1):
    """The binary's own CLI slicing path, driven exactly the way slice_model drives it
    (datadir + the A1 machine/process/filament templates): a real slice, a real header block."""
    from print_handy.core import orca_adapter
    templates = a1.pinned_templates()
    out = work / "cli-out"
    out.mkdir()
    command = [*orca_adapter.BAMBU_COMMAND, "--datadir", str(work / "datadir"),
               "--load-settings", f"{templates / 'machine.json'};{templates / 'process.json'}",
               "--load-filaments", str(templates / "filament.json"),
               "--arrange", "1", "--orient", "0", "--ensure-on-bed",
               "--allow-newer-file", "--slice", "0", "--outputdir", str(out),
               str(write_cube(work / "cube.stl", 20))]
    result = subprocess.run(command, capture_output=True, text=True, timeout=600)
    log = result.stdout + result.stderr
    print(f"\n$ {' '.join(command)}\nexit {result.returncode}\n{log[-2000:]}")
    assert result.returncode == 0
    gcode = out / "plate_1.gcode"
    assert gcode.is_file() and gcode.stat().st_size > 100_000
    lines = gcode.read_text(errors="replace").splitlines()
    # The real identity of a Bambu Studio slice: a header block, not a "generated by" line (#434).
    assert lines[0] == "; HEADER_BLOCK_START" and lines[1].startswith("; BambuStudio ")
    assert any(l.startswith("; total layer number:") for l in lines[:12])


def test_a1_bambu_studio_primary_production_slice(work, a1):
    """[printer] slicer: bambu_studio is the Bambu Lab default: Bambu Studio slices, the result
    verifies, packages as .gcode.3mf and print_now still refuses (offline flow)."""
    result = bambu_flow(work, write_cube(work / "cube.stl", 20),
                        PRINT_HANDY__PRINTER__SLICER="bambu_studio")
    assert "error" not in result, result
    assert result["printer_model"] == "bambulab.a1" and result["gcode_verified"] is True
    assert result["packages"] and result["print_now"].startswith("REFUSED: Bambu Lab A1")
    assert result["job_unchanged_by_print_now"] is True
    text = Path(result["sliced"]).read_text(errors="replace")
    lines = text.splitlines()
    assert lines[0] == "; HEADER_BLOCK_START" and lines[1].startswith("; BambuStudio ")
    assert a1.gcode_problems(text) == []
    bounds = toolpath_bounds(text)
    print(f"A1 Bambu Studio extruding toolpath bounds (mm): {bounds}")
    assert 0 <= bounds["X"][0] and bounds["X"][1] <= 256 and 0 <= bounds["Y"][0] and bounds["Y"][1] <= 256
    assert 0 < bounds["Z"][0] and bounds["Z"][1] <= 20.5


def test_orca_failure_falls_back_to_bambu_studio(work, a1):
    """With [printer] slicer: orca and an Orca command that cannot run at all (PRINT_HANDY_ORCA_CMD=/bin/false),
    the one isolated fallback attempt slices with Bambu Studio and the job still verifies and packages."""
    result = bambu_flow(work, write_cube(work / "cube.stl", 20),
                        PRINT_HANDY__PRINTER__SLICER="orca", PRINT_HANDY_ORCA_CMD="/bin/false")
    assert "error" not in result, result
    assert result["printer_model"] == "bambulab.a1" and result["gcode_verified"] is True
    # /bin/false cannot generate anything: this output can only be the Bambu Studio fallback's.
    assert result["packages"] and result["print_now"].startswith("REFUSED: Bambu Lab A1")
    text = Path(result["sliced"]).read_text(errors="replace")
    lines = text.splitlines()
    assert lines[0] == "; HEADER_BLOCK_START" and lines[1].startswith("; BambuStudio ")
    assert a1.gcode_problems(text) == []
