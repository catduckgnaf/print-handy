def prusa_table_source(path):
    """Two separate objects side by side; the table's top overhangs its leg, so
    supports generate. Separate objects keep the derived plate's per-part items
    clear of each other in plan view (the plate export flattens volumes into
    items; stacked volumes of one object are the whole-model fixture above)."""
    table = _mesh_xml(_box(30, 20, 3, (60, 55, 12)) + _box(6, 6, 12, (72, 62, 0)))
    model = ('<?xml version="1.0" encoding="UTF-8"?>'
             f'<model unit="millimeter" xmlns="{NS}"><resources>'
             f'<object id="1" name="Block" type="model">{_mesh_xml(_box(16, 16, 6, (20, 60, 0)))}</object>'
             f'<object id="2" name="Table" type="model">{table}</object>'
             '</resources><build>'
             '<item objectid="1" transform="1 0 0 0 1 0 0 0 1 0 0 0"/>'
             '<item objectid="2" transform="1 0 0 0 1 0 0 0 1 0 0 0"/>'
             '</build></model>')
    _write_package(path, {"3D/3dmodel.model": model,
                          "Metadata/Slic3r_PE.config": PRUSA_CONFIG,
                          "Metadata/Slic3r_PE_model.config": TABLE_MODEL_CONFIG})
    return path


def _decisions(manifest, state, picks):
    choices = {}
    for row in source_colors.canonical_prompts(manifest):
        slot = picks(row)
        choices[row["key"]] = model_job.resolve_filament_selection(
            state, dict(state["filament_slots"][str(slot)], slot=slot))
    return {"schema": "part_slots_v1", "mode": "per_part", "source_sha256": manifest["source_sha256"],
            "choices": choices}


def _tools(text):
    return {int(m.group(1)) for line in text.splitlines()
            if (m := re.match(r"\s*T(\d+)\s*(?:;.*)?$", line))}


def test_prusa_project_slices_with_its_support_filament():
    WORK.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=WORK) as tmp, \
            mock.patch.object(spoolman_client, "get_spool", return_value=None):
        tmp = Path(tmp)
        source = prusa_shelf_source(tmp / "shelf.3mf")
        state = json.loads(STATE.read_text())
        manifest = source_colors.inventory(source)
        assert manifest["support_filaments"] == {"base": 2, "interface": None}
        decisions = _decisions(manifest, state, lambda row: 2 if row["key"] == "filament:2" else 1)
        out, provenance, _configs = orca_adapter.slice_model(source, tmp / "slice", state,
                                                             color_decisions=decisions)
        text = Path(out).read_text(errors="replace")
        assert "PRUSA FOREIGN START" not in text
        assert "Original Prusa" not in text
        template_machine = json.loads((Path(orca_adapter.TEMPLATES) / "machine.json").read_text())
        assert f"; printer_model = {template_machine['printer_model']}" in text
        assert "; wall_loops = 4" in text  # the project-level Prusa setting, translated and kept
        assert "; support_filament = 2" in text  # the designated support filament, pointed at its spool
        assert 1 in _tools(text)  # and really loaded: the supports print on the second filament
        assert provenance["tool_mapping"] == {"0": 1, "1": 2}


def test_prusa_derived_plate_slices_as_one_filament():
    WORK.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=WORK) as tmp, \
            mock.patch.object(spoolman_client, "get_spool", return_value=None):
        tmp = Path(tmp)
        source = prusa_table_source(tmp / "table.3mf")
        state = json.loads(STATE.read_text())
        manifest = source_colors.inventory(source)
        decisions = _decisions(manifest, state, lambda row: 1)
        keys = [part["key"] for part in manifest["parts"]]
        plate = tmp / "plate.3mf"
        export_single_color_plate(source, plate, decisions, keys, slot_colors=state["filament_slots"])
        with zipfile.ZipFile(plate) as archive:  # the plate is still the author's package
            assert "Metadata/Slic3r_PE.config" in archive.namelist()
        out, _provenance, _configs = orca_adapter.slice_model(plate, tmp / "slice", state,
                                                              preserve_layout=True, filament_slot=1)
        text = Path(out).read_text(errors="replace")
        assert "PRUSA FOREIGN START" not in text
        assert "Original Prusa" not in text
        assert "; wall_loops = 4" in text
        assert "; support_filament = 0" in text  # one filament on the plate: supports use it
        # A one-filament AD5X slice issues no toolchange commands at all (the
        # loaded filament needs none); any other tool would mean a second one.
        assert _tools(text) <= {0}
