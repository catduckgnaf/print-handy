def _box(dx, dy, dz, offset=(0.0, 0.0, 0.0)):
    ox, oy, oz = offset
    v = [(ox, oy, oz), (ox + dx, oy, oz), (ox + dx, oy + dy, oz), (ox, oy + dy, oz),
         (ox, oy, oz + dz), (ox + dx, oy, oz + dz), (ox + dx, oy + dy, oz + dz), (ox, oy + dy, oz + dz)]
    faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
             (2, 3, 7), (2, 7, 6), (1, 2, 6), (1, 6, 5), (3, 0, 4), (3, 4, 7)]
    return [[v[a], v[b], v[c]] for a, b, c in faces]


def _mesh_xml(triangles):
    verts, index, tris = [], {}, []
    for tri in triangles:
        row = []
        for pt in tri:
            key = tuple(round(float(c), 6) for c in pt)
            if key not in index:
                index[key] = len(verts)
                verts.append(key)
            row.append(index[key])
        tris.append(row)
    vxml = ''.join(f'<vertex x="{x}" y="{y}" z="{z}"/>' for x, y, z in verts)
    txml = ''.join(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in tris)
    return f'<mesh><vertices>{vxml}</vertices><triangles>{txml}</triangles></mesh>'


def prusa_shelf_source(path):
    """Base plus a wider shelf on top: the shelf's rim overhangs, so supports generate."""
    model = ('<?xml version="1.0" encoding="UTF-8"?>'
             f'<model unit="millimeter" xmlns="{NS}"><resources>'
             f'<object id="2" name="Base" type="model">{_mesh_xml(_box(20, 20, 5, (40, 40, 0)))}</object>'
             f'<object id="3" name="Shelf" type="model">{_mesh_xml(_box(34, 34, 5, (33, 33, 5)))}</object>'
             '<object id="1" name="assembly" type="model"><components>'
             '<component objectid="2" transform="1 0 0 0 1 0 0 0 1 0 0 0"/>'
             '<component objectid="3" transform="1 0 0 0 1 0 0 0 1 0 0 0"/>'
             '</components></object>'
             '</resources><build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 0 0 0"/></build></model>')
    _write_package(path, {"3D/3dmodel.model": model,
                          "Metadata/Slic3r_PE.config": PRUSA_CONFIG,
                          "Metadata/Slic3r_PE_model.config": PRUSA_MODEL_CONFIG})
    return path


