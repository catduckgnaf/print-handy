"""Cross-slicer real-Orca tests (#1525, tranche D).

Skipped unless PRINT_HANDY_REAL_SLICER=1, like every slicer-tier test.
Inside that gate there are no further skips: the pinned Orca binary must
exist and run, the Cura fixture must slice through the production
translation, the editable export must reopen and slice in the real
Orca, and the statistics path (Orca statistics JSON vs verified G-code
comments) must prove one of its two paths on the real binary.

Fixture honesty: two Cura fixtures exist (see
tests/corpus/producer-fixtures/PROVENANCE.json). cura-spec-synthetic.3mf
is built to the Cura workspace-writer layout and this module says so;
cura-genuine.3mf was saved by the real UltiMaker Cura 5.8.1 application
through its own GUI under Xvfb, and its own Cura/version.ini is the
producer proof. The Prusa case slices the genuine fixture when the
provenance manifest records one, and otherwise asserts the manifest
honestly records that no genuine Prusa fixture is present yet — an
executed assertion, not a silent skip.
"""
import json
import os
import subprocess
from pathlib import Path

import pytest

from print_handy import settings
from print_handy.core import (author_settings, editable_export,
                              plate_statistics, source_descriptor)

REAL = os.environ.get("PRINT_HANDY_REAL_SLICER") == "1"
pytestmark = pytest.mark.skipif(
    not REAL, reason="set PRINT_HANDY_REAL_SLICER=1 to slice with the real Orca CLI")

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / "tests" / "corpus" / "producer-fixtures"
WORK = settings.ROOT / ".slicer-work"


def _orca_command():
    from print_handy.core import orca_adapter
    return orca_adapter._orca_command()


def _templates():
    templates = settings.current()["orca"]["templates"]
    return (templates / "machine.json", templates / "process.json",
            templates / "filament.json")


def _slice(source, out, *extra):
    machine, process, filament = _templates()
    out.mkdir(parents=True, exist_ok=True)
    command = [*_orca_command(),
               "--load-settings", f"{machine};{process}",
               "--load-filaments", str(filament),
               "--arrange", "1", "--orient", "0", "--ensure-on-bed",
               "--allow-newer-file", "--slice", "0",
               "--outputdir", str(out), *extra, str(source)]
    result = subprocess.run(command, capture_output=True, text=True, timeout=600)
    return result, out


@pytest.fixture(scope="module")
def work():
    WORK.mkdir(exist_ok=True)
    import tempfile
    with tempfile.TemporaryDirectory(dir=WORK) as tmp:
        yield Path(tmp)


def test_orca_binary_identity_is_real(work):
    command = _orca_command()
    assert command, "PRINT_HANDY_REAL_SLICER=1 but no Orca command is configured"
    result = subprocess.run([*command, "--help"], capture_output=True,
                            text=True, timeout=120)
    blob = (result.stdout + result.stderr).lower()
    assert "orcaslicer" in blob or "orca" in blob, (
        f"the configured slicer does not identify as OrcaSlicer: {blob[:200]}")


def test_cura_spec_synthetic_source_slices_with_translated_settings(work):
    fixture = FIXTURES / "cura-spec-synthetic.3mf"
    assert fixture.is_file()
    record = author_settings.read_project(fixture)
    assert record["format"] == "cura_project"
    assert record["author"]["layer_height"] == "0.16"
    result, out = _slice(fixture, work / "cura-out")
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]
    gcode = (out / "plate_1.gcode").read_text(errors="replace")
    assert "OrcaSlicer" in gcode.splitlines()[0] or "generated by OrcaSlicer" in gcode[:2000]
    # The fixture's own start G-code is a marker that must never leak.
    assert "SPEC SYNTHETIC START" not in gcode
    assert "SPEC SYNTHETIC END" not in gcode


def test_cura_genuine_source_is_proven_and_slices(work):
    """The genuine Cura fixture: saved by the real Cura 5.8.1 GUI.

    Its own Cura/version.ini is the producer proof; Print Handy's
    descriptor and author-settings readers must see the real stacks,
    and real Orca must slice its geometry.
    """
    import zipfile
    fixture = FIXTURES / "cura-genuine.3mf"
    provenance = json.loads((FIXTURES / "PROVENANCE.json").read_text())
    rows = {row["file"]: row for row in provenance["fixtures"]}
    assert rows["cura-genuine.3mf"]["class"] == "genuine"
    with zipfile.ZipFile(fixture) as archive:
        version = archive.read("Cura/version.ini").decode("utf-8", "replace")
    assert "cura_version = 5.8.1" in version
    described = source_descriptor.describe(fixture)
    assert described["kind"] == "cura"
    assert described["format"] == "cura_project"
    assert described["application"] == "UltiMaker Cura"
    record = author_settings.read_project(fixture)
    assert record["format"] == "cura_project"
    assert record["author"]["layer_height"] == "0.2"
    result, out = _slice(fixture, work / "cura-genuine-out")
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]


def test_editable_export_reopens_and_slices_in_real_orca(work):
    fixture = FIXTURES / "cura-spec-synthetic.3mf"
    target = work / "exported.3mf"
    report = editable_export.export_editable(fixture, target)
    assert report["source_sha256"]
    result, out = _slice(target, work / "export-out")
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]
    gcode = (out / "plate_1.gcode").read_text(errors="replace")
    assert "SPEC SYNTHETIC START" not in gcode


def test_prusa_genuine_fixture_state_is_honest(work):
    provenance = json.loads((FIXTURES / "PROVENANCE.json").read_text())
    rows = {row["file"]: row for row in provenance["fixtures"]}
    genuine = rows.get("prusa-genuine.3mf")
    if genuine is None:
        # No genuine fixture is recorded: the manifest must not pretend
        # otherwise, and the extended tier owns producing one.
        assert all(row["class"] != "genuine" or "prusa" not in row["file"]
                   for row in rows.values())
        return
    assert genuine["class"] == "genuine"
    fixture = FIXTURES / "prusa-genuine.3mf"
    assert fixture.is_file()
    assert source_descriptor.describe(fixture)["kind"] == "prusa"
    result, out = _slice(fixture, work / "prusa-out")
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]


def test_orca_statistics_path_is_proven_on_the_real_binary(work):
    stl = work / "cube.stl"
    from tests.slicer.test_orca_real import write_cube
    write_cube(stl, 20)
    result, out = _slice(stl, work / "stats-out", "--export-statistics")
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]
    gcode = (out / "plate_1.gcode").read_text(errors="replace")
    stats_files = sorted(out.rglob("*.statistics.json")) + sorted(out.rglob("statistics*.json"))
    if stats_files:
        weights = plate_statistics.parse_statistics_json(
            stats_files[0].read_text(errors="replace"))
        assert weights, "Orca wrote a statistics file but no per-filament weights parsed"
        print(f"statistics path proven: orca-statistics-json via {stats_files[0].name}")
    else:
        artifact = plate_statistics.build_plate_statistics(
            gcode_text=gcode,
            filaments=[{"source_extruder": 1, "material": "PLA"}])
        assert artifact["statistics_source"] == "gcode-comments", artifact
        assert artifact["filaments"][0]["estimated_grams"] is not None
        print("statistics path proven: gcode-comments (the pinned Orca wrote "
              "no statistics JSON for this slice)")
