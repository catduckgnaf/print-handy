def _orca_command():
    from print_handy.core import orca_adapter
    return orca_adapter._orca_command()


def _templates():
    templates = settings.current()["orca"]["templates"]
    return (templates / "machine.json", templates / "process.json",
            templates / "filament.json")


def _slice(source, out, *extra):
    machine, process, filament = _templates()
    out.mkdir(parents=True, exist_ok=True)
    command = [*_orca_command(),
               "--load-settings", f"{machine};{process}",
               "--load-filaments", str(filament),
               "--arrange", "1", "--orient", "0", "--ensure-on-bed",
               "--allow-newer-file", "--slice", "0",
               "--outputdir", str(out), *extra, str(source)]
    result = subprocess.run(command, capture_output=True, text=True, timeout=600)
    return result, out


