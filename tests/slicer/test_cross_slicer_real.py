def test_prusa_genuine_fixture_state_is_honest(work):
    provenance = json.loads((FIXTURES / "PROVENANCE.json").read_text())
    rows = {row["file"]: row for row in provenance["fixtures"]}
    genuine = rows.get("prusa-genuine.3mf")
    if genuine is None:
        # No genuine fixture is recorded: the manifest must not pretend
        # otherwise, and the extended tier owns producing one.
        assert all(row["class"] != "genuine" or "prusa" not in row["file"]
                   for row in rows.values())
        return
    assert genuine["class"] == "genuine"
    fixture = FIXTURES / "prusa-genuine.3mf"
    assert fixture.is_file()
    assert source_descriptor.describe(fixture)["kind"] == "prusa"
    result, out = _slice(fixture, work / "prusa-out")
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]


def test_orca_statistics_path_is_proven_on_the_real_binary(work):
    stl = work / "cube.stl"
    from tests.slicer.test_orca_real import write_cube
    write_cube(stl, 20)
    result, out = _slice(stl, work / "stats-out", "--export-statistics")
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]
    gcode = (out / "plate_1.gcode").read_text(errors="replace")
    stats_files = sorted(out.rglob("*.statistics.json")) + sorted(out.rglob("statistics*.json"))
    if stats_files:
        weights = plate_statistics.parse_statistics_json(
            stats_files[0].read_text(errors="replace"))
        assert weights, "Orca wrote a statistics file but no per-filament weights parsed"
        print(f"statistics path proven: orca-statistics-json via {stats_files[0].name}")
    else:
        artifact = plate_statistics.build_plate_statistics(
            gcode_text=gcode,
            filaments=[{"source_extruder": 1, "material": "PLA"}])
        assert artifact["statistics_source"] == "gcode-comments", artifact
        assert artifact["filaments"][0]["estimated_grams"] is not None
        print("statistics path proven: gcode-comments (the pinned Orca wrote "
              "no statistics JSON for this slice)")
