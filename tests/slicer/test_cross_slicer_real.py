def test_orca_binary_identity_is_real(work):
    command = _orca_command()
    assert command, "PRINT_HANDY_REAL_SLICER=1 but no Orca command is configured"
    result = subprocess.run([*command, "--help"], capture_output=True,
                            text=True, timeout=120)
    blob = (result.stdout + result.stderr).lower()
    assert "orcaslicer" in blob or "orca" in blob, (
        f"the configured slicer does not identify as OrcaSlicer: {blob[:200]}")


def test_cura_spec_synthetic_source_slices_with_translated_settings(work):
    fixture = FIXTURES / "cura-spec-synthetic.3mf"
    assert fixture.is_file()
    record = author_settings.read_project(fixture)
