def _problems(mutate, selection=None):
    status = _ready_status()
    mutate(status)
    return adapter_for(PRO).readiness_problems({}, status, selection)


def test_a_build_without_afc_is_refused():
    def drop_afc(status):
        for name in [n for n in status if n.startswith("AFC")]:
            del status[name]
    assert any("AFC" in p for p in _problems(drop_afc))


@pytest.mark.parametrize("mutate, words", [
    (lambda s: s["ff_toolchange"].update(state_ok=False, state_reason="T2 grab and dock disagree"),
     "T2 grab and dock disagree"),
    (lambda s: s.pop("ff_toolchange"), "ff_toolchange is not reporting"),
    (lambda s: s["toolchanger"].update(status="changing"), "tool change"),
    (lambda s: s["ff_toolchange"].update(docked_tools=[0, 2, 3]), "T1 is neither in its dock"),
    (lambda s: s["ff_toolchange"].update(calibrated_tools=[0, 1, 3]), "T2 is not calibrated"),
    (lambda s: s["ff_toolchange"].update(station_z=None), "station"),
    (lambda s: s["gcode_macro FF_BEFORE_PRINT_START"].update(prepare=0), "prepare off"),
    (lambda s: s["gcode_macro FF_BEFORE_PRINT_START"].update(defer_mesh=1), "defer_mesh on"),
    (lambda s: s.pop("gcode_macro FF_BEFORE_PRINT_START"), "FF_BEFORE_PRINT_START is not reporting"),
    (lambda s: s.pop("ff_print"), "ff_print is not reporting"),
    (lambda s: s["AFC"].update(error_state=True), "error state"),
    (lambda s: s["AFC_extruder e3"].update(tool_start_status=False), "no filament"),
    (lambda s: s["AFC"].update(units=["Toolchanger Tools", "ACE_1"]), "ACE unit"),
    (lambda s: s.pop("heater_generic chamber_heater"), "chamber_heater"),
])
def test_readiness_refuses_naming_the_cause(mutate, words):
    problems = _problems(mutate)
    assert any(words in p for p in problems), problems


def test_a_mounted_tool_counts_as_present():
    def mounted(status):
        status["ff_toolchange"].update(current_tool=1, docked_tools=[0, 2, 3])
    assert _problems(mounted) == []


def test_only_the_jobs_tools_are_gated():
    def t3_missing(status):
        status["ff_toolchange"].update(docked_tools=[0, 1, 2])
        status["AFC_extruder e3"]["tool_start_status"] = False
    assert _problems(t3_missing, {"tool_mapping": {"0": 1, "1": 2}}) == []
    assert _problems(t3_missing)


def test_multiple_mapping_on_is_judged_by_the_map_itself():
    # Shipped on: an identity map passes (the ready status above), a map
    # that puts two tools on one head does not.
    def shared(status):
        status["AFC_lane e0"]["map"] = ["T0", "T1"]
        status["AFC_lane e1"]["map"] = []
    assert any("more than one tool" in p or "T1" in p for p in _problems(shared))


def test_the_printers_remap_is_followed():
    def swap(status):
        status["AFC_lane e0"]["map"] = ["T1"]
        status["AFC_lane e1"]["map"] = ["T0"]
    assert _problems(swap) == []
    status = _ready_status()
    swap(status)
    assert adapter_for(PRO).tool_head_map(status) == {0: 1, 1: 0, 2: 2, 3: 3}

    def swap_and_empty_head(status):
        swap(status)
        status["AFC_extruder e1"]["tool_start_status"] = False
    problems = _problems(swap_and_empty_head, {"tool_mapping": {"0": 1}})
    assert any("T0 (toolhead 2) has no filament" in p for p in problems), problems


def test_status_reports_the_mounted_tool_from_ff_toolchange():
    status = _ready_status()
    assert adapter_for(PRO).normalize_status(status)["active_tool"] is None
    status["ff_toolchange"]["current_tool"] = 2
