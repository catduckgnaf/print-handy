def _ready_status(key=PRO):
    status = {"print_stats": {"state": "standby"}, "webhooks": {"state": "ready"},
              "heater_bed": {"temperature": 24.0},
              "ff_toolchange": {"current_tool": -1, "state_ok": True,
                                "state_reason": "all tools docked",
                                "calibrated_tools": [0, 1, 2, 3], "station_z": -3.1,
                                "print_offset_ready": True, "docked_tools": [0, 1, 2, 3]},
              "toolchanger": {"status": "ready", "tool_number": -1},
              "ff_print": {"active": False, "filename": None},
              "gcode_macro FF_BEFORE_PRINT_START": {"prepare": 1, "prepare_on_m23": 0,
                                                    "defer_mesh": 0},
              # Reforge ships enable_multiple_mapping: True (ff-afc.cfg).
              "AFC": {"error_state": False, "units": ["Toolchanger Tools"],
                      "multiple_tool_mapping": True,
                      "lanes": [f"e{n}" for n in range(4)]},
              "heater_generic chamber_heater": {"temperature": 24.0, "target": 0.0},
              # Asked for and unknown on this firmware: Moonraker answers {}.
              "zmod_color": {}, "creator5_toolchanger": {}}
    for tool in range(4):
        status["extruder" if tool == 0 else f"extruder{tool}"] = {"temperature": 24.0}
        status[f"AFC_extruder e{tool}"] = {"tool_start_status": True, "on_shuttle": False}
        # AFC_lane get_status: extruder is the AFC_extruder's name (AFC 8ba0f7bf).
        status[f"AFC_lane e{tool}"] = {"map": [f"T{tool}"], "extruder": f"e{tool}",
                                       "load": True, "material": "PLA"}
    if key == BASE:
        del status["heater_generic chamber_heater"]
    return status


