def _status_of(objects):
    return {name: {"x": 1} for name in objects}


def test_a_reforge_model_on_another_firmware_names_it():
    a = adapter_for(PRO)
    on_oc = {**_ready_status(), **_status_of(["creator5_toolchanger"])}
    for name in ("ff_toolchange", "ff_print"):
        on_oc.pop(name)
    assert any("running OpenCreator, not Reforge" in p for p in a.readiness_problems({}, on_oc))
    on_zmod = {**_ready_status(), "zmod_color": {"active_tool_id": 0}}
    for name in ("ff_toolchange", "ff_print"):
        on_zmod.pop(name)
    assert any("running ZMod, not Reforge" in p for p in a.readiness_problems({}, on_zmod))


def test_zmod_and_opencreator_models_on_reforge_name_reforge():
    status = _status_of(REFORGE_AFC)
    assert "running Reforge, not ZMod" in " ".join(
        adapter_for("flashforge.creator5_pro").readiness_problems({}, status))
    assert firmware_check.opencreator_mismatch_problem(status) is None
    assert "running Reforge, not OpenCreator" in " ".join(
        adapter_for("flashforge_opencreator.creator5_pro").readiness_problems({}, status))


