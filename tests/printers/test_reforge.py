def test_ff_print_derivation_reads_the_first_matching_lines():
    start = start_contract.derive_start(SLICED_PRO)
    assert start == start_contract.DerivedStart(bed=60, nozzle=220, tool=1, layer=0.2)


def test_a_matching_file_has_no_start_problems():
    assert start_contract.start_problems(SLICED_PRO, 60, 220) == []
    assert adapter_for(PRO).start_synthesis_problems(SLICED_PRO, 60, 220) == []


def test_derivation_truncates_to_whole_degrees_like_the_firmware():
    text = SLICED_PRO.replace("M104 S220", "M104 S215.5")
    assert start_contract.derive_start(text).nozzle == 215
    problems = start_contract.start_problems(text, 60, 215.5)
    assert any("215 C" in p and "215.5" in p for p in problems)


def test_first_match_wins_even_at_zero():
    # ff_print takes the first M140/M190 line and keeps it only above 0.
    text = "M140 S0\n" + SLICED_PRO
    assert start_contract.derive_start(text).bed is None
    assert any("bed" in p for p in start_contract.start_problems(text, 60, 220))


