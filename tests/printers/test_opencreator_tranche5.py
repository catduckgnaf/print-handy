"""Tranche 5 tests for the OpenCreator Creator models (#1490): per-print start overrides.

Offline, no printer, network or slicer. The rule under test: an explicit
C5_PRINT_START line opts the file out of the dispatcher's synthesis, and
the firmware then fills in nothing for it. So an override must arrive on
the full line the dispatcher would have synthesized, never on a line of
overrides alone (which would start the print with no TOOL, HOTEND or
BED). The dispatcher's order is creator5_start_command in the fork's
klippy/extras/virtual_sdcard.py, read for behavior only. Guidance from
Cartrigger (OpenCreator) on #1490.
"""

import pytest

from print_handy import printers, settings
from print_handy.printers.flashforge_opencreator import start_contract as sc

from .test_adapters import a1_fixture

KEYS = ("flashforge_opencreator.creator5", "flashforge_opencreator.creator5_pro")

# A two-tool Orca file: T1 first, M140/M190 bed, M104 nozzle preheat, and the
# config block with per-slot lists the dispatcher reads.
TWO_TOOL = "\n".join([
    "; generated by OrcaSlicer 2.3.1",
    "; first_layer_height = 0.2",
    "M140 S65",
    "M104 S215",
    "T1",
    "M190 S65",
    "G1 X10 Y10",
    "; filament used [mm] = 0.00,120.50,33.10,0.00",
    "; nozzle_temperature_initial_layer = 210,215,230,200",
    "; idle_temperature = 0,0,170,0",
    "; filament_type = PLA;PETG;\"PLA-CF\";PLA",
    "",
])


def _count_start_lines(text):
    return sum(1 for line in text.splitlines()
               if line.strip().upper().startswith("C5_PRINT_START"))


def _load(key, **env):
    return settings.load(local=False, environ={
        "PRINT_HANDY__PRINTER__MODEL": key,
        "PRINT_HANDY__PATHS__STATE_HOME": str(a1_fixture.HERMES), **env})


# ------------------------------------------------------------ the line itself

def test_default_settings_leave_the_file_to_the_firmware():
    assert sc.override_params({}) == {}
    assert sc.with_overrides(TWO_TOOL, {}) == TWO_TOOL
    assert _count_start_lines(TWO_TOOL) == 0


def test_one_override_writes_exactly_one_full_line_in_dispatcher_order():
    overrides = sc.override_params({"opencreator_purge_line": "off"})
    assert overrides == {"PURGE_LINE": 0}
    out = sc.with_overrides(TWO_TOOL, overrides)
    assert _count_start_lines(out) == 1
    first = out.splitlines()[0]
    assert first == (
        "C5_PRINT_START TOOL=1 HOTEND=215 BED=65 FIRST_LAYER_HEIGHT=0.2 "
        "MATERIAL0=PLA MATERIAL1=PETG MATERIAL2=PLA-CF MATERIAL3=PLA "
        "USED_TOOLS=1,2 HOTEND2=230 IDLE2=170 PURGE_LINE=0")
    # Everything after the new line is the sliced file, byte for byte.
    assert out[len(first) + 1:] == TWO_TOOL


def test_one_override_still_passes_the_start_check():
    out = sc.with_overrides(TWO_TOOL, sc.override_params({"opencreator_bed_leveling": "on"}))
    start = sc.synthesize_start(out)
    assert start.explicit and start.args["TOOL"] == 1 and start.args["BED_LEVELING"] == 1
    assert sc.start_problems(out, bed=65, hotend=215) == []


def test_an_overrides_only_line_is_what_the_start_check_refuses():
    # The bug this rebuild fixes: a line of overrides alone names no HOTEND.
    bad = "C5_PRINT_START PURGE_LINE=0 BUILDPLATE_CHECK=0\n" + TWO_TOOL
    assert any("names no HOTEND" in p for p in sc.start_problems(bad, bed=65, hotend=215))


def test_buildplate_check_is_sent_only_when_turned_off():
    assert sc.override_params({"opencreator_buildplate_check": "printer"}) == {}
    assert sc.override_params({"opencreator_buildplate_check": "off"}) == {"BUILDPLATE_CHECK": 0}
    line = sc.explicit_start_line(TWO_TOOL, {"BUILDPLATE_CHECK": 0})
    assert line.endswith(" BUILDPLATE_CHECK=0")


def test_chamber_from_the_file_rides_on_the_line():
    pro = "M141 S45\n" + TWO_TOOL
    line = sc.explicit_start_line(pro, {"PURGE": 0})
    assert " CHAMBER=45 PURGE=0" in line


@pytest.mark.parametrize("value", ["yes", "ON", 1, True, ""])
def test_a_bad_switch_value_is_refused(value):
    with pytest.raises(ValueError, match="opencreator_purge"):
        sc.override_params({"opencreator_purge": value})


def test_a_bad_buildplate_value_is_refused():
    with pytest.raises(ValueError, match="opencreator_buildplate_check"):
        sc.override_params({"opencreator_buildplate_check": "on"})


def test_a_file_with_its_own_line_is_refused_not_given_a_second():
    own = "C5_PRINT_START TOOL=0 HOTEND=210 BED=60\n" + TWO_TOOL
    with pytest.raises(ValueError, match="already carries"):
        sc.with_overrides(own, {"PURGE": 0})


def test_a_file_with_no_hotend_is_refused():
    with pytest.raises(ValueError, match="no hotend temperature"):
        sc.with_overrides("M140 S60\nG1 X1\n", {"PURGE": 0})


# ------------------------------------------------------------ settings and adapter

@pytest.mark.parametrize("key", KEYS)
def test_adapter_finalize_output_applies_the_settings(key):
    adapter = printers.get(key, _load(key, PRINT_HANDY__PRINTER__OPENCREATOR_PURGE="off",
                                      PRINT_HANDY__PRINTER__OPENCREATOR_BUILDPLATE_CHECK="off"))
    out = adapter.finalize_output(TWO_TOOL)
    assert _count_start_lines(out) == 1
    assert out.splitlines()[0].endswith(" PURGE=0 BUILDPLATE_CHECK=0")
    assert adapter.start_synthesis_problems(out, bed=65, hotend=215) == []


@pytest.mark.parametrize("key", KEYS)
def test_adapter_finalize_output_is_a_no_op_by_default(key):
    adapter = printers.get(key, _load(key))
    assert adapter.finalize_output(TWO_TOOL) == TWO_TOOL


def test_other_printers_finalize_output_is_a_no_op():
    adapter = printers.get("flashforge.ad5x", _load("flashforge.ad5x"))
    assert adapter.finalize_output(TWO_TOOL) == TWO_TOOL


def test_settings_refuse_a_bad_value():
    with pytest.raises(settings.SettingsError, match="opencreator_purge_line"):
        _load(KEYS[0], PRINT_HANDY__PRINTER__OPENCREATOR_PURGE_LINE="maybe")


def test_settings_refuse_the_keys_on_other_firmware():
    with pytest.raises(settings.SettingsError, match="only applies to Flashforge printers on OpenCreator"):
        _load("flashforge.ad5x", PRINT_HANDY__PRINTER__OPENCREATOR_PURGE="off")


def test_defaults_are_accepted_on_any_printer_because_the_config_page_submits_them():
    _load("flashforge.ad5x", PRINT_HANDY__PRINTER__OPENCREATOR_PURGE="printer",
          PRINT_HANDY__PRINTER__OPENCREATOR_BUILDPLATE_CHECK="printer")


def test_a_bad_value_is_refused_on_any_printer():
    with pytest.raises(settings.SettingsError, match="opencreator_purge"):
        _load("flashforge.ad5x", PRINT_HANDY__PRINTER__OPENCREATOR_PURGE="maybe")
