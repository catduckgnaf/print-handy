def test_a1_is_a_model_of_the_shared_bambu_vendor():
    assert printers.MODELS[A1] is MODEL or printers.MODELS[A1] == MODEL
    assert printers.MODELS[A1].vendor is VENDOR is printers.VENDORS["bambulab"]
    a = adapter_for(A1)
    assert isinstance(a, A1Adapter) and isinstance(a, BambuOfflineAdapter)
    # Connection, start code, slicers and delivery come from VENDOR only.
    assert a.connection == VENDOR.connection == "bambulab_lan"
    assert a.transport == "bambulab_lan" and not (ROOT / "print_handy/printers/bambulab/vendor.py").exists()
    assert not {"connection", "delivery", "slicers", "start_code"} & (set(facts.A1) | set(facts.VENDOR_FACTS))
    vol = a.build_volume()
    assert (vol.bed_mm, vol.max_height_mm) == ((256.0, 256.0), 256.0)
    # The AMS Lite is the A1's slot system (#671): multi_slot, four slots.
    assert (a.slot_count, a.multi_slot, a.has_native_screen) == (4, True, False)
    assert a.supported_nozzle_sizes == (0.4,) and a.supported_nozzle_types == ("stainless_steel", "hardened_steel")


