def template(key, name="machine"):
    return json.loads((adapter_for(key).templates_dir() / f"{name}.json").read_text())


def state():
    st = copy.deepcopy(json.loads(STATE.read_text()))
    st.update(printer="Bambu Lab A1", moonraker_url="", filament_slots={}, bed_mm=[256, 256], max_print_height_mm=256)
    st["nozzle"]["type"] = "stainless_steel"
    return st


def render(text):
    """Template -> G-code the way Orca would resolve it, keeping every conditional branch."""
    def value(match):
        inner = match.group(0)[1:-1]
        key = re.match(r"\w*", inner).group(0)
        return PLACEHOLDER_VALUES.get(key, "1")
    text = guard._CONTROL.sub("", text)
    return re.sub(r"\{[^{}]*\}|\[[^\[\]]*\]", value, text)


def filament_named(name):
    """The generated A1 filament template whose profile is name."""
    folder = adapter_for(A1).pinned_templates_folder()
    for path in [*sorted((folder / profiles.FILAMENTS).glob("*.json")), folder / "filament.json"]:
        data = json.loads(path.read_text())
        if data["name"] == name:
            return data
    raise KeyError(name)


def identity_lines(generator):
    """The identity line as the real slicer writes it (#434): OrcaSlicer puts a "; generated by" line
    inside the header block; Bambu Studio writes no such line — its identity is the header block's
    bare "; BambuStudio <version>" line. Anything else keeps the generated-by form."""
    if generator.startswith("BambuStudio"):
        return [f"; {generator}"]
    return [f"; generated by {generator}"]


def a1_gcode(body=None, *, material="PLA", nozzle="0.4", nozzle_type="stainless_steel", bed=60, hotend=210,
             tags=False, plate="Textured PEI Plate", generator="OrcaSlicer 2.4.2", filament="Generic PLA @BBL A1",
             blocks=None):
    """Synthetic A1 G-code in real Orca 2.4.2 Bambu layout: config block first, Orca's preamble, "; FEATURE: Custom"
    before the vendor start and end blocks, "; CHANGE_LAYER" per layer, a vendor timelapse park in the toolpath.
    tags=True adds the start/end tags Orca 2.5+ writes. filament names the profile in filament_settings_id; its
    filament blocks are rendered unless blocks names another profile. The generator identity is written the
    way the named slicer really writes it (identity_lines). Not real slicer output."""
    machine, settings_id, filament = template(A1), filament, filament_named(blocks or filament)
    start = render(machine["machine_start_gcode"]).replace("M104 S210", f"M104 S{hotend}").replace("M140 S60", f"M140 S{bed}")
    timelapse = "; SKIPPABLE_START\n" + render(machine["time_lapse_gcode"]) + "G1 X100 Y120 F18000\n; SKIPPABLE_END\n"
    body = body if body is not None else (
        "G1 E-.8 F1800\nG1 Z.2 F720\nG1 X100 Y100 F30000\nG1 E.8 F1800\n; FEATURE: Outer wall\n; LINE_WIDTH: 0.42\n"
        "G1 X120 Y100 E.8\nG1 X120 Y120 E.8\nG1 X100 Y120 E.8\nG1 X100 Y100 E.8\n" + timelapse +
        "; CHANGE_LAYER\n; Z_HEIGHT: 0.4\nG1 Z.4\nG1 X100 Y100\nG1 X120 Y100 E.8\nG1 E-.8\nM106 S0\n")
    return "\n".join([
        "; HEADER_BLOCK_START", *identity_lines(generator), "; model printing time: 5m; total estimated time: 9m",
        "; HEADER_BLOCK_END", "; CONFIG_BLOCK_START", "; printer_model = Bambu Lab A1",
        "; printer_settings_id = Bambu Lab A1 0.4 nozzle", "; print_settings_id = 0.20mm Standard @BBL A1",
        f"; filament_settings_id = \"{settings_id}\"", f"; filament_type = {material}",
        f"; nozzle_diameter = {nozzle}", f"; nozzle_type = {nozzle_type}", f"; curr_bed_type = {plate}",
        "; z_hop_types = Normal Lift",
        "; enable_arc_fitting = 0", "; brim_type = outer_only", "; CONFIG_BLOCK_END", "; EXECUTABLE_BLOCK_START",
        "M73 P0 R20", "M201 X6000 Y6000 Z1500 E5000", "M204 P12000 R5000 T12000",
        "; FEATURE: Custom", start, render(filament["filament_start_gcode"][0]),
        *(["; MACHINE_START_GCODE_END"] if tags else []), "G90", "G21", "M83 ; use relative distances for extrusion",
        "M981 S1 P20000", "M106 S0", "; CHANGE_LAYER", "; Z_HEIGHT: 0.2", body,
        *(["; MACHINE_END_GCODE_START"] if tags else []), "; FEATURE: Custom",
        render(filament["filament_end_gcode"][0]), render(machine["machine_end_gcode"]), "M73 P100 R0",
        "; EXECUTABLE_BLOCK_END", ""])


def ad5x_gcode():
    """What an AD5X slice looks like: its start (M190/M104 preamble + START_PRINT ... MESH=) and END_PRINT."""
    ad5x = adapter_for(AD5X)
    start = ad5x.machine_start_gcode(template(AD5X)["machine_start_gcode"], "MESH_DATA")
    start = start.replace("[bed_temperature_initial_layer_single]", "60").replace("[nozzle_temperature_initial_layer]", "210")
    text = a1_gcode().replace("; printer_model = Bambu Lab A1", "; printer_model = Flashforge AD5X")
    pre, rest = text.split("; FEATURE: Custom\n", 1)
    return pre + "; FEATURE: Custom\n" + start + "\n" + rest.split("; CHANGE_LAYER", 1)[1].join(["; CHANGE_LAYER", ""]) \
        .rsplit("; FEATURE: Custom", 1)[0] + "; FEATURE: Custom\nEND_PRINT\n; EXECUTABLE_BLOCK_END\n"


