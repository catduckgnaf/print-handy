"""The temperatures Orca receives come from the job's own spool, on every printer.

2026-10-31: a Silk PLA spool in AD5X IFS slot 2 sliced at 210 °C, the printer-wide
temps_c left by an earlier PLA spool, instead of 220 °C (PLA 210 + the #512 Silk
adjustment). resolve_material_temperatures was right; the slice never asked it. These
tests read the filament JSON slice_model hands Orca, so they fail on exactly that.
"""
import copy
import json
from pathlib import Path

import pytest

from print_handy import printers, settings
from print_handy.core import orca_adapter, slice_guard, spoolman_client

ROOT = Path(__file__).resolve().parents[2]
STATE = ROOT / "tests" / "pipeline" / "fixtures" / "printer_hardware.json"
MODEL = ROOT / "tests" / "corpus" / "cases" / "single-part" / "model.3mf"

# Expected targets written out, not derived, so a wrong resolver fails here too.
EXPECTED = {
    "PLA": (210, 60), "Pla": (210, 60), "PLA+": (215, 60), "PLA Plus": (215, 60), "Silk PLA": (220, 60),
    "PLA Silk": (220, 60), "Shiny Silk PLA": (220, 60), "Matte PLA": (215, 60), "PLA-CF": (215, 60),
    "PETG": (240, 85), "PETG-CF": (245, 85), "ABS": (245, 100), "ASA": (260, 105), "TPU": (230, 50),
}
# Models whose Orca profiles ship in the repo, so CI can slice them offline. The others (Prusa,
# Creality K1, Qidi, Elegoo SDCP, Snapmaker U1, Bambu Lab, stock-firmware AD5X) read profiles from the
# host's state folder at runtime; their temperatures come from the same slice_temperatures call.
ORCA_IN_REPO = sorted(m for m in printers.MODELS
                      if m.split(".")[0] in {"flashforge", "klipper", "octoprint", "sovol", "sovol_marlin"})
# One model per transport / vendor family that slices offline.
FAMILIES = ["flashforge.ad5x", "flashforge.creator5", "klipper.generic", "sovol.sv06", "sovol_marlin.sv06",
            "octoprint.ender3"]


def adapter_for(model):
    return printers.get(model, settings.load(local=False, environ={"PRINT_HANDY__PRINTER__MODEL": model}))


def material_refused(adapter, material, tmp_path):
    """A printer that has no checked profile for a material refuses it before Orca (Bambu Lab)."""
    try:
        adapter.filament_template(Path(adapter.config.get("orca_templates", tmp_path)), material)
    except Exception:
        return True
    return False


@pytest.fixture
def slice_inputs(tmp_path, monkeypatch):
    monkeypatch.setattr(orca_adapter, "ORCA_COMMAND", list(settings.load(local=False, environ={})["orca"]["command"]))
    monkeypatch.setattr(orca_adapter, "pre_slice", lambda **k: slice_guard.Result())
    monkeypatch.setattr(orca_adapter, "post_slice", lambda *a, **k: slice_guard.Result())
    monkeypatch.setattr(orca_adapter.sg, "enforce_approved_baseline", lambda out, **k: slice_guard.Result())

    def run(command, **_kwargs):
        folder = Path(command[command.index("--outputdir") + 1])
        material = json.loads((folder / "filament.json").read_text())["filament_type"][0]
        # The header Orca writes: a tool change and the quoted per-tool filament type.
        header = f'T0\n; filament_type = "{material}"\n; filament_colour = #0C6283\n'
        (folder / "plate_1.gcode").write_text(
            header + "; generated by OrcaSlicer 2.4.2\nM104 S0\nG90\nG1 X1 Y1 Z0.2 E1\nEND_PRINT\n" * 40)
        return type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})()

    monkeypatch.setattr(orca_adapter.subprocess, "run", run)
    spools = {}  # spoolman_id -> Spoolman spool record the mocked client returns
    monkeypatch.setattr(spoolman_client, "get_spool", lambda sid, **k: spools.get(int(sid)))
    monkeypatch.setattr(spoolman_client, "note_unavailable_once", lambda *a, **k: None)

    def slice_for(model, state, **kw):
        folder = tmp_path / model.replace(".", "_")
        adapter = adapter_for(model)
        orca_adapter.slice_model(MODEL, folder, state, adapter=adapter, **kw)
        filament = json.loads((folder / "filament.json").read_text())
        nozzle = {int(filament["nozzle_temperature"][0]), int(filament["nozzle_temperature_initial_layer"][0])}
        beds = {int(filament[k][0]) for k in ("cool_plate_temp", "hot_plate_temp", "textured_plate_temp")
                if k in filament}
        assert len(nozzle) == 1 and len(beds) == 1, (nozzle, beds)
        return nozzle.pop(), beds.pop(), filament

    return type("Inputs", (), {"slice": staticmethod(slice_for), "spools": spools, "tmp": tmp_path})


def stale_state(material, spool_id=17):
    """The active spool is `material`, but temps_c and its resolution are an earlier PLA spool's
    (what slot selection, active-spool sync and Spoolman slot sync all leave behind)."""
    state = copy.deepcopy(json.loads(STATE.read_text()))
    state["temps_c"] = {"nozzle": 210, "bed": 60}
    state["temperature_resolution"] = {"material_family": "PLA", "material": "PLA", "spoolman_id": 10,
                                       "sources": {"nozzle": "material default", "bed": "material default"},
                                       "source": "material default"}
    state["spool"] = {**state["spool"], "spoolman_id": spool_id, "name": "job spool", "material": material}
    state["filament_slots"] = {"1": {"slot": 1, "spoolman_id": spool_id, "material": material,
                                     "physical_color_verified": True, "hex": "0C6283"}}
    return state


def nozzle_effective(model, nozzle):
    """The adapter's nozzle-type rule (core/nozzle.effective_nozzle_temperature) may raise a target."""
    from print_handy.core.nozzle import effective_nozzle_temperature
    state = json.loads(STATE.read_text())
    return int(effective_nozzle_temperature((state.get("nozzle") or {}).get("type", "hardened_steel"), nozzle))


@pytest.mark.parametrize("model", ORCA_IN_REPO)
@pytest.mark.parametrize("material", ["PLA", "Silk PLA"])
def test_every_printer_slices_the_job_spool_temperature_not_a_stale_one(slice_inputs, model, material):
    adapter = adapter_for(model)
    if material_refused(adapter, material, slice_inputs.tmp):
        pytest.skip(f"{model} has no checked profile for {material}")
    nozzle, bed, _ = slice_inputs.slice(model, stale_state(material))
    want_nozzle, want_bed = EXPECTED[material]
    assert (nozzle, bed) == (nozzle_effective(model, want_nozzle), want_bed)


@pytest.mark.parametrize("model", FAMILIES)
@pytest.mark.parametrize("material", sorted(EXPECTED))
def test_material_matrix_reaches_orca_for_each_printer_family(slice_inputs, model, material):
    adapter = adapter_for(model)
    if material_refused(adapter, material, slice_inputs.tmp):
        pytest.skip(f"{model} has no checked profile for {material}")
    nozzle, bed, filament = slice_inputs.slice(model, stale_state(material))
    want_nozzle, want_bed = EXPECTED[material]
    assert (nozzle, bed) == (nozzle_effective(model, want_nozzle), want_bed)
    assert filament["filament_type"] == [material]


def test_ifs_slot_swap_resolves_the_slot_spool_temperature(slice_inputs):
    """The incident: active spool PLA #10 at 210, job on IFS slot 2 holding Silk PLA #17."""
    state = copy.deepcopy(json.loads(STATE.read_text()))
    state["temperature_resolution"] = {"material_family": "PLA", "material": "PLA", "spoolman_id": 10,
                                       "sources": {}, "source": "material default"}
    state["filament_slots"]["2"] = {"spoolman_id": 17, "color": "rose red blue green", "material": "Silk PLA",
                                    "hex": "0C6283", "physical_color_verified": True}
    slice_inputs.spools[17] = {"id": 17, "filament": {"material": "Silk PLA", "settings_extruder_temp": None,
                                                      "settings_bed_temp": None}}
    nozzle, bed, _ = slice_inputs.slice("flashforge.ad5x", state, filament_slot=2)
    assert (nozzle, bed) == (nozzle_effective("flashforge.ad5x", 220), 60)


def test_spoolman_temperatures_win_and_are_not_adjusted(slice_inputs):
    state = stale_state("Silk PLA")
    slice_inputs.spools[17] = {"id": 17, "filament": {"material": "Silk PLA", "settings_extruder_temp": 205,
                                                      "settings_bed_temp": 55}}
    assert slice_inputs.slice("flashforge.ad5x", state)[:2] == (nozzle_effective("flashforge.ad5x", 205), 55)


def test_spoolman_record_of_another_material_is_ignored_for_temperatures(slice_inputs):
    state = stale_state("Silk PLA")
    slice_inputs.spools[17] = {"id": 17, "filament": {"material": "PETG", "settings_extruder_temp": 250,
                                                      "settings_bed_temp": 80}}
    assert slice_inputs.slice("flashforge.ad5x", state)[:2] == (nozzle_effective("flashforge.ad5x", 220), 60)


def test_stored_temperatures_hold_only_for_the_spool_they_were_set_for(slice_inputs):
    state = stale_state("Silk PLA")
    state["temps_c"] = {"nozzle": 225, "bed": 65}
    state["temperature_resolution"] = {"material_family": "PLA", "material": "Silk PLA", "spoolman_id": 17,
                                       "sources": {}, "source": "operator setting"}
    assert slice_inputs.slice("flashforge.ad5x", state)[:2] == (nozzle_effective("flashforge.ad5x", 225), 65)
    state["temperature_resolution"]["spoolman_id"] = 10  # set for another spool: resolved again
    assert slice_inputs.slice("flashforge.ad5x", state)[:2] == (nozzle_effective("flashforge.ad5x", 220), 60)


def test_unknown_material_refuses_rather_than_slicing_at_pla_temperatures(slice_inputs):
    with pytest.raises((RuntimeError, ValueError), match="(?i)unsupported filament material"):
        slice_inputs.slice("flashforge.ad5x", stale_state("NoPLA+"))


# Verification checks a G-code against its own spool's temperatures, resolved the way the slice
# resolved them. Against the printer-wide record a correct 220 °C Silk slot job would be refused.

def slot_job_state():
    state = stale_state("PLA", spool_id=10)
    state["filament_slots"] = {"1": {"spoolman_id": 10, "material": "PLA", "hex": "FFFFFF",
                                     "physical_color_verified": True},
                               "2": {"spoolman_id": 17, "material": "Silk PLA", "hex": "0C6283",
                                     "physical_color_verified": True}}
    return state


def test_gcode_temperatures_resolve_for_the_slot_spool_the_gcode_names():
    from print_handy.core import printer_state
    state = slot_job_state()
    assert printer_state.gcode_temperatures(state, ["Silk PLA"]) == {"nozzle": 220, "bed": 60}
    assert printer_state.gcode_temperatures(state, ["PLA"]) == {"nozzle": 210, "bed": 60}
    fetched = {17: {"material": "Silk PLA", "settings_extruder_temp": 205, "settings_bed_temp": 55}}
    assert printer_state.gcode_temperatures(state, ["Silk PLA"], fetched.get) == {"nozzle": 205, "bed": 55}


def test_two_slots_of_one_material_with_different_temperatures_refuse():
    from print_handy.core import printer_state
    state = slot_job_state()
    state["filament_slots"]["3"] = {"spoolman_id": 18, "material": "Silk PLA", "hex": "AA0000",
                                    "physical_color_verified": True}
    fetched = {17: {"material": "Silk PLA", "settings_extruder_temp": 205},
               18: {"material": "Silk PLA", "settings_extruder_temp": 225}}
    with pytest.raises(RuntimeError, match="different temperatures"):
        printer_state.gcode_temperatures(state, ["Silk PLA"], fetched.get)


def gcode_at(tmp_path, nozzle, material="Silk PLA"):
    path = tmp_path / f"job_{nozzle}.gcode"
    path.write_text(f"M190 S60\nM104 S{nozzle} T0\nSTART_PRINT BED_TEMP=60 EXTRUDER_TEMP={nozzle} MESH=auto\n"
                    "G90\nG1 X10 Y10 Z0.2 E1\nEND_PRINT\n"
                    f'; filament_type = "{material}"\n; nozzle_diameter = 0.4\n')
    return path


def operator_record():
    """The AD5X record as it was on 2026-10-31: no temperature_resolution at all, an active
    spool with no Spoolman id whose material is Silk PLA, temps_c 210/60, and Silk PLA spool 17
    in IFS slot 2. Slicing swapped to slot 2; verification must agree with that slice."""
    state = copy.deepcopy(json.loads(STATE.read_text()))
    state.pop("temperature_resolution", None)
    state["temps_c"] = {"nozzle": 210, "bed": 60}
    state["spool"] = {**state["spool"], "spoolman_id": None, "name": "Rose red blue green", "material": "Silk PLA"}
    state["filament_slots"] = {"1": {"spoolman_id": 16, "material": "Pla", "hex": "FFFFFF", "physical_color_verified": True},
                               "2": {"spoolman_id": 17, "material": "Silk PLA", "hex": "0C6283", "physical_color_verified": True},
                               "3": {"spoolman_id": 15, "material": "PLA+", "hex": "161616", "physical_color_verified": True},
                               "4": {"spoolman_id": 12, "material": "PLA", "hex": "067749", "physical_color_verified": True}}
    return state


def test_the_operator_record_slices_slot_2_silk_at_220_and_verifies_it(slice_inputs, tmp_path, monkeypatch):
    from print_handy.core import model_job, printer_state
    slice_inputs.spools[17] = {"id": 17, "filament": {"material": "Silk PLA", "settings_extruder_temp": None,
                                                      "settings_bed_temp": None}}
    state = operator_record()
    nozzle, bed, _ = slice_inputs.slice("flashforge.ad5x", state, filament_slot=2)
    assert (nozzle, bed) == (nozzle_effective("flashforge.ad5x", 220), 60)
    assert printer_state.gcode_temperatures(state, ["Silk PLA"]) == {"nozzle": 220, "bed": 60}
    monkeypatch.setattr(model_job.printers, "current", lambda: adapter_for("flashforge.ad5x"))
    state["nozzle"] = {**state.get("nozzle", {}), "type": "brass", "diameter_mm": 0.4}
    for gcode_nozzle, ok in ((220, True), (210, False)):
        try:
            model_job.verify_gcode_offline(gcode_at(tmp_path, gcode_nozzle), state)
            message = ""
        except RuntimeError as exc:
            message = str(exc)
        assert ("START_PRINT matching" not in message) is ok, (gcode_nozzle, message)


@pytest.mark.parametrize("nozzle,ok", [(220, True), (210, False)])
def test_offline_verification_checks_the_slot_job_at_its_own_temperature(tmp_path, monkeypatch, nozzle, ok):
    from print_handy.core import model_job
    monkeypatch.setattr(model_job.printers, "current", lambda: adapter_for("flashforge.ad5x"))
    monkeypatch.setattr(spoolman_client, "get_spool", lambda sid, **k: None)
    state = slot_job_state()
    state["nozzle"] = {**state.get("nozzle", {}), "type": "brass", "diameter_mm": 0.4}
    try:
        model_job.verify_gcode_offline(gcode_at(tmp_path, nozzle), state)
        message = ""
    except RuntimeError as exc:
        message = str(exc)
    temperature_errors = [m for m in ("startup heater prefix", "START_PRINT matching") if m in message]
    assert (temperature_errors == []) is ok, message


def test_bare_seeded_pla_default_does_not_hold_for_the_active_silk_spool():
    """Live AD5X 2026-10-31 (Print #64): active spool IS slot 2 Silk PLA #17, temps_c 210/60 with no
    temperature_resolution (the seeded PLA default). It must resolve to Silk's 220, not slice at 210."""
    from print_handy.core import printer_state
    state = operator_record()
    state["spool"] = {**state["spool"], "spoolman_id": 17}
    temps, resolution = printer_state.slice_temperatures(state)
    assert temps == {"nozzle": 220, "bed": 60}
    assert resolution["material"] == "Silk PLA"


def test_bare_explicit_legacy_temperatures_still_hold():
    from print_handy.core import printer_state
    state = operator_record()
    state["spool"] = {**state["spool"], "spoolman_id": 17}
    state["temps_c"] = {"nozzle": 225, "bed": 55}
    assert printer_state.slice_temperatures(state)[0] == {"nozzle": 225, "bed": 55}
