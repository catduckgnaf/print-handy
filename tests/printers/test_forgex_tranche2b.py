"""Forge-X per-print timelapse skip (#1506 tranche 2b), offline.

START_PRINT TIMELAPSE=0 skips the printer's native timelapse for one print;
the beta's START_PRINT refuses any value but 0 or 1 (config/stock.cfg in
ff5m 1.4.2, read for behavior only). The default leaves the file alone.
"""
import pytest

from print_handy import printers, settings
from print_handy.printers.flashforge_forgex import start_contract as sc

from .test_adapters import a1_fixture

KEYS = ("flashforge_forgex.ad5m", "flashforge_forgex.ad5m_pro")
SLICED = ("; generated by OrcaSlicer 2.3.1\n"
          "SET_PRINT_STATS_INFO TOTAL_LAYER=120\n"
          "START_PRINT EXTRUDER_TEMP=220 BED_TEMP=60\n"
          "G1 X10 Y10\n")


def _load(key, **env):
    return settings.load(local=False, environ={
        "PRINT_HANDY__PRINTER__MODEL": key,
        "PRINT_HANDY__PATHS__STATE_HOME": str(a1_fixture.HERMES), **env})


def test_skip_adds_timelapse_zero_to_the_one_start_line():
    out = sc.with_timelapse_skip(SLICED)
    assert "START_PRINT EXTRUDER_TEMP=220 BED_TEMP=60 TIMELAPSE=0\n" in out
    assert out.count("START_PRINT") == 1
    assert out.replace(" TIMELAPSE=0", "") == SLICED


@pytest.mark.parametrize("text,word", [
    ("G1 X1\n", "found 0"),
    (SLICED + "START_PRINT EXTRUDER_TEMP=220 BED_TEMP=60\n", "found 2"),
    (SLICED.replace("BED_TEMP=60", "BED_TEMP=60 TIMELAPSE=1"), "already names TIMELAPSE"),
])
def test_ambiguous_files_are_refused(text, word):
    with pytest.raises(ValueError, match=word):
        sc.with_timelapse_skip(text)


@pytest.mark.parametrize("value", ["on", "OFF", "", 0, True])
def test_bad_values_are_refused(value):
    with pytest.raises(ValueError, match="forgex_timelapse"):
        sc.timelapse_choice({"forgex_timelapse": value})


@pytest.mark.parametrize("key", KEYS)
def test_adapter_default_leaves_the_file_alone(key):
    adapter = printers.get(key, _load(key))
    assert adapter.finalize_output(SLICED) == SLICED


@pytest.mark.parametrize("key", KEYS)
def test_adapter_off_skips_the_timelapse(key):
    adapter = printers.get(key, _load(key, PRINT_HANDY__PRINTER__FORGEX_TIMELAPSE="off"))
    out = adapter.finalize_output(SLICED)
    assert "TIMELAPSE=0" in out
    assert not sc.forbidden_params(next(l for l in out.splitlines() if l.startswith("START_PRINT")))


def test_settings_refuse_off_on_other_firmware_and_accept_the_default_anywhere():
    _load("flashforge.ad5x", PRINT_HANDY__PRINTER__FORGEX_TIMELAPSE="printer")
    with pytest.raises(settings.SettingsError, match="only applies to Flashforge printers on Forge-X"):
        _load("flashforge.ad5x", PRINT_HANDY__PRINTER__FORGEX_TIMELAPSE="off")
    with pytest.raises(settings.SettingsError, match="forgex_timelapse"):
        _load(KEYS[0], PRINT_HANDY__PRINTER__FORGEX_TIMELAPSE="maybe")
