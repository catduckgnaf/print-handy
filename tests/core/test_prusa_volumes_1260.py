"""#1260: PrusaSlicer modifier, negative and support volumes are never printed as solid plastic.

PrusaSlicer writes each object as one mesh holding the triangles of all its
volumes; Metadata/Slic3r_PE_model.config marks each volume's triangle range
(<volume firstid lastid>) and its volume_type (ModelPart, ParameterModifier,
NegativeVolume, SupportBlocker, SupportEnforcer; older files only a modifier
flag). Nothing read the ranges, so inventory returned one part per object and
every export wrote every triangle as solid geometry: a modifier or support
blocker printed as plastic, a negative volume printed instead of being
subtracted.

Now inventory splits those ranges: the object's part keeps its key (no color
question changes, the #1203 rule) restricted to its model-part triangles, and
each other volume becomes a cutter row like a Bambu/Orca modifier_part or
negative_part. The rebuilt exports write it as a typed volume; a path that
cannot carry it (the single-color plate copy, the slice-time adoption of a
PrusaSlicer model config) refuses by name. All sources are built here; no
third-party files.
"""
import json
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

import pytest

from print_handy.core import model_job, orca_adapter, painted_geometry, source_colors as sc
from print_handy.core.color_geometry import export_color_geometry, export_single_color_plate
from tests.corpus.make_models import _write_package

NS = "http://schemas.microsoft.com/3dmanufacturing/core/2015/02"
STATE = Path(__file__).parents[1] / "pipeline" / "fixtures" / "printer_hardware.json"
CONFIG = "Metadata/Slic3r_PE_model.config"
_PRUSA = ("; generated by PrusaSlicer 2.8.0\n; filament_colour = #FF0000;#00FF00;#0000FF\n"
          "; extruder_colour = #FF0000;#00FF00;#0000FF\n; filament_type = PLA;PLA;PLA\n"
          "; perimeter_extruder = 1\n; infill_extruder = 1\n; solid_infill_extruder = 1\n"
          "; support_material_extruder = 0\n; support_material_interface_extruder = 0\n")
KINDS = {"ParameterModifier": "modifier_part", "NegativeVolume": "negative_part",
         "SupportBlocker": "support_blocker", "SupportEnforcer": "support_enforcer"}


def _box(dx, dy, dz, offset=(0.0, 0.0, 0.0), base=0, paint=None):
    ox, oy, oz = offset
    v = [(ox, oy, oz), (ox + dx, oy, oz), (ox + dx, oy + dy, oz), (ox, oy + dy, oz),
         (ox, oy, oz + dz), (ox + dx, oy, oz + dz), (ox + dx, oy + dy, oz + dz), (ox, oy + dy, oz + dz)]
    faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
             (2, 3, 7), (2, 7, 6), (1, 2, 6), (1, 6, 5), (3, 0, 4), (3, 4, 7)]
    attr = f' slic3rpe:mmu_segmentation="{paint}"' if paint else ""
    verts = "".join(f'<vertex x="{x}" y="{y}" z="{z}"/>' for x, y, z in v)
    tris = "".join(f'<triangle v1="{a + base}" v2="{b + base}" v3="{c + base}"{attr}/>'
                   for a, b, c in faces)
    return verts, tris


def _volume(first, last, name, *, kind=None, modifier=None, extruder=None, extra=""):
    meta = f'<metadata type="volume" key="name" value="{name}"/>'
    if modifier is not None:
        meta += f'<metadata type="volume" key="modifier" value="{modifier}"/>'
    if kind is not None:
        meta += f'<metadata type="volume" key="volume_type" value="{kind}"/>'
    if extruder is not None:
        meta += f'<metadata type="volume" key="extruder" value="{extruder}"/>'
    ids = (f' firstid="{first}"' if first is not None else "") + (f' lastid="{last}"' if last is not None else "")
    return f'<volume{ids}>{meta}{extra}</volume>'


def prusa_volume_source(path, volume, *, cap=False, body_paint=None, volume_paint=None,
                        model_config=None, prusa_config=True):
    """One PrusaSlicer object "Sign": a 20 mm body (triangles 0-11) and a 6 mm volume
    (triangles 12-23) in the same mesh, the volume sticking 3 mm out of the body's +X/+Y/+Z
    corner. cap adds a second object "Cap" on extruder 2, so a color question maps filament 2.
    """
    body_v, body_t = _box(20, 20, 20, paint=body_paint)
    vol_v, vol_t = _box(6, 6, 6, offset=(17.0, 17.0, 17.0), base=8, paint=volume_paint)
    mesh = f"<mesh><vertices>{body_v}{vol_v}</vertices><triangles>{body_t}{vol_t}</triangles></mesh>"
    objects = f'<object id="1" type="model">{mesh}</object>'
    items = '<item objectid="1" transform="1 0 0 0 1 0 0 0 1 50 50 0"/>'
    config_objects = ('<object id="1" instances_count="1"><metadata type="object" key="name" value="Sign"/>'
                      '<metadata type="object" key="extruder" value="1"/>'
                      f'{_volume(0, 11, "Sign body", kind="ModelPart")}{volume}</object>')
    if cap:
        cap_v, cap_t = _box(10, 10, 10)
        objects += f'<object id="2" type="model"><mesh><vertices>{cap_v}</vertices><triangles>{cap_t}</triangles></mesh></object>'
        items += '<item objectid="2" transform="1 0 0 0 1 0 0 0 1 120 50 0"/>'
        config_objects += ('<object id="2" instances_count="1"><metadata type="object" key="name" value="Cap"/>'
                           '<metadata type="object" key="extruder" value="2"/>'
                           f'{_volume(0, 11, "Cap", kind="ModelPart")}</object>')
    model = ('<?xml version="1.0" encoding="UTF-8"?>'
             f'<model unit="millimeter" xmlns="{NS}" '
             'xmlns:slic3rpe="http://schemas.slic3r.org/3mf/2017/06">'
             f'<resources>{objects}</resources><build>{items}</build></model>')
    files = {"3D/3dmodel.model": model,
             CONFIG: model_config if model_config is not None else
             f'<?xml version="1.0" encoding="UTF-8"?><config>{config_objects}</config>'}
    if prusa_config:
        files["Metadata/Slic3r_PE.config"] = _PRUSA
    _write_package(path, files)
    return path


