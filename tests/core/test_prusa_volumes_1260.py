def test_slice_adoption_types_a_component_volume(tmp_path):
    # Volumes stored as separate component meshes match in order: the
    # modifier keeps its type in the converted model settings.
    body_v, body_t = _box(20, 20, 20)
    band_v, band_t = _box(6, 6, 6, offset=(17.0, 17.0, 17.0))
    model = ('<?xml version="1.0" encoding="UTF-8"?>'
             f'<model unit="millimeter" xmlns="{NS}"><resources>'
             f'<object id="2" type="model"><mesh><vertices>{body_v}</vertices><triangles>{body_t}</triangles></mesh></object>'
             f'<object id="3" type="model"><mesh><vertices>{band_v}</vertices><triangles>{band_t}</triangles></mesh></object>'
             '<object id="1" type="model"><components><component objectid="2"/><component objectid="3"/>'
             '</components></object></resources><build><item objectid="1"/></build></model>')
    config = ('<?xml version="1.0" encoding="UTF-8"?><config><object id="1">'
              '<metadata type="object" key="name" value="Sign"/>'
              f'{_volume(0, 11, "Sign body", kind="ModelPart")}'
              f'{_volume(12, 23, "Band", kind="ParameterModifier")}</object></config>')
    path = tmp_path / "components.3mf"
    _write_package(path, {"3D/3dmodel.model": model, CONFIG: config, "Metadata/Slic3r_PE.config": _PRUSA})
    manifest = sc.inventory(path)
    assert [p["key"] for p in manifest["parts"]] == ["build:0/0"]
    assert [(c["key"], c["subtype"]) for c in manifest["cutters"]] == [("build:0/1", "modifier_part")]
    root = ET.fromstring(orca_adapter._prusa_model_settings(config.encode(), model.encode(), {}))
    assert [(p.get("id"), p.get("subtype")) for p in root.iter("part")] == [
        ("2", "normal_part"), ("3", "modifier_part")]
    assert len(orca_adapter._parse_3mf_triangles(path)) == 12
    report = orca_adapter.export_geometry(path, tmp_path / "geometry.3mf")
    assert report["volumes"] == {"normal_part": 1, "modifier_part": 1}


