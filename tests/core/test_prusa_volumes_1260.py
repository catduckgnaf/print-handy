@pytest.mark.parametrize("kind", sorted(KINDS))
def test_export_geometry_writes_the_volume_typed_never_solid(tmp_path, kind):
    path = prusa_volume_source(tmp_path / "sign.3mf", _volume(12, 23, "Band", kind=kind))
    target = tmp_path / "geometry.3mf"
    report = orca_adapter.export_geometry(path, target)
    assert report["volumes"] == {"normal_part": 1, KINDS[kind]: 1}
    parts = _parts(target)
    subtype, triangles, vertices, xs, _meta = parts["Object 1"]
    assert (subtype, triangles, vertices) == ("normal_part", 12, 8)
    subtype, triangles, vertices, _xs, _meta = parts["Band"]
    assert (subtype, triangles, vertices) == (KINDS[kind], 12, 8)
    # Placement is the body's: the volume sticking out does not move the bed center.
    assert report["build_bounds_mm"][0] == (50.0, 70.0)
    assert max(xs) - min(xs) == pytest.approx(20.0)


