@pytest.mark.parametrize("kind", sorted(KINDS))
def test_prusa_non_model_volume_is_a_cutter_row_never_a_part_or_question(tmp_path, kind):
    path = prusa_volume_source(tmp_path / "sign.3mf", _volume(12, 23, "Band", kind=kind, extruder="1"))
    manifest = sc.inventory(path)
    [part] = manifest["parts"]
    assert part["key"] == "build:0" and part["triangle_ranges"] == [[0, 11]]
    [cutter] = manifest["cutters"]
    assert cutter["subtype"] == KINDS[kind] and cutter["name"] == "Band"
    assert cutter["key"] == "build:0/volume1" and cutter["triangle_ranges"] == [[12, 23]]
    # Same questions as the project without the volume (#1203).
    assert _question_keys(manifest) == _question_keys(sc.inventory(body_only_source(tmp_path / "b.3mf")))


def test_old_prusa_modifier_flag_is_a_modifier_cutter(tmp_path):
    path = prusa_volume_source(tmp_path / "sign.3mf", _volume(12, 23, "Band", modifier="1"))
    [cutter] = sc.inventory(path)["cutters"]
    assert cutter["subtype"] == "modifier_part"


def test_prusa_modifier_extruder_a_question_maps_is_known_usage(tmp_path):
    # The Cap prints filament 2, so a question maps it: the modifier's region
    # is carried by the rebuilt export and counts as used filament 2.
    path = prusa_volume_source(tmp_path / "sign.3mf",
                               _volume(12, 23, "Band", kind="ParameterModifier", extruder="2"), cap=True)
    manifest = sc.inventory(path)
    [cutter] = manifest["cutters"]
    assert cutter["modifier_extruder"] == 2
    entry = manifest["plate_usage"]["1"]
    assert entry["classes"]["modifiers"]["status"] == "known"
    assert entry["classes"]["modifiers"]["source_filaments"] == [2]
    assert entry["usage_known"]
    assert _question_keys(manifest) == _question_keys(sc.inventory(body_only_source(tmp_path / "b.3mf", cap=True)))


def test_prusa_modifier_extruder_no_question_maps_stays_unknown_never_a_question(tmp_path):
    path = prusa_volume_source(tmp_path / "sign.3mf",
                               _volume(12, 23, "Band", kind="ParameterModifier", extruder="3"), cap=True)
    manifest = sc.inventory(path)
    entry = manifest["plate_usage"]["1"]
    assert entry["classes"]["modifiers"]["status"] == "unknown"
    assert "'Band' (object 1) names extruder 3" in entry["classes"]["modifiers"]["reason"]
    assert 3 not in entry["source_filaments"]
    assert _question_keys(manifest) == _question_keys(sc.inventory(body_only_source(tmp_path / "b.3mf", cap=True)))


def test_painted_body_counts_only_its_own_triangles(tmp_path):
    # The volume's triangles carry paint state 2; the body is unpainted. The
    # body's paint census must not include the modifier's triangles.
    path = prusa_volume_source(tmp_path / "sign.3mf", _volume(12, 23, "Band", kind="ParameterModifier"),
                               volume_paint="8")
    manifest = sc.inventory(path)
    [part] = manifest["parts"]
    assert painted_geometry.leaf_states(path, part) == {"states": {}, "unpainted": 12}
    [cutter] = manifest["cutters"]
    assert painted_geometry.leaf_states(path, cutter) == {"states": {2: 12}, "unpainted": 0}


@pytest.mark.parametrize("volume, words", [
    (_volume(None, None, "Band", kind="NegativeVolume"), "no valid triangle range"),
    (_volume(12, 20, "Band", kind="NegativeVolume"), "cover 21 triangles but its mesh has 24"),
    (_volume(10, 23, "Band", kind="NegativeVolume"), "do not cover its mesh exactly once"),
    (_volume(12, 23, "Band", kind="TextVolume"), "volume type 'TextVolume'"),
], ids=["no-range", "short-range", "overlapping-range", "unknown-type"])
def test_a_volume_that_cannot_be_split_exactly_is_refused_by_name(tmp_path, volume, words):
    path = prusa_volume_source(tmp_path / "sign.3mf", volume)
    with pytest.raises(RuntimeError, match="PrusaSlicer object 1") as caught:
        sc.inventory(path)
    assert words in str(caught.value)


