"""#1155: PrusaSlicer modifier volumes and same-extruder height ranges in plate usage.

- PrusaSlicer stores a modifier as a triangle range (a <volume> with
  volume_type ParameterModifier) of its object's one mesh in
  Metadata/Slic3r_PE_model.config. Inventory does not split that mesh, so a
  modifier that names its own extruder was never detected: the plate claimed
  "known, nothing extra" while the source prints that region in another
  filament. It is now UNKNOWN usage with the reason (a warning to accept),
  never a used filament and never a new color question (the #1203 rule).
- A PrusaSlicer height range that names its object's own extruder changes no
  filament, but was reported unknown (review finding on #1238).
"""
import re
import zipfile

import pytest

from print_handy.core import source_colors as sc
from tests.core.test_usage_reads_1155 import (NS, PRUSA_RANGES, _box, _part_keys, _question_keys,
                                              _ranges)
from tests.corpus.make_models import _write_package

_CONFIG = ("; generated by PrusaSlicer 2.8.0\n; filament_colour = #FF0000;#00FF00;#0000FF\n"
           "; extruder_colour = #FF0000;#00FF00;#0000FF\n; filament_type = PLA;PLA;PLA\n"
           "; perimeter_extruder = 1\n; infill_extruder = 1\n; solid_infill_extruder = 1\n"
           "; support_material_extruder = 0\n; support_material_interface_extruder = 0\n")


def _volume(first, last, name, *, kind=None, modifier=None, extruder=None):
    meta = f'<metadata type="volume" key="name" value="{name}"/>'
    if modifier is not None:
        meta += f'<metadata type="volume" key="modifier" value="{modifier}"/>'
    if kind is not None:
        meta += f'<metadata type="volume" key="volume_type" value="{kind}"/>'
    if extruder is not None:
        meta += f'<metadata type="volume" key="extruder" value="{extruder}"/>'
    return f'<volume firstid="{first}" lastid="{last}">{meta}</volume>'


def prusa_modifier_source(path, modifier, *, object_extruder="1", members=None):
    """One PrusaSlicer object: a body (triangles 0-11) plus one volume (12-23) in the same mesh."""
    body, band = _box(20, 20, 20), _box(4, 4, 4, offset=(8.0, 8.0, 8.0))
    # Merge the two boxes into one mesh, as PrusaSlicer writes an object.

    verts = re.findall(r'<vertex [^>]*/>', body) + re.findall(r'<vertex [^>]*/>', band)
    tris = re.findall(r'<triangle [^>]*/>', body)
    tris += [re.sub(r'v(\d)="(\d+)"', lambda m: f'v{m.group(1)}="{int(m.group(2)) + 8}"', t)
             for t in re.findall(r'<triangle [^>]*/>', band)]
    mesh = f'<mesh><vertices>{"".join(verts)}</vertices><triangles>{"".join(tris)}</triangles></mesh>'
    model = ('<?xml version="1.0" encoding="UTF-8"?>'
             f'<model unit="millimeter" xmlns="{NS}"><resources><object id="1" type="model">{mesh}'
             '</object></resources><build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 50 50 0"/>'
             '</build></model>')
    own = (f'<metadata type="object" key="extruder" value="{object_extruder}"/>'
           if object_extruder is not None else '')
    model_config = ('<?xml version="1.0" encoding="UTF-8"?><config><object id="1" instances_count="1">'
                    f'<metadata type="object" key="name" value="Sign"/>{own}'
                    f'{_volume(0, 11, "Sign", kind="ModelPart")}{modifier}</object></config>')
    _write_package(path, {"3D/3dmodel.model": model, "Metadata/Slic3r_PE.config": _CONFIG,
                          "Metadata/Slic3r_PE_model.config": model_config, **(members or {})})
    return path


def test_prusa_modifier_volume_with_its_own_extruder_is_unknown_never_a_question(tmp_path):
    path = prusa_modifier_source(tmp_path / "sign.3mf",
                                 _volume(12, 23, "Band", kind="ParameterModifier", modifier="1",
                                         extruder="2"))
    manifest = sc.inventory(path)
    entry = manifest["plate_usage"]["1"]
    modifiers = entry["classes"]["modifiers"]
    assert modifiers["status"] == "unknown"
    assert "'Band' (object 1) names extruder 2" in modifiers["reason"]
    assert not entry["usage_known"]
    assert 2 not in entry["source_filaments"]
    assert _question_keys(manifest) == _part_keys(manifest)
    assert sc.filament_readiness_warnings(manifest, {}, ["1"])


def test_old_prusa_modifier_flag_without_volume_type_is_read(tmp_path):
    path = prusa_modifier_source(tmp_path / "sign.3mf",
                                 _volume(12, 23, "Band", modifier="1", extruder="3"))
    entry = sc.inventory(path)["plate_usage"]["1"]
    assert entry["classes"]["modifiers"]["status"] == "unknown"
    assert "names extruder 3" in entry["classes"]["modifiers"]["reason"]


@pytest.mark.parametrize("extruder", [None, "0", "1"])
def test_prusa_modifier_inheriting_or_repeating_the_object_extruder_changes_nothing(tmp_path, extruder):
    path = prusa_modifier_source(tmp_path / "sign.3mf",
                                 _volume(12, 23, "Band", kind="ParameterModifier", modifier="1",
                                         extruder=extruder))
    entry = sc.inventory(path)["plate_usage"]["1"]
    assert entry["classes"]["modifiers"]["status"] == "known"
    assert entry["usage_known"]


def test_an_object_with_no_extruder_prints_extruder_1_for_the_modifier_comparison(tmp_path):
    same = prusa_modifier_source(tmp_path / "same.3mf",
                                 _volume(12, 23, "Band", kind="ParameterModifier", extruder="1"),
                                 object_extruder=None)
    other = prusa_modifier_source(tmp_path / "other.3mf",
                                  _volume(12, 23, "Band", kind="ParameterModifier", extruder="2"),
                                  object_extruder=None)
    assert sc.inventory(same)["plate_usage"]["1"]["usage_known"]
    assert not sc.inventory(other)["plate_usage"]["1"]["usage_known"]


@pytest.mark.parametrize("kind", ["NegativeVolume", "SupportBlocker", "SupportEnforcer"])
def test_non_modifier_volumes_are_not_read_as_modifiers(tmp_path, kind):
    path = prusa_modifier_source(tmp_path / "sign.3mf", _volume(12, 23, "Other", kind=kind, extruder="2"))
    assert sc.inventory(path)["plate_usage"]["1"]["classes"]["modifiers"]["status"] == "known"


def test_an_unparsable_prusa_model_config_makes_modifiers_unknown(tmp_path):
    path = prusa_modifier_source(tmp_path / "sign.3mf", "")

    broken = tmp_path / "broken.3mf"
    with zipfile.ZipFile(path) as src, zipfile.ZipFile(broken, "w") as out:
        for name in src.namelist():
            data = src.read(name)
            out.writestr(name, b"<config><object" if name == "Metadata/Slic3r_PE_model.config" else data)
    entry = sc.inventory(broken)["plate_usage"]["1"]
    assert entry["classes"]["modifiers"]["status"] == "unknown"
    assert "could not be parsed" in entry["classes"]["modifiers"]["reason"]


def test_prusa_height_range_naming_the_objects_own_extruder_stays_known(tmp_path):
    path = prusa_modifier_source(tmp_path / "sign.3mf", "", object_extruder="2",
                                 members={PRUSA_RANGES: _ranges(2)})
    entry = sc.inventory(path)["plate_usage"]["1"]
    assert entry["classes"]["height_ranges"]["status"] == "known"
    other = prusa_modifier_source(tmp_path / "other.3mf", "", object_extruder="2",
                                  members={PRUSA_RANGES: _ranges(3)})
    assert sc.inventory(other)["plate_usage"]["1"]["classes"]["height_ranges"]["status"] == "unknown"
