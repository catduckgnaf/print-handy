def classify_domain_term(term: str) -> str | None:
    """Classify a 3D-printing domain term into its category, or None if unknown.

    Checks canonical domain vocabulary, known aliases, single-token typos,
    and compound forms across the 8 domain categories: models, slicer,
    defects, materials, colors, hardware, habits, and commands.
    """
    if not term or not isinstance(term, str):
        return None
    cleaned = term.strip().lower()
    if not cleaned:
        return None
    if cleaned in _DOMAIN_ALIAS_TO_CATEGORY:
        return _DOMAIN_ALIAS_TO_CATEGORY[cleaned]
    folded = TYPO_FORMS.get(cleaned, cleaned)
    if folded in _DOMAIN_ALIAS_TO_CATEGORY:
        return _DOMAIN_ALIAS_TO_CATEGORY[folded]
    token_val = TOKEN_FORMS.get(cleaned) or TOKEN_FORMS.get(folded)
    if token_val:
        token_clean = token_val.strip().lower()
        if token_clean in _DOMAIN_ALIAS_TO_CATEGORY:
            return _DOMAIN_ALIAS_TO_CATEGORY[token_clean]
    for category, vocab in DOMAIN_CATEGORIES.items():
        if cleaned in vocab or folded in vocab:
            return category
    return None


def extract_domain_entities(text: str) -> dict[str, list[str]]:
    """Extract 3D-printing domain entities grouped by category from text.

    Scans text for canonical terms, compound phrases, and known aliases across
    the 8 domain categories. Returns a mapping from category name to an ordered,
    deduplicated list of recognized domain terms (e.g. {'models': ['benchy']}).
    """
    if not text or not isinstance(text, str):
        return {}
    tokens = [t for t in re.split(r"[^a-zA-Z0-9]+", text.lower()) if t]
    entities: dict[str, list[str]] = {}
    i = 0
    max_len = 4
    while i < len(tokens):
        matched = False
        for n in range(min(max_len, len(tokens) - i), 0, -1):
            phrase = " ".join(tokens[i:i + n])
            target_term = _DOMAIN_ALIAS_TO_TERM.get(phrase)
            cat = _DOMAIN_ALIAS_TO_CATEGORY.get(phrase)
            if not target_term and n == 1:
                single = tokens[i]
                folded = TYPO_FORMS.get(single, single)
                target_term = _DOMAIN_ALIAS_TO_TERM.get(folded)
                cat = _DOMAIN_ALIAS_TO_CATEGORY.get(folded)
                if not target_term:
                    token_val = TOKEN_FORMS.get(single) or TOKEN_FORMS.get(folded)
                    if token_val:
                        token_clean = token_val.strip().lower()
                        target_term = _DOMAIN_ALIAS_TO_TERM.get(token_clean)
                        cat = _DOMAIN_ALIAS_TO_CATEGORY.get(token_clean)
            if target_term and cat:
                entities.setdefault(cat, [])
                if target_term not in entities[cat]:
                    entities[cat].append(target_term)
                i += n
                matched = True
                break
        if not matched:
            i += 1
    return entities
