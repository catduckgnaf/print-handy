"""OrcaSlicer's vendor printer and filament profiles, flattened into one committed database (#1816).

Design record: docs/history/FILAMENT-TYPES-DESIGN.md, section 3 ("Slicing values come from the vendor's own
profile first") and section 6 (the database). The data lives in ``print_handy/data/orca_profiles/``:

    index.json          meta (Orca version and commit, source digest) and every printer preset
    <Vendor>.jsonl      one instantiable filament preset per line, its ``inherits`` chain resolved

It is generated by ``scripts/build_orca_profile_db.py`` from OrcaSlicer's ``resources/profiles`` tree at the
release ``docker/orca-prebuilt.sh`` pins, never edited by hand. The profiles are OrcaSlicer's (AGPL-3.0, the
same license as Print Handy; see NOTICE). A test fails when the database's Orca commit is not the pinned one,
and an Orca bump regenerates it and reports the changed values (``diff``).

This module builds, loads, compares and queries the database. ``resolve`` picks the vendor profile for one
printer, nozzle and filament type, in the design's order: the vendor's sub-type profile, then the vendor's
generic profile for the family. It returns None when the vendor has neither, and the caller keeps the library
generic (``filament_families.toml``). Nothing here changes a slice by itself.
"""
from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any, Iterable, Mapping

from . import filament_type

DATA_DIR = Path(__file__).resolve().parent.parent / "data" / "orca_profiles"
FORMAT = 1
LIBRARY_VENDOR = "OrcaFilamentLibrary"
# Keys that describe a preset rather than set a slicing value: kept on the record, not in ``values``.
_META_KEYS = frozenset({"name", "type", "from", "inherits", "instantiation", "setting_id", "filament_id",
                        "compatible_printers", "compatible_printers_condition", "filament_settings_id",
                        "include", "description", "renamed_from", "compatible_prints",
                        "compatible_prints_condition"})
# Flags that select a different vendor profile, so a profile carrying one is used only for a spool that has it
# (design section 5: a finish-only difference such as matte never changes the slice).
SLICE_FLAGS = frozenset({"high_speed", "silk", "plus"})
# The values the bump diff reports by default: the ones a print visibly depends on.
REPORT_KEYS = ("filament_type", "filament_flow_ratio", "nozzle_temperature", "nozzle_temperature_initial_layer",
               "filament_max_volumetric_speed", "hot_plate_temp", "textured_plate_temp", "fan_min_speed",
               "fan_max_speed", "pressure_advance", "slow_down_layer_time")


class ProfileDatabaseError(RuntimeError):
    """The Orca tree or the committed database is not in the shape this module reads."""


# ---------------------------------------------------------------------------------------------
# Building from an OrcaSlicer resources/profiles tree
# ---------------------------------------------------------------------------------------------

def _read_tree(profiles: Path, kind: str) -> dict[str, dict[str, dict[str, Any]]]:
    """vendor -> preset name -> the preset's own JSON, for one kind (machine or filament)."""
    out: dict[str, dict[str, dict[str, Any]]] = {}
    for vendor_dir in sorted(p for p in profiles.iterdir() if p.is_dir()):
        folder = vendor_dir / kind
        if not folder.is_dir():
            continue
        for path in sorted(folder.rglob("*.json")):
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError) as exc:
                raise ProfileDatabaseError(f"cannot read {path}: {exc}") from exc
            if not isinstance(data, dict):
                raise ProfileDatabaseError(f"{path} is not a JSON object")
            out.setdefault(vendor_dir.name, {})[str(data.get("name") or path.stem)] = data
    return out


def _flattener(tree: Mapping[str, Mapping[str, Mapping[str, Any]]]):
    """flat(vendor, name) -> (values with the inherits chain applied, chain of parent names), or None.

    A parent is looked up in the preset's own vendor first, then in OrcaFilamentLibrary, as Orca does.
    """
    library = tree.get(LIBRARY_VENDOR, {})
    cache: dict[tuple[str, str], tuple[dict[str, Any], list[str]] | None] = {}

    def flat(vendor: str, name: str, seen: tuple[str, ...] = ()):
        key = (vendor, name)
        if key in cache:
            return cache[key]
        if name in seen:
            raise ProfileDatabaseError(f"inherits cycle in {vendor}: {' -> '.join(seen + (name,))}")
        own = tree.get(vendor, {}).get(name)
        if own is None:
            own = library.get(name)
        if own is None:
            cache[key] = None
            return None
        parent = own.get("inherits")
        values: dict[str, Any] = {}
        chain: list[str] = []
        if parent:
            resolved = flat(vendor, str(parent), seen + (name,))
            if resolved is None:
                raise ProfileDatabaseError(f"{vendor} preset {name!r} inherits missing {parent!r}")
            values, chain = dict(resolved[0]), [str(parent)] + resolved[1]
        values.update(own)
        cache[key] = (values, chain)
        return cache[key]

    return flat


def _instantiable(data: Mapping[str, Any]) -> bool:
    return str(data.get("instantiation", "")).lower() == "true"


def _first(value: Any) -> Any:
    return value[0] if isinstance(value, list) and value else value


def source_digest(profiles: Path) -> str:
    """SHA-256 over every machine and filament JSON file's path and bytes, in sorted order."""
    digest = hashlib.sha256()
    for path in sorted(profiles.glob("*/*/**/*.json")):
        rel = path.relative_to(profiles).as_posix()
        if rel.split("/")[1] not in ("machine", "filament"):
            continue
        digest.update(rel.encode() + b"\0" + path.read_bytes() + b"\0")
    return digest.hexdigest()


def build(profiles: Path, orca_version: str, orca_revision: str) -> dict[str, Any]:
    """The database for one Orca ``resources/profiles`` tree, as plain data (see ``write``)."""
    profiles = Path(profiles)
    if not profiles.is_dir():
        raise ProfileDatabaseError(f"{profiles} is not an Orca resources/profiles folder")
    machines, filaments = _read_tree(profiles, "machine"), _read_tree(profiles, "filament")
    flat_machine, flat_filament = _flattener(machines), _flattener(filaments)
    printers: dict[str, dict[str, Any]] = {}
    for vendor, presets in machines.items():
        for name, own in presets.items():
            if not _instantiable(own):
                continue
            values, _chain = flat_machine(vendor, name)
            raw = values.get("nozzle_diameter")
            # One entry per extruder; a multi-extruder preset may also pack them in one "0.4,0.4" string.
            entries = [part.strip() for item in (raw if isinstance(raw, list) else [raw]) if item not in (None, "")
                       for part in str(item).split(",") if part.strip()]
            nozzles = [float(part) for part in entries]
            printers[name] = {"vendor": vendor, "printer_model": values.get("printer_model"),
                              "variant": values.get("printer_variant"),
                              "nozzle_diameter": nozzles[0] if nozzles else None,
                              "extruders": len(nozzles)}
    vendors: dict[str, list[dict[str, Any]]] = {}
    for vendor, presets in filaments.items():
        for name, own in presets.items():
            if not _instantiable(own):
                continue
            values, chain = flat_filament(vendor, name)
            vendors.setdefault(vendor, []).append({
                "name": name,
                "filament_id": values.get("filament_id"),
                "setting_id": values.get("setting_id"),
                "inherits": chain,
                "compatible_printers": list(values.get("compatible_printers") or []),
                "condition": values.get("compatible_printers_condition") or None,
                "values": {k: v for k, v in sorted(values.items()) if k not in _META_KEYS},
            })
    for records in vendors.values():
        records.sort(key=lambda r: r["name"])
    meta = {"format": FORMAT, "orca_version": orca_version, "orca_revision": orca_revision,
            "source_digest": source_digest(profiles), "printer_presets": len(printers),
            "filament_presets": sum(len(r) for r in vendors.values()), "vendors": sorted(vendors),
            "own_brands": {v: b for v, b in sorted((v, own_brand(r)) for v, r in vendors.items()) if b}}
    return {"meta": meta, "printers": dict(sorted(printers.items())), "filaments": vendors}


def own_brand(records: Iterable[Mapping[str, Any]]) -> str | None:
    """The filament brand a vendor folder's own line uses, or None when the folder has no clear one.

    The brand rarely equals the folder name (Anker's line is "AnkerMake", BBL's "Bambu Lab", Prusa's
    "Prusa Polymers"), and folders also carry other brands' profiles (Flashforge has FusRock and SUNLU). A
    brand is the folder's own when it names at least half of the folder's non-generic profiles and at least
    three of them; a folder of only third-party profiles (Sovol's one Polymaker and one SUNLU) has none.
    """
    counts: dict[str, int] = {}
    total = 0
    for record in records:
        if record["name"].startswith("Generic "):
            continue
        brands = {str(b).strip() for b in record["values"].get("filament_vendor") or [] if str(b).strip()}
        if not brands:
            continue
        total += 1
        for brand in brands:
            counts[brand] = counts.get(brand, 0) + 1
    if not counts:
        return None
    brand, count = min(counts.items(), key=lambda item: (-item[1], item[0]))
    return brand if count >= 3 and count * 2 >= total and brand.casefold() not in ("generic", "other") else None


def _vendor_file(vendor: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9 ._-]*", vendor):
        raise ProfileDatabaseError(f"unexpected Orca vendor folder name {vendor!r}")
    return f"{vendor}.jsonl"


def render(db: Mapping[str, Any]) -> dict[str, str]:
    """The database's files, name -> text: index.json plus one JSON-lines file per vendor."""
    files = {}
    for vendor, records in db["filaments"].items():
        lines = [json.dumps(r, sort_keys=True, ensure_ascii=False, separators=(",", ":")) for r in records]
        files[_vendor_file(vendor)] = "\n".join(lines) + "\n"
    index = {"meta": db["meta"], "printers": db["printers"]}
    files["index.json"] = json.dumps(index, sort_keys=True, ensure_ascii=False, indent=1) + "\n"
    return files


def write(db: Mapping[str, Any], folder: Path = DATA_DIR) -> None:
    """Write ``render(db)`` into ``folder``; vendor files the database no longer has are removed."""
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    files = render(db)
    for name, text in files.items():
        (folder / name).write_text(text, encoding="utf-8", newline="\n")
    for stale in folder.glob("*.jsonl"):
        if stale.name not in files:
            stale.unlink()


def empty() -> dict[str, Any]:
    """A database with nothing in it (the 'before' side of a first generation)."""
    return {"meta": {"format": FORMAT, "orca_version": None, "orca_revision": None, "vendors": []},
            "printers": {}, "filaments": {}}


# ---------------------------------------------------------------------------------------------
# Loading the committed database
# ---------------------------------------------------------------------------------------------

@lru_cache(maxsize=4)
def index(folder: Path = DATA_DIR) -> dict[str, Any]:
    path = Path(folder) / "index.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ProfileDatabaseError(f"cannot read the Orca profile database index {path}: {exc}") from exc
    if (data.get("meta") or {}).get("format") != FORMAT:
        raise ProfileDatabaseError(f"{path} is format {(data.get('meta') or {}).get('format')!r}, "
                                   f"this code reads format {FORMAT}")
    return data


def meta(folder: Path = DATA_DIR) -> dict[str, Any]:
    return dict(index(folder)["meta"])


@lru_cache(maxsize=16)
def vendor_filaments(vendor: str, folder: Path = DATA_DIR) -> tuple[dict[str, Any], ...]:
    """Every instantiable filament preset in one Orca vendor folder (loaded on first use)."""
    path = Path(folder) / _vendor_file(vendor)
    if not path.is_file():
        return ()
    try:
        return tuple(json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip())
    except ValueError as exc:
        raise ProfileDatabaseError(f"cannot read {path}: {exc}") from exc


def load(folder: Path = DATA_DIR) -> dict[str, Any]:
    """The whole database in ``build``'s shape (for ``diff`` and tests; slicing uses the lazy readers)."""
    data = index(folder)
    return {"meta": data["meta"], "printers": data["printers"],
            "filaments": {v: list(vendor_filaments(v, folder)) for v in data["meta"]["vendors"]}}


def printer_preset(printer_model: str, nozzle_diameter: float, folder: Path = DATA_DIR) -> str | None:
    """The Orca machine preset name for a printer model and nozzle size, or None when Orca has none."""
    matches = sorted(name for name, p in index(folder)["printers"].items()
                     if p.get("printer_model") == printer_model and p.get("nozzle_diameter") is not None
                     and abs(float(p["nozzle_diameter"]) - float(nozzle_diameter)) < 1e-6)
    if len(matches) > 1:
        raise ProfileDatabaseError(f"Orca has {len(matches)} presets for {printer_model} with a "
                                   f"{nozzle_diameter:g} mm nozzle: {', '.join(matches)}")
    return matches[0] if matches else None


# ---------------------------------------------------------------------------------------------
# Resolving the vendor profile for one spool
# ---------------------------------------------------------------------------------------------

def value(values: Mapping[str, Any], key: str) -> Any:
    """A profile value as Orca reads it: the first entry of a list, with ``nil`` (inherit the machine's) as None."""
    raw = _first(values.get(key))
    return None if raw in (None, "", "nil") else raw


@dataclass(frozen=True)
class Resolution:
    """The vendor profile chosen for one spool, and why."""

    printer_preset: str
    name: str
    filament_id: str | None
    level: str  # "vendor sub-type" or "vendor generic"
    flags: frozenset[str]
    values: Mapping[str, Any] = field(repr=False)
    inherits: tuple[str, ...] = ()

    def get(self, key: str) -> Any:
        return value(self.values, key)


def _profile_type(record: Mapping[str, Any]) -> filament_type.FilamentType:
    return filament_type.from_orca_profile(value(record["values"], "filament_type"), record["name"])


def _brands(record: Mapping[str, Any]) -> set[str]:
    return {str(b).strip().casefold() for b in record["values"].get("filament_vendor") or [] if str(b).strip()}


def candidates(preset: str, family: str, brand: str | None = None, folder: Path = DATA_DIR) -> list[dict[str, Any]]:
    """The vendor folder's filament presets for ``preset`` and ``family`` that may serve a spool.

    That is the folder's generic profiles, its own line (``meta.own_brands``: the brand differs from the
    folder name, Anker's is AnkerMake), and, when the spool's ``brand`` is known, that brand's profiles.
    Another brand's profile in the folder (Flashforge's folder has SUNLU's) is never used for a spool of
    a different brand.
    """
    data = index(folder)
    printer = data["printers"].get(preset)
    if printer is None:
        return []
    vendor = printer["vendor"]
    allowed = {b.casefold() for b in (data["meta"].get("own_brands", {}).get(vendor), brand) if b}
    out = []
    for record in vendor_filaments(vendor, folder):
        if preset not in record["compatible_printers"]:
            continue
        if not (record["name"].startswith("Generic ") or _brands(record) & allowed):
            continue
        if _profile_type(record).family == family:
            out.append(record)
    return out


def resolve(preset: str, spool: filament_type.FilamentType, brand: str | None = None,
            folder: Path = DATA_DIR) -> Resolution | None:
    """The vendor profile a spool of this type (and, when known, ``brand``) is sliced with, or None.

    A profile qualifies when its slice-relevant flags (``SLICE_FLAGS``) are all on the spool: a high-speed
    profile is never used for a plain spool, and a plain generic still serves a high-speed spool when the
    vendor has no high-speed profile for this nozzle. Among qualifying profiles the most matching
    slice-relevant flags win, then the most matching finish flags, then the spool's own brand, then a
    "Generic" name for a flagless match and the vendor's own line for a flagged one, then the name (so the
    choice is deterministic).
    """
    if spool.family is None:
        return None
    spool_brand = brand.strip().casefold() if brand and brand.strip() else None
    ranked = []
    for record in candidates(preset, spool.family, brand, folder):
        ptype = _profile_type(record)
        flags = ptype.flags
        slice_flags = flags & SLICE_FLAGS
        extra = flags - spool.flags
        # A slice-relevant flag or an effect fill (marble, wood, glow) the spool lacks rules the profile out;
        # an extra finish only ranks it behind a profile without one.
        if extra & SLICE_FLAGS or any(filament_type._kind(f) == "effect" for f in extra):
            continue
        generic = record["name"].startswith("Generic ")
        prefer_generic = not slice_flags
        ranked.append(((-len(slice_flags), -len(flags & spool.flags - SLICE_FLAGS), len(extra),
                        0 if spool_brand and spool_brand in _brands(record) else 1,
                        0 if generic == prefer_generic else 1, len(ptype.unmapped), record["name"]), record, flags))
    if not ranked:
        return None
    _key, record, flags = min(ranked, key=lambda item: item[0])
    return Resolution(printer_preset=preset, name=record["name"], filament_id=record.get("filament_id"),
                      level="vendor sub-type" if flags & SLICE_FLAGS else "vendor generic",
                      flags=frozenset(flags), values=record["values"], inherits=tuple(record["inherits"]))


# ---------------------------------------------------------------------------------------------
# Comparing two databases (the Orca bump report)
# ---------------------------------------------------------------------------------------------

def diff(old: Mapping[str, Any], new: Mapping[str, Any], keys: Iterable[str] = REPORT_KEYS) -> dict[str, Any]:
    """What changed between two databases: printer presets and filament presets added or removed, and, per
    surviving filament preset, the ``keys`` whose value changed."""
    keys = tuple(keys)
    old_p, new_p = set(old["printers"]), set(new["printers"])

    def by_name(db):
        return {(v, r["name"]): r for v, records in db["filaments"].items() for r in records}

    old_f, new_f = by_name(old), by_name(new)
    changed = []
    for key in sorted(set(old_f) & set(new_f)):
        before, after = old_f[key]["values"], new_f[key]["values"]
        deltas = {k: (value(before, k), value(after, k)) for k in keys if value(before, k) != value(after, k)}
        printers_before, printers_after = set(old_f[key]["compatible_printers"]), set(new_f[key]["compatible_printers"])
        if deltas or printers_before != printers_after:
            changed.append({"vendor": key[0], "name": key[1], "values": deltas,
                            "printers_added": sorted(printers_after - printers_before),
                            "printers_removed": sorted(printers_before - printers_after)})
    return {"from": {k: old["meta"].get(k) for k in ("orca_version", "orca_revision")},
            "to": {k: new["meta"].get(k) for k in ("orca_version", "orca_revision")},
            "printers_added": sorted(new_p - old_p), "printers_removed": sorted(old_p - new_p),
            "filaments_added": [f"{v}/{n}" for v, n in sorted(set(new_f) - set(old_f))],
            "filaments_removed": [f"{v}/{n}" for v, n in sorted(set(old_f) - set(new_f))],
            "filaments_changed": changed}


def diff_markdown(report: Mapping[str, Any], limit: int = 400) -> str:
    """The bump PR's profile section: a readable summary of ``diff``."""
    lines = [f"### Orca profile database: {report['from']['orca_version']} -> {report['to']['orca_version']}", ""]
    for label, items in (("Printer presets added", report["printers_added"]),
                         ("Printer presets removed", report["printers_removed"]),
                         ("Filament presets added", report["filaments_added"]),
                         ("Filament presets removed", report["filaments_removed"])):
        lines.append(f"- {label}: {len(items)}" + (f" ({', '.join(items[:20])}{', ...' if len(items) > 20 else ''})"
                                                    if items else ""))
    changed = report["filaments_changed"]
    lines += ["", f"Filament presets with changed values: {len(changed)}", ""]
    if changed:
        lines += ["| Vendor | Profile | Change |", "| --- | --- | --- |"]
        for item in changed[:limit]:
            parts = [f"{k} {a} -> {b}" for k, (a, b) in item["values"].items()]
            if item["printers_added"]:
                parts.append("now also for " + ", ".join(item["printers_added"]))
            if item["printers_removed"]:
                parts.append("no longer for " + ", ".join(item["printers_removed"]))
            lines.append(f"| {item['vendor']} | {item['name']} | {'; '.join(parts)} |")
        if len(changed) > limit:
            lines.append(f"| ... | {len(changed) - limit} more | see the regenerated files |")
    return "\n".join(lines) + "\n"
