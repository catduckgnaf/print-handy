"""Bambu Lab HMS / print_error code lookup (#306).

The data (`hms_data.json`, generated by `scripts/bambu-hms.py` from Bambu Studio's own
`resources/hms/hms_en_<prefix>.json` files at the pinned commit recorded in the data's
`_provenance` block) maps Bambu's fault codes to concise descriptions. Print Handy's own
generator produced it; no third-party catalog is used (maziggy/bambuddy is AGPL — protocol
facts only; see docs/BAMBU-CONNECTIVITY.md).

Lookup discipline (from the #298 Stage 0 audit):
- The two key spaces are NEVER mixed: `hms[]` entries key on the 16-hex attr+code;
  `print_error` keys on its own 8-hex value. A lookup only ever consults its own space.
- A per-model text (keyed by the device prefix, e.g. the first three characters of the
  printer's serial as Bambu Studio names its files) wins over the common text. The
  H3C's prefix is 32X (recorded in facts.py from Bambu Studio's device definition
  for the model); its override sections arrive with the table regenerated from
  Bambu Studio 02.09.01.70, the first release carrying that prefix's files.
- "Listed with empty text" is distinct from "unlisted": Bambu lists some codes with no
  text, and those do not count as faults. `listed` says which case a result is.
- No severity is invented here: the alert level is part of Bambu's code structure, and
  this module reports text only.
"""
import json
from pathlib import Path

_DATA = None


def _data():
    global _DATA
    if _DATA is None:
        _DATA = json.loads((Path(__file__).parent / "hms_data.json").read_text())
    return _DATA


def prefixes():
    """The device prefixes the generated table carries per-model overrides for."""
    return tuple(_data()["_provenance"]["prefixes"])


class Lookup:
    """One decoded code. `listed` False = the code is not in Bambu's tables at all
    (unknown — report the raw code, never a guessed text). `text` "" with `listed`
    True = Bambu lists the code with no description (not a fault)."""

    __slots__ = ("key", "listed", "text")

    def __init__(self, key, listed, text):
        self.key = key
        self.listed = listed
        self.text = text

    @property
    def is_fault(self):
        """Counts as a fault: listed with a description, or unlisted (unknown stays a fault —
        an undecodable error must never be silently dropped). Listed-but-empty is not a fault."""
        return self.text != "" or not self.listed


def _hex(value, width):
    """Normalise an int or hex string to exactly `width` upper-case hex digits, else None."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return f"{value:0{width}X}" if 0 <= value < 16 ** width else None
    if isinstance(value, str):
        text = value.strip().upper()
        if text.startswith("0X"):
            text = text[2:]
        if len(text) == width and all(c in "0123456789ABCDEF" for c in text):
            return text
    return None


def hms_key(attr, code):
    """The 16-hex key for an `hms[]` entry's attr+code pair, or None when malformed."""
    a, c = _hex(attr, 8), _hex(code, 8)
    return a + c if a is not None and c is not None else None


def lookup_hms(key, model_prefix=None):
    """Decode a 16-hex HMS key. Strictly the HMS key space — an 8-hex value never resolves here."""
    if not isinstance(key, str) or len(key) != 16:
        return Lookup(key, False, None)
    data = _data()
    if model_prefix:
        overrides = data["hms_by_model"].get(str(model_prefix).upper()) or {}
        if key in overrides:
            return Lookup(key, True, overrides[key])
    if key in data["hms"]:
        return Lookup(key, True, data["hms"][key])
    return Lookup(key, False, None)


def lookup_error(value, model_prefix=None):
    """Decode a `print_error` value in its own 8-hex key space. A 16-hex HMS key never
    resolves here — the spaces are not interchangeable."""
    key = _hex(value, 8)
    if key is None:
        return Lookup(value, False, None)
    data = _data()
    if model_prefix:
        overrides = data["error_by_model"].get(str(model_prefix).upper()) or {}
        if key in overrides:
            return Lookup(key, True, overrides[key])
    if key in data["error"]:
        return Lookup(key, True, data["error"][key])
    return Lookup(key, False, None)


def decode_entry(entry, model_prefix=None):
    """Decode one `hms[]` report entry ({attr, code}) to a Lookup, or None when the entry
    carries no usable code pair at all."""
    if not isinstance(entry, dict):
        return None
    key = hms_key(entry.get("attr"), entry.get("code"))
    return lookup_hms(key, model_prefix) if key is not None else None
